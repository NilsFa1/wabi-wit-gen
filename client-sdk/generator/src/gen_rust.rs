//! Emits the *core-side* glue for a Rust core: plain Rust types, their payload
//! codec, a trait per resource that the core implements with idiomatic async
//! Rust, and the method-id dispatcher used by the generic FFI adapter.

use crate::ir::*;
use crate::names::*;


pub fn emit(m: &Model) -> String {
    let mut o = String::new();
    let (maj, min, pat) = m.version_triple();
    w!(o, "// @generated by acme-wit-gen from wit/*.wit — DO NOT EDIT.");
    w!(o, "#![allow(unused, clippy::all)]");
    w!(o, "use crate::ffi::host::{{self, AbiError, AbiStream, BoxFuture, ObjectRef}};");
    w!(o, "use crate::ffi::wire::{{Reader, WireError, Writer}};");
    w!(o, "use std::future::Future;");
    w!(o, "use std::sync::Arc;");
    w!(o, "");
    w!(o, "pub const CONTRACT_ID: &str = \"{}\";", m.contract_id());
    w!(o, "pub const CONTRACT_ID_C: &std::ffi::CStr = c\"{}\";", m.contract_id());
    w!(o, "pub const CONTRACT_VERSION: (u32, u32, u32) = ({maj}, {min}, {pat});");
    w!(o, "");
    w!(o, "/// Resource groups (high byte of method ids), pinned in abi-ids.lock.");
    w!(o, "pub mod groups {{");
    for r in &m.resources {
        w!(o, "    pub const {}: u32 = {:#04x};", screaming(&r.name), r.group);
    }
    w!(o, "}}");
    w!(o, "");
    w!(o, "/// Stable method ids, pinned in abi-ids.lock.");
    w!(o, "pub mod method_ids {{");
    for r in &m.resources {
        for f in r.ctor.iter().chain(&r.methods) {
            w!(o, "    pub const {}_{}: u32 = {:#06x};", screaming(&r.name), screaming(&f.name), f.id);
        }
    }
    w!(o, "}}");
    w!(o, "");

    for t in &m.types {
        emit_type(&mut o, m, t);
    }
    for r in &m.resources {
        emit_resource_trait(&mut o, r);
    }
    emit_dispatch(&mut o, m);
    emit_exports(&mut o, m);
    o
}

fn rust_c(t: crate::abi_table::CTy) -> &'static str {
    use crate::abi_table::CTy::*;
    match t {
        Void => "()",
        U32 => "u32",
        U64 | Handle => "u64",
        Status => "acme_status",
        Bytes => "acme_bytes",
        Buffer => "acme_buffer",
        BufferPtr => "*mut acme_buffer",
        HandlePtr => "*mut u64",
        Callback => "acme_future_callback",
        VoidPtr => "*mut std::ffi::c_void",
        CStr => "*const std::ffi::c_char",
    }
}

/// The package's exported C symbols (`<prefix>_call_sync`, ...). They only
/// forward to the generic, hand-written adapter in `crate::ffi::exports`.
fn emit_exports(o: &mut String, m: &Model) {
    let prefix = m.symbol_prefix();
    w!(o, "");
    w!(o, "/// Exported ABI symbols of package {} (prefix `{prefix}_`, ABI.md §1.1).", m.contract_id());
    w!(o, "pub mod exports {{");
    w!(o, "    use crate::ffi::abi_types::*;");
    w!(o, "    use crate::ffi::exports as adapter;");
    for f in crate::abi_table::FUNCTIONS {
        let ps: Vec<String> = f.params.iter().map(|(t, n)| format!("{}: {}", snake_param(n), rust_c(*t))).collect();
        let args: Vec<String> = f.params.iter().map(|(_, n)| snake_param(n)).collect();
        let ret = if f.ret == crate::abi_table::CTy::Void { String::new() } else { format!(" -> {}", rust_c(f.ret)) };
        w!(o, "");
        w!(o, "    /// # Safety");
        w!(o, "    /// See abi/acme_abi_functions.h.");
        w!(o, "    #[export_name = \"{}\"]", crate::abi_table::symbol(&prefix, f.name));
        w!(o, "    pub unsafe extern \"C\" fn {}({}){ret} {{", f.name.trim_start_matches("acme_"), ps.join(", "));
        w!(o, "        adapter::{}({})", f.name, args.join(", "));
        w!(o, "    }}");
    }
    w!(o, "}}");
}

fn snake_param(n: &str) -> String {
    let mut out = String::new();
    for ch in n.chars() {
        if ch.is_ascii_uppercase() {
            out.push('_');
            out.push(ch.to_ascii_lowercase());
        } else {
            out.push(ch);
        }
    }
    out
}

fn docs(o: &mut String, d: &Option<String>, indent: &str) {
    if let Some(d) = d {
        for l in d.lines() {
            w!(o, "{indent}/// {}", l.trim_end());
        }
    }
}

pub fn rty(t: &Ty) -> String {
    match t {
        Ty::Bool => "bool".into(),
        Ty::U8 => "u8".into(),
        Ty::U16 => "u16".into(),
        Ty::U32 => "u32".into(),
        Ty::U64 => "u64".into(),
        Ty::S8 => "i8".into(),
        Ty::S16 => "i16".into(),
        Ty::S32 => "i32".into(),
        Ty::S64 => "i64".into(),
        Ty::F32 => "f32".into(),
        Ty::F64 => "f64".into(),
        Ty::Char => "char".into(),
        Ty::String => "String".into(),
        Ty::Bytes => "Vec<u8>".into(),
        Ty::List(t) => format!("Vec<{}>", rty(t)),
        Ty::Option(t) => format!("Option<{}>", rty(t)),
        Ty::Tuple(ts) => format!("({},)", ts.iter().map(rty).collect::<Vec<_>>().join(", ")),
        Ty::Named(n) => pascal(n),
        Ty::Stream(t) => format!("AbiStream<{}>", rty(t)),
    }
}

fn ret_ty(r: &Ret) -> String {
    match r {
        Ret::Unit => "()".into(),
        Ret::Value(t) => rty(t),
        Ret::Result { ok, err } => format!(
            "Result<{}, {}>",
            ok.as_ref().map(rty).unwrap_or("()".into()),
            err.as_ref().map(rty).unwrap_or("()".into())
        ),
    }
}

/// Statements encoding the value referenced by `e` (an expression of type `&T`).
fn enc(t: &Ty, e: &str, d: usize) -> String {
    match t {
        Ty::Bool => format!("w.bool(*{e});"),
        Ty::U8 | Ty::U16 | Ty::U32 | Ty::U64 => format!("w.uint(*{e} as u64);"),
        Ty::S8 | Ty::S16 | Ty::S32 | Ty::S64 => format!("w.int(*{e} as i64);"),
        Ty::F32 => format!("w.f32(*{e});"),
        Ty::F64 => format!("w.f64(*{e});"),
        Ty::Char => format!("w.uint(*{e} as u32 as u64);"),
        Ty::String => format!("w.str({e});"),
        Ty::Bytes => format!("w.bin({e});"),
        Ty::List(t) => {
            let x = format!("x{d}");
            format!("{{ let v{d} = {e}; w.array_header(v{d}.len()); for {x} in v{d}.iter() {{ {} }} }}", enc(t, &x, d + 1))
        }
        Ty::Option(t) => {
            let x = format!("x{d}");
            format!("match {e} {{ Some({x}) => {{ {} }} None => w.nil(), }}", enc(t, &x, d + 1))
        }
        Ty::Tuple(ts) => {
            let mut s = format!("{{ let t{d} = {e}; w.array_header({}); ", ts.len());
            for (i, t) in ts.iter().enumerate() {
                s += &enc(t, &format!("&t{d}.{i}"), d + 1);
                s += " ";
            }
            s + "}"
        }
        Ty::Named(_) => format!("({e}).encode(w);"),
        Ty::Stream(_) => unreachable!("streams are encoded by the dispatcher"),
    }
}

/// Expression decoding a `T` from reader `r` inside a fn returning `Result<_, WireError>`.
fn dec(t: &Ty) -> String {
    match t {
        Ty::Bool => "r.bool()?".into(),
        Ty::U8 => "r.u8()?".into(),
        Ty::U16 => "r.u16()?".into(),
        Ty::U32 => "r.u32()?".into(),
        Ty::U64 => "r.u64()?".into(),
        Ty::S8 => "r.i8()?".into(),
        Ty::S16 => "r.i16()?".into(),
        Ty::S32 => "r.i32()?".into(),
        Ty::S64 => "r.i64()?".into(),
        Ty::F32 => "r.f32()?".into(),
        Ty::F64 => "r.f64()?".into(),
        Ty::Char => "r.char()?".into(),
        Ty::String => "r.str()?".into(),
        Ty::Bytes => "r.bin()?".into(),
        Ty::List(t) => format!("r.list(|r| Ok({}))?", dec(t)),
        Ty::Option(t) => format!("r.option(|r| Ok({}))?", dec(t)),
        Ty::Tuple(ts) => format!(
            "{{ r.tuple_header({})?; ({},) }}",
            ts.len(),
            ts.iter().map(dec).collect::<Vec<_>>().join(", ")
        ),
        Ty::Named(n) => format!("{}::decode(r)?", pascal(n)),
        Ty::Stream(_) => unreachable!(),
    }
}

fn emit_type(o: &mut String, _m: &Model, t: &TypeDecl) {
    let name = pascal(&t.name);
    docs(o, &t.docs, "");
    match &t.kind {
        TypeKind::Record(fields) => {
            w!(o, "#[derive(Debug, Clone, PartialEq)]");
            w!(o, "pub struct {name} {{");
            for f in fields {
                docs(o, &f.docs, "    ");
                w!(o, "    pub {}: {},", snake(&f.name), rty(&f.ty));
            }
            w!(o, "}}");
            w!(o, "impl {name} {{");
            w!(o, "    pub fn encode(&self, w: &mut Writer) {{");
            w!(o, "        let mut n = 0usize;");
            for f in fields {
                if matches!(f.ty, Ty::Option(_)) {
                    w!(o, "        if self.{}.is_some() {{ n += 1; }}", snake(&f.name));
                } else {
                    w!(o, "        n += 1;");
                }
            }
            w!(o, "        w.map_header(n);");
            for f in fields {
                let fname = snake(&f.name);
                if let Ty::Option(inner) = &f.ty {
                    w!(o, "        if let Some(x) = &self.{fname} {{ w.uint({}); {} }}", f.tag, enc(inner, "x", 1));
                } else {
                    w!(o, "        w.uint({}); {}", f.tag, enc(&f.ty, &format!("&self.{fname}"), 1));
                }
            }
            w!(o, "    }}");
            w!(o, "    pub fn decode(r: &mut Reader) -> Result<Self, WireError> {{");
            w!(o, "        let n = r.map_header()?;");
            for f in fields {
                w!(o, "        let mut f_{}: Option<{}> = None;", snake(&f.name), match &f.ty {
                    Ty::Option(inner) => rty(inner),
                    t => rty(t),
                });
            }
            w!(o, "        for _ in 0..n {{");
            w!(o, "            match r.u32()? {{");
            for f in fields {
                let fname = snake(&f.name);
                match &f.ty {
                    Ty::Option(_) => w!(o, "                {} => f_{fname} = {},", f.tag, dec(&f.ty)),
                    t => w!(o, "                {} => f_{fname} = Some({}),", f.tag, dec(t)),
                }
            }
            w!(o, "                _ => r.skip()?,");
            w!(o, "            }}");
            w!(o, "        }}");
            w!(o, "        Ok(Self {{");
            for f in fields {
                let fname = snake(&f.name);
                if matches!(f.ty, Ty::Option(_)) {
                    w!(o, "            {fname}: f_{fname},");
                } else {
                    w!(o, "            {fname}: f_{fname}.ok_or(WireError::missing(\"{}.{}\"))?,", t.name, f.name);
                }
            }
            w!(o, "        }})");
            w!(o, "    }}");
            w!(o, "}}");
        }
        TypeKind::Variant(cases) => {
            w!(o, "#[derive(Debug, Clone, PartialEq)]");
            w!(o, "pub enum {name} {{");
            for c in cases {
                docs(o, &c.docs, "    ");
                match &c.ty {
                    Some(t) => w!(o, "    {}({}),", pascal(&c.name), rty(t)),
                    None => w!(o, "    {},", pascal(&c.name)),
                }
            }
            w!(o, "}}");
            w!(o, "impl {name} {{");
            w!(o, "    pub fn encode(&self, w: &mut Writer) {{");
            w!(o, "        match self {{");
            for c in cases {
                match &c.ty {
                    Some(t) => w!(o, "            Self::{}(x) => {{ w.array_header(2); w.uint({}); {} }}", pascal(&c.name), c.tag, enc(t, "x", 1)),
                    None => w!(o, "            Self::{} => {{ w.array_header(1); w.uint({}); }}", pascal(&c.name), c.tag),
                }
            }
            w!(o, "        }}");
            w!(o, "    }}");
            w!(o, "    pub fn decode(r: &mut Reader) -> Result<Self, WireError> {{");
            w!(o, "        let n = r.array_header()?;");
            w!(o, "        if n == 0 {{ return Err(WireError::msg(\"{}: empty variant\")); }}", t.name);
            w!(o, "        let (v, used) = match r.u32()? {{");
            for c in cases {
                match &c.ty {
                    Some(ty) => w!(o, "            {} if n >= 2 => (Self::{}({}), 2),", c.tag, pascal(&c.name), dec(ty)),
                    None => w!(o, "            {} => (Self::{}, 1),", c.tag, pascal(&c.name)),
                }
            }
            w!(o, "            tag => return Err(WireError::unknown_case(\"{}\", tag)),", t.name);
            w!(o, "        }};");
            w!(o, "        for _ in used..n {{ r.skip()?; }}");
            w!(o, "        Ok(v)");
            w!(o, "    }}");
            w!(o, "}}");
        }
        TypeKind::Enum(cases) => {
            w!(o, "#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash)]");
            w!(o, "pub enum {name} {{");
            for c in cases {
                docs(o, &c.docs, "    ");
                w!(o, "    {},", pascal(&c.name));
            }
            w!(o, "}}");
            w!(o, "impl {name} {{");
            w!(o, "    pub fn encode(&self, w: &mut Writer) {{");
            w!(o, "        w.uint(match self {{ {} }});", cases.iter().map(|c| format!("Self::{} => {}", pascal(&c.name), c.tag)).collect::<Vec<_>>().join(", "));
            w!(o, "    }}");
            w!(o, "    pub fn decode(r: &mut Reader) -> Result<Self, WireError> {{");
            w!(o, "        match r.u32()? {{");
            for c in cases {
                w!(o, "            {} => Ok(Self::{}),", c.tag, pascal(&c.name));
            }
            w!(o, "            tag => Err(WireError::unknown_case(\"{}\", tag)),", t.name);
            w!(o, "        }}");
            w!(o, "    }}");
            w!(o, "}}");
        }
    }
    if t.is_error {
        w!(o, "impl std::fmt::Display for {name} {{");
        w!(o, "    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {{ write!(f, \"{{:?}}\", self) }}");
        w!(o, "}}");
        w!(o, "impl std::error::Error for {name} {{}}");
    }
    w!(o, "");
}

fn params_sig(f: &Func) -> String {
    f.params.iter().map(|(n, t)| format!(", {}: {}", snake(n), rty(t))).collect()
}

fn emit_resource_trait(o: &mut String, r: &Resource) {
    docs(o, &r.docs, "");
    w!(o, "///");
    w!(o, "/// Implemented by the core. Plain async Rust: no FFI types appear here.");
    w!(o, "pub trait {}Resource: Send + Sync + Sized + 'static {{", pascal(&r.name));
    if let Some(c) = &r.ctor {
        docs(o, &c.docs, "    ");
        let ps: Vec<String> = c.params.iter().map(|(n, t)| format!("{}: {}", snake(n), rty(t))).collect();
        w!(o, "    fn new({}) -> Self;", ps.join(", "));
    }
    for f in &r.methods {
        docs(o, &f.docs, "    ");
        if f.is_async {
            w!(o, "    fn {}(&self{}) -> impl Future<Output = {}> + Send;", snake(&f.name), params_sig(f), ret_ty(&f.ret));
        } else {
            w!(o, "    fn {}(&self{}) -> {};", snake(&f.name), params_sig(f), ret_ty(&f.ret));
        }
    }
    w!(o, "    /// Called when the host drops its handle. In-flight calls may still hold");
    w!(o, "    /// references to `self`; use this to abort them and end streams.");
    w!(o, "    fn on_drop(&self) {{}}");
    w!(o, "}}");
    w!(o, "");
}

fn encode_ret(o: &mut String, ret: &Ret, indent: &str) {
    match ret {
        Ret::Unit => w!(o, "{indent}w.nil();"),
        Ret::Value(t) => w!(o, "{indent}{}", enc(t, "&ret", 1)),
        Ret::Result { ok, err } => {
            w!(o, "{indent}w.array_header(2);");
            w!(o, "{indent}match &ret {{");
            match ok {
                Some(t) => w!(o, "{indent}    Ok(v) => {{ w.uint(0); {} }}", enc(t, "v", 1)),
                None => w!(o, "{indent}    Ok(_) => {{ w.uint(0); w.nil(); }}"),
            }
            match err {
                Some(t) => w!(o, "{indent}    Err(e) => {{ w.uint(1); {} }}", enc(t, "e", 1)),
                None => w!(o, "{indent}    Err(_) => {{ w.uint(1); w.nil(); }}"),
            }
            w!(o, "{indent}}}");
        }
    }
}

fn decode_params(o: &mut String, f: &Func, indent: &str) {
    w!(o, "{indent}let mut r = Reader::new(request);");
    w!(o, "{indent}let r = &mut r;");
    w!(o, "{indent}r.params({})?;", f.params.len());
    for (n, t) in &f.params {
        w!(o, "{indent}let {}: {} = {};", snake(n), rty(t), dec(t));
    }
    w!(o, "{indent}r.finish()?;");
}

fn args(f: &Func) -> String {
    f.params.iter().map(|(n, _)| snake(n)).collect::<Vec<_>>().join(", ")
}

fn emit_dispatch(o: &mut String, m: &Model) {
    w!(o, "/// Binds the generated contract to the core's concrete types.");
    w!(o, "pub trait Implementation {{");
    for r in &m.resources {
        w!(o, "    type {}: {}Resource;", pascal(&r.name), pascal(&r.name));
    }
    w!(o, "}}");
    w!(o, "");

    // ---- sync ------------------------------------------------------------
    w!(o, "pub fn dispatch_sync<I: Implementation>(object: Option<ObjectRef>, method_id: u32, request: &[u8]) -> Result<Vec<u8>, AbiError> {{");
    w!(o, "    let mut w = Writer::new();");
    w!(o, "    let w = &mut w;");
    w!(o, "    match method_id {{");
    for r in &m.resources {
        let rt = format!("I::{}", pascal(&r.name));
        if let Some(c) = &r.ctor {
            w!(o, "        method_ids::{}_{} => {{", screaming(&r.name), screaming(&c.name));
            w!(o, "            if object.is_some() {{ return Err(AbiError::InvalidHandle); }}");
            decode_params(o, c, "            ");
            w!(o, "            let obj = Arc::new(<{rt} as {}Resource>::new({}));", pascal(&r.name), args(c));
            w!(o, "            let hook = obj.clone();");
            w!(o, "            let handle = host::insert_object(groups::{}, obj, move || hook.on_drop());", screaming(&r.name));
            w!(o, "            w.uint(handle);");
            w!(o, "        }}");
        }
        for f in r.methods.iter().filter(|f| !f.is_async) {
            w!(o, "        method_ids::{}_{} => {{", screaming(&r.name), screaming(&f.name));
            w!(o, "            let this = host::object::<{rt}>(object)?;");
            decode_params(o, f, "            ");
            w!(o, "            let ret = this.{}({});", snake(&f.name), args(f));
            if let Ret::Value(Ty::Stream(item)) = &f.ret {
                w!(o, "            let handle = host::insert_stream(ret, |item: &{}, w: &mut Writer| {{ {} }});", rty(item), enc(item, "item", 1));
                w!(o, "            w.uint(handle);");
            } else {
                encode_ret(o, &f.ret, "            ");
            }
            w!(o, "        }}");
        }
        for f in r.methods.iter().filter(|f| f.is_async) {
            w!(o, "        method_ids::{}_{} => return Err(AbiError::Unsupported),", screaming(&r.name), screaming(&f.name));
        }
    }
    w!(o, "        _ => return Err(AbiError::UnknownMethod),");
    w!(o, "    }}");
    w!(o, "    Ok(std::mem::take(w).into_vec())");
    w!(o, "}}");
    w!(o, "");

    // ---- async -----------------------------------------------------------
    w!(o, "pub fn dispatch_async<I: Implementation>(object: Option<ObjectRef>, method_id: u32, request: &[u8]) -> Result<BoxFuture<Result<Vec<u8>, AbiError>>, AbiError> {{");
    w!(o, "    match method_id {{");
    for r in &m.resources {
        let rt = format!("I::{}", pascal(&r.name));
        for f in r.methods.iter().filter(|f| f.is_async) {
            w!(o, "        method_ids::{}_{} => {{", screaming(&r.name), screaming(&f.name));
            w!(o, "            let this = host::object::<{rt}>(object)?;");
            decode_params(o, f, "            ");
            w!(o, "            Ok(Box::pin(async move {{");
            w!(o, "                let ret = this.{}({}).await;", snake(&f.name), args(f));
            w!(o, "                let mut w = Writer::new();");
            w!(o, "                let w = &mut w;");
            encode_ret(o, &f.ret, "                ");
            w!(o, "                Ok(std::mem::take(w).into_vec())");
            w!(o, "            }}))");
            w!(o, "        }}");
        }
        for f in r.ctor.iter().chain(r.methods.iter().filter(|f| !f.is_async)) {
            w!(o, "        method_ids::{}_{} => Err(AbiError::Unsupported),", screaming(&r.name), screaming(&f.name));
        }
    }
    w!(o, "        _ => Err(AbiError::UnknownMethod),");
    w!(o, "    }}");
    w!(o, "}}");
}
