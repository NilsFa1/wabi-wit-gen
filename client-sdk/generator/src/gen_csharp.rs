//! C# emitter: records / enums / variants (closed record hierarchies),
//! exceptions, the payload codec, one client class per WIT resource and the
//! P/Invoke declarations of the generic ABI.

use crate::abi_table::{self, CTy};
use crate::ir::*;
use crate::names::*;

/// Namespace of the hand-written, contract-agnostic runtime (and its generated glue).
const RT_NS: &str = "Wabi.Client.Runtime";

/// `wabi:client` -> `Wabi.Client`, `gematik:zero` -> `Gematik.Zero`
pub fn cs_ns(m: &Model) -> String {
    format!("{}.{}", pascal(&m.namespace), pascal(&m.package))
}

pub fn emit(m: &Model) -> Vec<(String, String)> {
    let mut files = vec![
        ("Types.g.cs".to_string(), types(m)),
        ("WireCodec.g.cs".to_string(), codec(m)),
        ("NativeAbi.g.cs".to_string(), native_abi(m)),
    ];
    for r in &m.resources {
        files.push((format!("{}.g.cs", class_name(m, r)), resource(m, r)));
    }
    if m.needs_host_calls() {
        files.push((format!("{}.g.cs", host_class(m)), host(m)));
    }
    files
}

pub(crate) fn header() -> String {
    "// <auto-generated>\n//   Generated by wabi-wit-gen from wit/*.wit — DO NOT EDIT.\n// </auto-generated>\n#nullable enable\n".into()
}

/// Resource class name: `wabi:client` + resource `client` -> `WabiClient`
/// (qualified only when the resource is named like its package), otherwise
/// just the resource name (`dpop-signer` -> `DpopSigner`).
pub fn class_name(m: &Model, r: &Resource) -> String {
    if r.name == m.package { format!("{}{}", pascal(&m.namespace), pascal(&r.name)) } else { pascal(&r.name) }
}

fn xml(s: &str) -> String {
    s.replace('&', "&amp;").replace('<', "&lt;").replace('>', "&gt;")
}

pub(crate) fn docs(o: &mut String, d: &Option<String>, ind: &str) {
    if let Some(d) = d {
        w!(o, "{ind}/// <summary>");
        for l in d.lines() {
            w!(o, "{ind}/// {}", xml(l.trim_end()));
        }
        w!(o, "{ind}/// </summary>");
    }
}

const KEYWORDS: &[&str] = &[
    "abstract", "as", "base", "bool", "break", "byte", "case", "catch", "char", "checked", "class", "const",
    "continue", "decimal", "default", "delegate", "do", "double", "else", "enum", "event", "explicit", "extern",
    "false", "finally", "fixed", "float", "for", "foreach", "goto", "if", "implicit", "in", "int", "interface",
    "internal", "is", "lock", "long", "namespace", "new", "null", "object", "operator", "out", "override", "params",
    "private", "protected", "public", "readonly", "ref", "return", "sbyte", "sealed", "short", "sizeof", "stackalloc",
    "static", "string", "struct", "switch", "this", "throw", "true", "try", "typeof", "uint", "ulong", "unchecked",
    "unsafe", "ushort", "using", "virtual", "void", "volatile", "while",
];

pub(crate) fn ident(s: &str) -> String {
    let c = camel(s);
    if KEYWORDS.contains(&c.as_str()) { format!("@{c}") } else { c }
}

pub fn cs(t: &Ty) -> String {
    match t {
        Ty::Bool => "bool".into(),
        Ty::U8 => "byte".into(),
        Ty::U16 => "ushort".into(),
        Ty::U32 => "uint".into(),
        Ty::U64 => "ulong".into(),
        Ty::S8 => "sbyte".into(),
        Ty::S16 => "short".into(),
        Ty::S32 => "int".into(),
        Ty::S64 => "long".into(),
        Ty::F32 => "float".into(),
        Ty::F64 => "double".into(),
        Ty::Char => "System.Text.Rune".into(),
        Ty::String => "string".into(),
        Ty::Bytes => "byte[]".into(),
        Ty::List(t) => format!("IReadOnlyList<{}>", cs(t)),
        Ty::Option(t) => format!("{}?", cs(t)),
        Ty::Tuple(ts) => format!("({})", ts.iter().map(cs).collect::<Vec<_>>().join(", ")),
        Ty::Named(n) => pascal(n),
        Ty::Stream(t) => format!("IAsyncEnumerable<{}>", cs(t)),
    }
}

/// Statement(s) writing expression `e` of type `t` to writer `w`.
pub(crate) fn enc(t: &Ty, e: &str, d: usize) -> String {
    match t {
        Ty::Bool => format!("w.WriteBool({e});"),
        Ty::U8 | Ty::U16 | Ty::U32 | Ty::U64 => format!("w.WriteUInt({e});"),
        Ty::S8 | Ty::S16 | Ty::S32 | Ty::S64 => format!("w.WriteInt({e});"),
        Ty::F32 => format!("w.WriteFloat32({e});"),
        Ty::F64 => format!("w.WriteFloat64({e});"),
        Ty::Char => format!("w.WriteUInt((uint){e}.Value);"),
        Ty::String => format!("w.WriteString({e});"),
        Ty::Bytes => format!("w.WriteBinary({e});"),
        Ty::List(t) => format!(
            "w.WriteArrayHeader({e}.Count); foreach (var x{d} in {e}) {{ {} }}",
            enc(t, &format!("x{d}"), d + 1)
        ),
        Ty::Option(t) => format!(
            "if ({e} is {{ }} x{d}) {{ {} }} else {{ w.WriteNil(); }}",
            enc(t, &format!("x{d}"), d + 1)
        ),
        Ty::Tuple(ts) => {
            let mut s = format!("w.WriteArrayHeader({});", ts.len());
            for (i, t) in ts.iter().enumerate() {
                s += " ";
                s += &enc(t, &format!("{e}.Item{}", i + 1), d + 1);
            }
            s
        }
        Ty::Named(n) => format!("WireCodec.Write{}(w, {e});", pascal(n)),
        Ty::Stream(_) => unreachable!(),
    }
}

/// Expression reading a value of type `t` from reader `r`.
pub(crate) fn dec(t: &Ty, r: &str, d: usize) -> String {
    match t {
        Ty::Bool => format!("{r}.ReadBool()"),
        Ty::U8 => format!("checked((byte){r}.ReadUInt64())"),
        Ty::U16 => format!("checked((ushort){r}.ReadUInt64())"),
        Ty::U32 => format!("checked((uint){r}.ReadUInt64())"),
        Ty::U64 => format!("{r}.ReadUInt64()"),
        Ty::S8 => format!("checked((sbyte){r}.ReadInt64())"),
        Ty::S16 => format!("checked((short){r}.ReadInt64())"),
        Ty::S32 => format!("checked((int){r}.ReadInt64())"),
        Ty::S64 => format!("{r}.ReadInt64()"),
        Ty::F32 => format!("{r}.ReadFloat32()"),
        Ty::F64 => format!("{r}.ReadFloat64()"),
        Ty::Char => format!("new System.Text.Rune(checked((int){r}.ReadUInt64()))"),
        Ty::String => format!("{r}.ReadString()"),
        Ty::Bytes => format!("{r}.ReadBinary()"),
        Ty::List(t) => format!("{r}.ReadList(r{d} => {})", dec(t, &format!("r{d}"), d + 1)),
        Ty::Option(t) => format!("({r}.TryReadNil() ? default({}?) : {})", cs(t), dec(t, r, d + 1)),
        Ty::Tuple(ts) => format!(
            "((Func<{}>)(() => {{ {r}.ReadArrayHeader({}); return ({}); }}))()",
            cs(t),
            ts.len(),
            ts.iter().map(|t| dec(t, r, d + 1)).collect::<Vec<_>>().join(", ")
        ),
        Ty::Named(n) => format!("WireCodec.Read{}({r})", pascal(n)),
        Ty::Stream(_) => unreachable!(),
    }
}

fn types(m: &Model) -> String {
    let mut o = header();
    w!(o, "using System;");
    w!(o, "using System.Collections.Generic;");
    w!(o, "using {RT_NS};");
    w!(o, "");
    w!(o, "namespace {};", cs_ns(m));
    w!(o, "");
    for t in &m.types {
        let name = pascal(&t.name);
        docs(&mut o, &t.docs, "");
        match &t.kind {
            TypeKind::Record(fields) => {
                let ps: Vec<String> = fields.iter().map(|f| format!("{} {}", cs(&f.ty), pascal(&f.name))).collect();
                w!(o, "public sealed record {name}({});", ps.join(", "));
            }
            TypeKind::Enum(cases) => {
                w!(o, "public enum {name}");
                w!(o, "{{");
                for c in cases {
                    docs(&mut o, &c.docs, "    ");
                    w!(o, "    {} = {},", pascal(&c.name), c.tag);
                }
                w!(o, "}}");
            }
            TypeKind::Variant(cases) => {
                w!(o, "public abstract record {name}");
                w!(o, "{{");
                w!(o, "    private {name}() {{ }}");
                for c in cases {
                    w!(o, "");
                    docs(&mut o, &c.docs, "    ");
                    match &c.ty {
                        Some(t) => w!(o, "    public sealed record {}({} Value) : {name};", pascal(&c.name), cs(t)),
                        None => w!(o, "    public sealed record {}() : {name};", pascal(&c.name)),
                    }
                }
                w!(o, "}}");
            }
        }
        w!(o, "");
        if t.is_error {
            let ex = exception_name(&t.name);
            w!(o, "/// <summary>Thrown when an operation fails with a <see cref=\"{name}\"/>.</summary>");
            w!(o, "public sealed class {ex} : WabiException");
            w!(o, "{{");
            w!(o, "    public {name} Error {{ get; }}");
            w!(o, "    public {ex}({name} error) : base(error.ToString()) => Error = error;");
            w!(o, "}}");
            w!(o, "");
        }
    }
    o
}

fn codec(m: &Model) -> String {
    let mut o = header();
    w!(o, "using System;");
    w!(o, "using System.Collections.Generic;");
    w!(o, "using {RT_NS};");
    w!(o, "");
    w!(o, "namespace {};", cs_ns(m));
    w!(o, "");
    w!(o, "/// <summary>Payload encoding v1 for all contract types (see ABI.md §5).</summary>");
    w!(o, "internal static class WireCodec");
    w!(o, "{{");
    for t in &m.types {
        let name = pascal(&t.name);
        match &t.kind {
            TypeKind::Record(fields) => {
                w!(o, "    public static void Write{name}(MsgPackWriter w, {name} v)");
                w!(o, "    {{");
                w!(o, "        int n = 0;");
                for f in fields {
                    if matches!(f.ty, Ty::Option(_)) {
                        w!(o, "        if (v.{} is not null) n++;", pascal(&f.name));
                    } else {
                        w!(o, "        n++;");
                    }
                }
                w!(o, "        w.WriteMapHeader(n);");
                for f in fields {
                    let p = pascal(&f.name);
                    if let Ty::Option(inner) = &f.ty {
                        w!(o, "        if (v.{p} is {{ }} f{}) {{ w.WriteUInt({}); {} }}", f.tag, f.tag, enc(inner, &format!("f{}", f.tag), 1));
                    } else {
                        w!(o, "        w.WriteUInt({}); {}", f.tag, enc(&f.ty, &format!("v.{p}"), 1));
                    }
                }
                w!(o, "    }}");
                w!(o, "");
                w!(o, "    public static {name} Read{name}(MsgPackReader r)");
                w!(o, "    {{");
                w!(o, "        int n = r.ReadMapHeader();");
                for f in fields {
                    w!(o, "        {} f{} = default!; bool has{} = false;", cs(&f.ty), f.tag, f.tag);
                }
                w!(o, "        for (int i = 0; i < n; i++)");
                w!(o, "        {{");
                w!(o, "            switch (r.ReadUInt64())");
                w!(o, "            {{");
                for f in fields {
                    w!(o, "                case {}: f{} = {}; has{} = true; break;", f.tag, f.tag, dec(&f.ty, "r", 1), f.tag);
                }
                w!(o, "                default: r.Skip(); break;");
                w!(o, "            }}");
                w!(o, "        }}");
                for f in fields.iter().filter(|f| !matches!(f.ty, Ty::Option(_))) {
                    w!(o, "        if (!has{}) throw new WabiProtocolException(\"{}: missing field '{}'\");", f.tag, t.name, f.name);
                }
                for f in fields.iter().filter(|f| matches!(f.ty, Ty::Option(_))) {
                    w!(o, "        _ = has{};", f.tag);
                }
                let args: Vec<String> = fields.iter().map(|f| format!("f{}", f.tag)).collect();
                w!(o, "        return new {name}({});", args.join(", "));
                w!(o, "    }}");
            }
            TypeKind::Enum(cases) => {
                w!(o, "    public static void Write{name}(MsgPackWriter w, {name} v) => w.WriteUInt((uint)v);");
                w!(o, "");
                w!(o, "    public static {name} Read{name}(MsgPackReader r)");
                w!(o, "    {{");
                w!(o, "        var tag = r.ReadUInt64();");
                w!(o, "        return tag switch");
                w!(o, "        {{");
                for c in cases {
                    w!(o, "            {} => {name}.{},", c.tag, pascal(&c.name));
                }
                w!(o, "            _ => throw new WabiProtocolException($\"unknown case tag {{tag}} for '{}'\"),", t.name);
                w!(o, "        }};");
                w!(o, "    }}");
            }
            TypeKind::Variant(cases) => {
                w!(o, "    public static void Write{name}(MsgPackWriter w, {name} v)");
                w!(o, "    {{");
                w!(o, "        switch (v)");
                w!(o, "        {{");
                for c in cases {
                    let cn = pascal(&c.name);
                    match &c.ty {
                        Some(t) => w!(o, "            case {name}.{cn} c: w.WriteArrayHeader(2); w.WriteUInt({}); {} break;", c.tag, enc(t, "c.Value", 1)),
                        None => w!(o, "            case {name}.{cn}: w.WriteArrayHeader(1); w.WriteUInt({}); break;", c.tag),
                    }
                }
                w!(o, "            default: throw new ArgumentException(\"unknown {name} case\", nameof(v));");
                w!(o, "        }}");
                w!(o, "    }}");
                w!(o, "");
                w!(o, "    public static {name} Read{name}(MsgPackReader r)");
                w!(o, "    {{");
                w!(o, "        int n = r.ReadArrayHeader();");
                w!(o, "        if (n == 0) throw new WabiProtocolException(\"{}: empty variant\");", t.name);
                w!(o, "        var tag = r.ReadUInt64();");
                w!(o, "        {name} v; int used;");
                w!(o, "        switch (tag)");
                w!(o, "        {{");
                for c in cases {
                    let cn = pascal(&c.name);
                    match &c.ty {
                        Some(t) => w!(o, "            case {} when n >= 2: v = new {name}.{cn}({}); used = 2; break;", c.tag, dec(t, "r", 1)),
                        None => w!(o, "            case {}: v = new {name}.{cn}(); used = 1; break;", c.tag),
                    }
                }
                w!(o, "            default: throw new WabiProtocolException($\"unknown case tag {{tag}} for '{}'\");", t.name);
                w!(o, "        }}");
                w!(o, "        for (int i = used; i < n; i++) r.Skip();");
                w!(o, "        return v;");
                w!(o, "    }}");
            }
        }
        w!(o, "");
    }
    w!(o, "}}");
    o
}

fn ret_cs(f: &Func) -> String {
    let inner = match &f.ret {
        Ret::Unit | Ret::Result { ok: None, .. } => None,
        Ret::Value(t) | Ret::Result { ok: Some(t), .. } => Some(cs(t)),
    };
    match (f.is_async, inner) {
        (true, None) => "Task".into(),
        (true, Some(t)) => format!("Task<{t}>"),
        (false, None) => "void".into(),
        (false, Some(t)) => t,
    }
}

fn resource(m: &Model, r: &Resource) -> String {
    let cls = class_name(m, r);
    let res = screaming_to_pascal(&r.name);
    let mut o = header();
    w!(o, "using System;");
    w!(o, "using System.Collections.Generic;");
    w!(o, "using System.Runtime.CompilerServices;");
    w!(o, "using System.Threading;");
    w!(o, "using System.Threading.Tasks;");
    w!(o, "using {RT_NS};");
    w!(o, "");
    w!(o, "namespace {};", cs_ns(m));
    w!(o, "");
    docs(&mut o, &r.docs, "");
    w!(o, "public sealed partial class {cls} : IDisposable, IAsyncDisposable");
    w!(o, "{{");
    w!(o, "    private readonly IClientBackend _backend;");
    w!(o, "    private readonly ObjectHandle _handle;");
    w!(o, "");
    if let Some(c) = &r.ctor {
        let ps: Vec<String> = c.params.iter().map(|(n, t)| format!("{} {}", cs(t), ident(n))).collect();
        let args: Vec<String> = c.params.iter().map(|(n, _)| ident(n)).collect();
        docs(&mut o, &c.docs, "    ");
        w!(o, "    public {cls}({}) : this({}{}NativeBackend.Shared) {{ }}", ps.join(", "), args.join(", "), if args.is_empty() { "" } else { ", " });
        w!(o, "");
        w!(o, "    /// <summary>Creates the client on an explicit backend (native core, component model, test double).</summary>");
        w!(o, "    public {cls}({}{}IClientBackend backend)", ps.join(", "), if ps.is_empty() { "" } else { ", " });
        w!(o, "    {{");
        w!(o, "        _backend = backend ?? throw new ArgumentNullException(nameof(backend));");
        w!(o, "        var w = new MsgPackWriter();");
        w!(o, "        w.WriteArrayHeader({});", c.params.len());
        for (n, t) in &c.params {
            w!(o, "        {}", enc(t, &ident(n), 1));
        }
        w!(o, "        var r = new MsgPackReader(_backend.CallSync(0, MethodIds.{res}{}, w.ToArray()));", pascal(&c.name));
        w!(o, "        _handle = new ObjectHandle(_backend, r.ReadUInt64());");
        w!(o, "    }}");
        w!(o, "");
    }
    for f in &r.methods {
        docs(&mut o, &f.docs, "    ");
        let mut ps: Vec<String> = f.params.iter().map(|(n, t)| format!("{} {}", cs(t), ident(n))).collect();
        let mid = format!("MethodIds.{res}{}", pascal(&f.name));
        if let Ret::Value(Ty::Stream(item)) = &f.ret {
            ps.push("[EnumeratorCancellation] CancellationToken cancellationToken = default".into());
            w!(o, "    public async IAsyncEnumerable<{}> {}({})", cs(item), pascal(&f.name), ps.join(", "));
            w!(o, "    {{");
            emit_request(&mut o, f);
            w!(o, "        var r = new MsgPackReader(_backend.CallSync(_handle.Value, {mid}, w.ToArray()));");
            w!(o, "        var stream = r.ReadUInt64();");
            w!(o, "        await foreach (var item in _backend.ReadStream(stream, cancellationToken).ConfigureAwait(false))");
            w!(o, "        {{");
            w!(o, "            yield return {};", dec(item, "new MsgPackReader(item)", 1));
            w!(o, "        }}");
            w!(o, "    }}");
            w!(o, "");
            continue;
        }
        let name = if f.is_async { format!("{}Async", pascal(&f.name)) } else { pascal(&f.name) };
        if f.is_async {
            ps.push("CancellationToken cancellationToken = default".into());
        }
        let asy = if f.is_async { "async " } else { "" };
        w!(o, "    public {asy}{} {name}({})", ret_cs(f), ps.join(", "));
        w!(o, "    {{");
        emit_request(&mut o, f);
        if f.is_async {
            w!(o, "        var r = new MsgPackReader(await _backend.CallAsync(_handle.Value, {mid}, w.ToArray(), cancellationToken).ConfigureAwait(false));");
        } else {
            w!(o, "        var r = new MsgPackReader(_backend.CallSync(_handle.Value, {mid}, w.ToArray()));");
        }
        match &f.ret {
            Ret::Unit => {}
            Ret::Value(t) => w!(o, "        return {};", dec(t, "r", 1)),
            Ret::Result { ok, err } => {
                w!(o, "        if (r.ReadResultTag() != 0)");
                match err {
                    Some(Ty::Named(n)) => w!(o, "            throw new {}(WireCodec.Read{}(r));", exception_name(n), pascal(n)),
                    Some(t) => w!(o, "            throw new WabiCallFailedException({});", dec(t, "r", 1)),
                    None => w!(o, "            throw new WabiCallFailedException(null);"),
                }
                match ok {
                    Some(t) => w!(o, "        return {};", dec(t, "r", 1)),
                    None => w!(o, "        r.ReadNil();"),
                }
            }
        }
        w!(o, "    }}");
        w!(o, "");
    }
    w!(o, "    /// <summary>Releases the native object. In-flight calls fail, event streams end.</summary>");
    w!(o, "    public void Dispose() => _handle.Dispose();");
    w!(o, "");
    w!(o, "    public ValueTask DisposeAsync()");
    w!(o, "    {{");
    w!(o, "        _handle.Dispose();");
    w!(o, "        return ValueTask.CompletedTask;");
    w!(o, "    }}");
    w!(o, "}}");
    o
}

fn screaming_to_pascal(s: &str) -> String {
    pascal(s)
}

fn emit_request(o: &mut String, f: &Func) {
    w!(o, "        var w = new MsgPackWriter();");
    w!(o, "        w.WriteArrayHeader({});", f.params.len());
    for (i, (n, t)) in f.params.iter().enumerate() {
        // distinct depth per parameter: pattern variables share the method scope
        w!(o, "        {}", enc(t, &ident(n), 1 + 10 * i));
    }
}

fn ctype(t: CTy) -> &'static str {
    match t {
        CTy::Void => "void",
        CTy::U32 => "uint",
        CTy::U64 | CTy::Handle => "ulong",
        CTy::Status => "int",
        CTy::Bytes => "WabiBytes",
        CTy::Buffer => "WabiBuffer",
        CTy::BufferPtr => "WabiBuffer*",
        CTy::HandlePtr => "ulong*",
        CTy::Callback | CTy::VoidPtr | CTy::CStr | CTy::HostHandler => "IntPtr",
    }
}

fn native_abi(m: &Model) -> String {
    let mut o = header();
    let (maj, min, _) = m.version_triple();
    w!(o, "using System;");
    w!(o, "using System.Runtime.InteropServices;");
    w!(o, "");
    w!(o, "namespace {RT_NS};");
    w!(o, "");
    w!(o, "/// <summary>The contract this SDK was generated from.</summary>");
    w!(o, "public static class Contract");
    w!(o, "{{");
    w!(o, "    public const string Id = \"{}\";", m.contract_id());
    w!(o, "    /// <summary>Prefix of this package's ABI symbols (`{0}_call_sync`, ...) and library name (`{0}`).</summary>", m.symbol_prefix());
    w!(o, "    public const string SymbolPrefix = \"{}_\";", m.symbol_prefix());
    w!(o, "    public const string Package = \"{}:{}\";", m.namespace, m.package);
    w!(o, "    public const int Major = {maj};");
    w!(o, "    public const int Minor = {min};");
    w!(o, "}}");
    w!(o, "");
    w!(o, "/// <summary>Stable method ids (wit/abi-ids.lock).</summary>");
    w!(o, "internal static class MethodIds");
    w!(o, "{{");
    for r in &m.resources {
        for f in r.ctor.iter().chain(&r.methods) {
            w!(o, "    public const uint {}{} = {:#06x};", pascal(&r.name), pascal(&f.name), f.id);
        }
    }
    for h in &m.imports {
        for f in &h.funcs {
            w!(o, "    public const uint {}{} = {:#06x}; // import, answered by the app", pascal(&h.name), pascal(&f.name), f.id);
        }
    }
    w!(o, "}}");
    w!(o, "");
    w!(o, "/// <summary>ABI status codes (abi/wabi_abi.h).</summary>");
    w!(o, "public static class WabiStatus");
    w!(o, "{{");
    for (n, v) in abi_table::STATUSES {
        w!(o, "    public const int {} = {v};", pascal(&n.to_ascii_lowercase().replace('_', "-")));
    }
    w!(o, "}}");
    w!(o, "");
    w!(o, "[Flags]");
    w!(o, "public enum WabiCapabilities : ulong");
    w!(o, "{{");
    w!(o, "    None = 0,");
    for (n, bit) in abi_table::CAPABILITIES {
        w!(o, "    {} = 1UL << {bit},", pascal(&n.to_ascii_lowercase().replace('_', "-")));
    }
    w!(o, "}}");
    w!(o, "");
    w!(o, "[StructLayout(LayoutKind.Sequential)]");
    w!(o, "internal unsafe readonly struct WabiBytes");
    w!(o, "{{");
    w!(o, "    public readonly byte* Ptr;");
    w!(o, "    public readonly nuint Len;");
    w!(o, "    public WabiBytes(byte* ptr, nuint len) {{ Ptr = ptr; Len = len; }}");
    w!(o, "}}");
    w!(o, "");
    w!(o, "[StructLayout(LayoutKind.Sequential)]");
    w!(o, "internal unsafe struct WabiBuffer");
    w!(o, "{{");
    w!(o, "    public byte* Ptr;");
    w!(o, "    public nuint Len;");
    w!(o, "}}");
    w!(o, "");
    w!(o, "/// <summary>P/Invoke declarations of the generic native ABI {}.{}. This list does not", abi_table::ABI_MAJOR, abi_table::ABI_MINOR);
    w!(o, "/// grow when WIT functions are added: those are addressed by <see cref=\"MethodIds\"/>.</summary>");
    w!(o, "internal static unsafe class NativeAbi");
    w!(o, "{{");
    w!(o, "    public const string Library = \"{}\";", m.symbol_prefix());
    w!(o, "    public const uint AbiMajor = {};", abi_table::ABI_MAJOR);
    w!(o, "    /// <summary>Minimum ABI minor this package needs (1 if it uses host calls).</summary>");
    w!(o, "    public const uint AbiMinor = {};", m.required_abi_minor());
    w!(o, "    public static readonly bool RequiresHostCalls = {};", m.needs_host_calls());
    for f in abi_table::FUNCTIONS {
        let ps: Vec<String> = f.params.iter().map(|(t, n)| format!("{} {}", ctype(*t), if KEYWORDS.contains(n) { format!("@{n}") } else { n.to_string() })).collect();
        w!(o, "");
        if f.host_call {
            w!(o, "    /// <summary>ABI 1.1 host calls: only present in cores with WABI_CAP_HOST_CALLS (bound lazily).</summary>");
        }
        w!(o, "    [DllImport(Library, EntryPoint = \"{}\", CallingConvention = CallingConvention.Cdecl, ExactSpelling = true)]", abi_table::symbol(&m.symbol_prefix(), f.name));
        w!(o, "    public static extern {} {}({});", ctype(f.ret), f.name, ps.join(", "));
    }
    w!(o, "}}");
    o
}

/// `gematik:zero` -> `ZeroHost`: registers the app's implementations of the imports.
fn host_class(m: &Model) -> String {
    format!("{}Host", pascal(&m.package))
}

fn host_ret(r: &Ret) -> String {
    match r {
        Ret::Unit | Ret::Result { ok: None, .. } => "Task".into(),
        Ret::Value(t) | Ret::Result { ok: Some(t), .. } => format!("Task<{}>", cs(t)),
    }
}

/// App-side host calls (ABI 1.1): one interface per imported WIT interface,
/// plus `<Package>Host.Register(...)` which decodes requests and encodes answers.
fn host(m: &Model) -> String {
    let cls = host_class(m);
    let mut o = header();
    w!(o, "using System;");
    w!(o, "using System.Collections.Generic;");
    w!(o, "using System.Threading.Tasks;");
    w!(o, "using {RT_NS};");
    w!(o, "");
    w!(o, "namespace {};", cs_ns(m));
    for h in &m.imports {
        w!(o, "");
        docs(&mut o, &h.docs, "");
        w!(o, "/// <remarks>WIT import `{}`: implemented by the APP, called by the core on its own", h.name);
        w!(o, "/// threads. Domain errors are reported by throwing the generated exception.</remarks>");
        w!(o, "public interface I{}", pascal(&h.name));
        w!(o, "{{");
        for f in &h.funcs {
            docs(&mut o, &f.docs, "    ");
            let ps: Vec<String> = f.params.iter().map(|(n, t)| format!("{} {}", cs(t), ident(n))).collect();
            w!(o, "    {} {}Async({});", host_ret(&f.ret), pascal(&f.name), ps.join(", "));
        }
        w!(o, "}}");
    }
    let params: Vec<String> = m.imports.iter().map(|h| format!("I{} {}", pascal(&h.name), ident(&h.name))).collect();
    let args: Vec<String> = m.imports.iter().map(|h| ident(&h.name)).collect();
    w!(o, "");
    w!(o, "/// <summary>Connects the app's implementations of the WIT imports of {} to the core.</summary>", m.contract_id());
    w!(o, "public static class {cls}");
    w!(o, "{{");
    w!(o, "    /// <summary>Call once at startup, before the core needs the app (process-wide).</summary>");
    w!(o, "    public static void Register({})", params.join(", "));
    w!(o, "    {{");
    for a in &args {
        w!(o, "        ArgumentNullException.ThrowIfNull({a});");
    }
    w!(o, "        HostCalls.Install((methodId, request) => DispatchAsync({}, methodId, request));", args.join(", "));
    w!(o, "    }}");
    w!(o, "");
    w!(o, "    /// <summary>Removes the registration.</summary>");
    w!(o, "    public static void Unregister() => HostCalls.Uninstall();");
    w!(o, "");
    w!(o, "    private static async Task<byte[]> DispatchAsync({}, uint methodId, byte[] request)", params.join(", "));
    w!(o, "    {{");
    w!(o, "        var r = new MsgPackReader(request);");
    w!(o, "        var w = new MsgPackWriter();");
    w!(o, "        switch (methodId)");
    w!(o, "        {{");
    for h in &m.imports {
        let target = ident(&h.name);
        for f in &h.funcs {
            w!(o, "            case MethodIds.{}{}:", pascal(&h.name), pascal(&f.name));
            w!(o, "            {{");
            w!(o, "                r.ReadArrayHeader({});", f.params.len());
            for (n, t) in &f.params {
                w!(o, "                var {} = {};", host_local(n), dec(t, "r", 1));
            }
            w!(o, "                if (r.Remaining != 0) throw new WabiProtocolException(\"trailing bytes in host call request\");");
            let call = format!("await {target}.{}Async({}).ConfigureAwait(false)", pascal(&f.name), f.params.iter().map(|(n, _)| host_local(n)).collect::<Vec<_>>().join(", "));
            match &f.ret {
                Ret::Unit => {
                    w!(o, "                {call};");
                    w!(o, "                w.WriteNil();");
                }
                Ret::Value(t) => {
                    w!(o, "                var ret = {call};");
                    w!(o, "                {}", enc(t, "ret", 1));
                }
                Ret::Result { ok, err } => {
                    w!(o, "                try");
                    w!(o, "                {{");
                    match ok {
                        Some(t) => {
                            w!(o, "                    var ret = {call};");
                            w!(o, "                    w.WriteArrayHeader(2); w.WriteUInt(0); {}", enc(t, "ret", 1));
                        }
                        None => {
                            w!(o, "                    {call};");
                            w!(o, "                    w.WriteArrayHeader(2); w.WriteUInt(0); w.WriteNil();");
                        }
                    }
                    w!(o, "                }}");
                    match err {
                        Some(Ty::Named(n)) => {
                            w!(o, "                catch ({} e)", exception_name(n));
                            w!(o, "                {{");
                            w!(o, "                    w = new MsgPackWriter();");
                            w!(o, "                    w.WriteArrayHeader(2); w.WriteUInt(1); WireCodec.Write{}(w, e.Error);", pascal(n));
                            w!(o, "                }}");
                        }
                        Some(t) => {
                            w!(o, "                catch (WabiCallFailedException e) when (e.Error is {} err)", cs(t));
                            w!(o, "                {{");
                            w!(o, "                    w = new MsgPackWriter();");
                            w!(o, "                    w.WriteArrayHeader(2); w.WriteUInt(1); {}", enc(t, "err", 1));
                            w!(o, "                }}");
                        }
                        None => {
                            w!(o, "                catch (WabiCallFailedException)");
                            w!(o, "                {{");
                            w!(o, "                    w = new MsgPackWriter();");
                            w!(o, "                    w.WriteArrayHeader(2); w.WriteUInt(1); w.WriteNil();");
                            w!(o, "                }}");
                        }
                    }
                }
            }
            w!(o, "                break;");
            w!(o, "            }}");
        }
    }
    w!(o, "            default:");
    w!(o, "                throw new WabiNativeException(WabiStatus.ErrUnknownMethod, $\"unknown host method 0x{{methodId:x4}}\", null);");
    w!(o, "        }}");
    w!(o, "        return w.ToArray();");
    w!(o, "    }}");
    w!(o, "}}");
    o
}
