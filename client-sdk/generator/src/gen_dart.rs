//! Dart emitter (Dart 3, usable from Flutter): immutable classes with value
//! equality, enhanced enums, sealed class hierarchies for variants (error types
//! implement Exception), the payload codec, one client class per resource
//! (Future / Stream / CancellationToken) and the dart:ffi bindings of the ABI.

use crate::abi_table::{self, CTy};
use crate::ir::*;
use crate::names::*;

/// Package defaults of the generated Dart build hook (`wabi-gen.conf`).
#[derive(Default)]
pub struct HookDefaults {
    pub prebuilt_dir: Option<String>,
    pub release_url: Option<String>,
}

pub fn emit(m: &Model, hook: &HookDefaults) -> Vec<(String, String)> {
    let mut files = vec![
        ("types.dart".to_string(), types(m)),
        ("wire_codec.dart".to_string(), codec(m)),
        ("abi_constants.dart".to_string(), constants(m)),
        ("native_abi.dart".to_string(), native_abi(m)),
        ("build_hook.dart".to_string(), build_hook(m, hook)),
    ];
    for r in &m.resources {
        files.push((format!("{}.dart", snake(&format!("{}-{}", m.namespace, r.name))), resource(m, r)));
    }
    if m.needs_host_calls() {
        files.push((format!("{}_host.dart", snake(&m.package)), host(m)));
    }
    files
}

fn header(ignores: &str) -> String {
    format!("// Generated by wabi-wit-gen from wit/*.wit — DO NOT EDIT.\n// ignore_for_file: unused_import, {ignores}\n\n")
}

/// Relative, so the same generated code works in any package (wabi_client, gematik_zero, ...).
const RUNTIME: &str = "import 'runtime/runtime.dart';";

fn docs(o: &mut String, d: &Option<String>, ind: &str) {
    if let Some(d) = d {
        for l in d.lines() {
            w!(o, "{ind}/// {}", l.trim_end());
        }
    }
}

const KEYWORDS: &[&str] = &[
    "abstract", "as", "assert", "async", "await", "base", "break", "case", "catch", "class", "const", "continue",
    "covariant", "default", "deferred", "do", "dynamic", "else", "enum", "export", "extends", "extension",
    "external", "factory", "false", "final", "finally", "for", "get", "if", "implements", "import", "in",
    "interface", "is", "late", "library", "mixin", "new", "null", "on", "operator", "part", "required", "rethrow",
    "return", "sealed", "set", "static", "super", "switch", "this", "throw", "true", "try", "typedef", "var",
    "void", "when", "while", "with", "yield", "hashCode", "runtimeType", "toString",
];

/// Members every Dart enum already has.
const ENUM_RESERVED: &[&str] = &["values", "index", "name"];

fn enum_ident(s: &str) -> String {
    let c = ident(s);
    if ENUM_RESERVED.contains(&c.as_str()) { format!("{c}_") } else { c }
}

fn ident(s: &str) -> String {
    let c = camel(s);
    if KEYWORDS.contains(&c.as_str()) { format!("{c}_") } else { c }
}

fn dt(t: &Ty) -> String {
    match t {
        Ty::Bool => "bool".into(),
        Ty::U8 | Ty::U16 | Ty::U32 | Ty::U64 | Ty::S8 | Ty::S16 | Ty::S32 | Ty::S64 | Ty::Char => "int".into(),
        Ty::F32 | Ty::F64 => "double".into(),
        Ty::String => "String".into(),
        Ty::Bytes => "Uint8List".into(),
        Ty::List(t) => format!("List<{}>", dt(t)),
        Ty::Option(t) => format!("{}?", dt(t)),
        Ty::Tuple(ts) => format!("({},)", ts.iter().map(dt).collect::<Vec<_>>().join(", ")),
        Ty::Named(n) => pascal(n),
        Ty::Stream(t) => format!("Stream<{}>", dt(t)),
    }
}

/// Whether `==` on values of this type is value equality (else use wabiEquals).
fn needs_deep_eq(t: &Ty) -> bool {
    match t {
        Ty::Bytes | Ty::List(_) => true,
        Ty::Option(t) => needs_deep_eq(t),
        _ => false,
    }
}

fn enc(t: &Ty, e: &str, d: usize) -> String {
    match t {
        Ty::Bool => format!("w.writeBool({e});"),
        Ty::U8 | Ty::U16 | Ty::U32 | Ty::U64 | Ty::Char => format!("w.writeUint({e});"),
        Ty::S8 | Ty::S16 | Ty::S32 | Ty::S64 => format!("w.writeInt({e});"),
        Ty::F32 => format!("w.writeFloat32({e});"),
        Ty::F64 => format!("w.writeFloat64({e});"),
        Ty::String => format!("w.writeString({e});"),
        Ty::Bytes => format!("w.writeBinary({e});"),
        Ty::List(t) => format!(
            "w.writeArrayHeader({e}.length); for (final x{d} in {e}) {{ {} }}",
            enc(t, &format!("x{d}"), d + 1)
        ),
        Ty::Option(t) => format!(
            "if ({e} case final x{d}?) {{ {} }} else {{ w.writeNil(); }}",
            enc(t, &format!("x{d}"), d + 1)
        ),
        Ty::Tuple(ts) => {
            let mut s = format!("w.writeArrayHeader({});", ts.len());
            for (i, t) in ts.iter().enumerate() {
                s += " ";
                s += &enc(t, &format!("{e}.${}", i + 1), d + 1);
            }
            s
        }
        Ty::Named(n) => format!("WireCodec.write{}(w, {e});", pascal(n)),
        Ty::Stream(_) => unreachable!(),
    }
}

fn dec(t: &Ty, r: &str, d: usize) -> String {
    match t {
        Ty::Bool => format!("{r}.readBool()"),
        Ty::U8 => format!("{r}.readUintMax(0xff)"),
        Ty::U16 => format!("{r}.readUintMax(0xffff)"),
        Ty::U32 => format!("{r}.readUintMax(0xffffffff)"),
        Ty::U64 => format!("{r}.readUint()"),
        Ty::S8 => format!("{r}.readIntRange(-0x80, 0x7f)"),
        Ty::S16 => format!("{r}.readIntRange(-0x8000, 0x7fff)"),
        Ty::S32 => format!("{r}.readIntRange(-0x80000000, 0x7fffffff)"),
        Ty::S64 => format!("{r}.readInt()"),
        Ty::F32 | Ty::F64 => format!("{r}.readFloat()"),
        Ty::Char => format!("{r}.readUintMax(0x10ffff)"),
        Ty::String => format!("{r}.readString()"),
        Ty::Bytes => format!("{r}.readBinary()"),
        Ty::List(t) => format!("{r}.readList((r{d}) => {})", dec(t, &format!("r{d}"), d + 1)),
        Ty::Option(t) => format!("{r}.readOptional((r{d}) => {})", dec(t, &format!("r{d}"), d + 1)),
        Ty::Tuple(ts) => format!(
            "(() {{ {r}.readTupleHeader({}); return ({},); }})()",
            ts.len(),
            ts.iter().map(|t| dec(t, r, d + 1)).collect::<Vec<_>>().join(", ")
        ),
        Ty::Named(n) => format!("WireCodec.read{}({r})", pascal(n)),
        Ty::Stream(_) => unreachable!(),
    }
}

/// Emits ==, hashCode and toString for a class with the given fields.
fn value_members(o: &mut String, cls: &str, fields: &[(String, Ty)]) {
    w!(o, "");
    w!(o, "  @override");
    if fields.is_empty() {
        w!(o, "  bool operator ==(Object other) => other is {cls};");
        w!(o, "");
        w!(o, "  @override");
        w!(o, "  int get hashCode => ({cls}).hashCode;");
        w!(o, "");
        w!(o, "  @override");
        w!(o, "  String toString() => '{cls}()';");
        return;
    }
    let eqs: Vec<String> = fields
        .iter()
        .map(|(n, t)| {
            if needs_deep_eq(t) { format!("wabiEquals({n}, other.{n})") } else { format!("{n} == other.{n}") }
        })
        .collect();
    w!(o, "  bool operator ==(Object other) =>");
    w!(o, "      identical(this, other) || other is {cls} && {};", eqs.join(" && "));
    w!(o, "");
    w!(o, "  @override");
    let hs: Vec<String> = fields
        .iter()
        .map(|(n, t)| if needs_deep_eq(t) { format!("wabiHash({n})") } else { n.clone() })
        .collect();
    if hs.len() == 1 {
        w!(o, "  int get hashCode => Object.hash({cls}, {});", hs[0]);
    } else {
        w!(o, "  int get hashCode => Object.hash({});", hs.join(", "));
    }
    w!(o, "");
    w!(o, "  @override");
    let ts: Vec<String> = fields.iter().map(|(n, _)| format!("{n}: ${n}")).collect();
    w!(o, "  String toString() => '{cls}({})';", ts.join(", "));
}

fn case_class(variant: &str, case: &str) -> String {
    format!("{}{}", pascal(variant), pascal(case))
}

fn types(m: &Model) -> String {
    let mut o = header("constant_identifier_names");
    w!(o, "import 'dart:typed_data';");
    w!(o, "");
    w!(o, "{RUNTIME}");
    w!(o, "");
    for t in &m.types {
        let name = pascal(&t.name);
        docs(&mut o, &t.docs, "");
        let exc = if t.is_error { " implements Exception" } else { "" };
        match &t.kind {
            TypeKind::Record(fields) => {
                w!(o, "final class {name}{exc} {{");
                let ps: Vec<String> = fields
                    .iter()
                    .map(|f| {
                        let req = if matches!(f.ty, Ty::Option(_)) { "" } else { "required " };
                        format!("{req}this.{}", ident(&f.name))
                    })
                    .collect();
                w!(o, "  const {name}({{{}}});", ps.join(", "));
                for f in fields {
                    w!(o, "");
                    docs(&mut o, &f.docs, "  ");
                    w!(o, "  final {} {};", dt(&f.ty), ident(&f.name));
                }
                let fs: Vec<(String, Ty)> = fields.iter().map(|f| (ident(&f.name), f.ty.clone())).collect();
                value_members(&mut o, &name, &fs);
                w!(o, "}}");
            }
            TypeKind::Enum(cases) => {
                w!(o, "enum {name}{exc} {{");
                let cs: Vec<String> = cases.iter().map(|c| format!("  {}({})", enum_ident(&c.name), c.tag)).collect();
                w!(o, "{};", cs.join(",\n"));
                w!(o, "");
                w!(o, "  const {name}(this.wireTag);");
                w!(o, "");
                w!(o, "  /// Stable tag from abi-ids.lock (not the declaration index).");
                w!(o, "  final int wireTag;");
                w!(o, "}}");
            }
            TypeKind::Variant(cases) => {
                w!(o, "sealed class {name}{exc} {{");
                w!(o, "  const {name}();");
                w!(o, "}}");
                for c in cases {
                    let cls = case_class(&t.name, &c.name);
                    w!(o, "");
                    docs(&mut o, &c.docs, "");
                    w!(o, "final class {cls} extends {name} {{");
                    match &c.ty {
                        Some(ty) => {
                            w!(o, "  const {cls}(this.value);");
                            w!(o, "");
                            w!(o, "  final {} value;", dt(ty));
                            value_members(&mut o, &cls, &[("value".into(), ty.clone())]);
                        }
                        None => {
                            w!(o, "  const {cls}();");
                            value_members(&mut o, &cls, &[]);
                        }
                    }
                    w!(o, "}}");
                }
            }
        }
        w!(o, "");
    }
    o
}

fn codec(m: &Model) -> String {
    let mut o = header("constant_identifier_names");
    w!(o, "import 'dart:typed_data';");
    w!(o, "");
    w!(o, "import 'types.dart';");
    w!(o, "{RUNTIME}");
    w!(o, "");
    w!(o, "/// Payload encoding v1 for all contract types (see ABI.md §5). Internal.");
    w!(o, "abstract final class WireCodec {{");
    for t in &m.types {
        let name = pascal(&t.name);
        match &t.kind {
            TypeKind::Record(fields) => {
                w!(o, "  static void write{name}(MsgPackWriter w, {name} v) {{");
                w!(o, "    var n = 0;");
                for f in fields {
                    if matches!(f.ty, Ty::Option(_)) {
                        w!(o, "    if (v.{} != null) n++;", ident(&f.name));
                    } else {
                        w!(o, "    n++;");
                    }
                }
                w!(o, "    w.writeMapHeader(n);");
                for f in fields {
                    let acc = format!("v.{}", ident(&f.name));
                    if let Ty::Option(inner) = &f.ty {
                        w!(o, "    if ({acc} case final f{}?) {{ w.writeUint({}); {} }}", f.tag, f.tag, enc(inner, &format!("f{}", f.tag), 1));
                    } else {
                        w!(o, "    w.writeUint({}); {}", f.tag, enc(&f.ty, &acc, 1));
                    }
                }
                w!(o, "  }}");
                w!(o, "");
                w!(o, "  static {name} read{name}(MsgPackReader r) {{");
                w!(o, "    final n = r.readMapHeader();");
                for f in fields {
                    let local = if matches!(f.ty, Ty::Option(_)) { dt(&f.ty) } else { format!("{}?", dt(&f.ty)) };
                    w!(o, "    {local} f{};", f.tag);
                    w!(o, "    var has{} = false;", f.tag);
                }
                w!(o, "    for (var i = 0; i < n; i++) {{");
                w!(o, "      switch (r.readUint()) {{");
                for f in fields {
                    w!(o, "        case {}:", f.tag);
                    w!(o, "          f{} = {};", f.tag, dec(&f.ty, "r", 1));
                    w!(o, "          has{} = true;", f.tag);
                }
                w!(o, "        default:");
                w!(o, "          r.skip();");
                w!(o, "      }}");
                w!(o, "    }}");
                for f in fields {
                    if matches!(f.ty, Ty::Option(_)) {
                        w!(o, "    assert(has{} || f{} == null);", f.tag, f.tag);
                    } else {
                        w!(o, "    if (!has{}) throw WabiProtocolException(\"{}: missing field '{}'\");", f.tag, t.name, f.name);
                    }
                }
                let args: Vec<String> = fields
                    .iter()
                    .map(|f| {
                        let bang = if matches!(f.ty, Ty::Option(_)) { "" } else { " as " };
                        if bang.is_empty() {
                            format!("{}: f{}", ident(&f.name), f.tag)
                        } else {
                            format!("{}: f{} as {}", ident(&f.name), f.tag, dt(&f.ty))
                        }
                    })
                    .collect();
                w!(o, "    return {name}({});", args.join(", "));
                w!(o, "  }}");
            }
            TypeKind::Enum(cases) => {
                w!(o, "  static void write{name}(MsgPackWriter w, {name} v) => w.writeUint(v.wireTag);");
                w!(o, "");
                w!(o, "  static {name} read{name}(MsgPackReader r) {{");
                w!(o, "    final tag = r.readUint();");
                w!(o, "    return switch (tag) {{");
                for c in cases {
                    w!(o, "      {} => {name}.{},", c.tag, enum_ident(&c.name));
                }
                w!(o, "      _ => throw WabiProtocolException(\"unknown case tag $tag for '{}'\"),", t.name);
                w!(o, "    }};");
                w!(o, "  }}");
            }
            TypeKind::Variant(cases) => {
                w!(o, "  static void write{name}(MsgPackWriter w, {name} v) {{");
                w!(o, "    switch (v) {{");
                for c in cases {
                    let cls = case_class(&t.name, &c.name);
                    match &c.ty {
                        Some(ty) => {
                            w!(o, "      case {cls}(:final value):");
                            w!(o, "        w.writeArrayHeader(2);");
                            w!(o, "        w.writeUint({});", c.tag);
                            w!(o, "        {}", enc(ty, "value", 1));
                        }
                        None => {
                            w!(o, "      case {cls}():");
                            w!(o, "        w.writeArrayHeader(1);");
                            w!(o, "        w.writeUint({});", c.tag);
                        }
                    }
                }
                w!(o, "    }}");
                w!(o, "  }}");
                w!(o, "");
                w!(o, "  static {name} read{name}(MsgPackReader r) {{");
                w!(o, "    final n = r.readArrayHeader();");
                w!(o, "    if (n == 0) throw WabiProtocolException('{}: empty variant');", t.name);
                w!(o, "    final tag = r.readUint();");
                w!(o, "    final {name} v;");
                w!(o, "    final int used;");
                w!(o, "    switch (tag) {{");
                for c in cases {
                    let cls = case_class(&t.name, &c.name);
                    match &c.ty {
                        Some(ty) => {
                            w!(o, "      case {} when n >= 2:", c.tag);
                            w!(o, "        v = {cls}({});", dec(ty, "r", 1));
                            w!(o, "        used = 2;");
                        }
                        None => {
                            w!(o, "      case {}:", c.tag);
                            w!(o, "        v = const {cls}();");
                            w!(o, "        used = 1;");
                        }
                    }
                }
                w!(o, "      default:");
                w!(o, "        throw WabiProtocolException(\"unknown case tag $tag for '{}'\");", t.name);
                w!(o, "    }}");
                w!(o, "    for (var i = used; i < n; i++) {{");
                w!(o, "      r.skip();");
                w!(o, "    }}");
                w!(o, "    return v;");
                w!(o, "  }}");
            }
        }
        w!(o, "");
    }
    w!(o, "}}");
    o
}

fn constants(m: &Model) -> String {
    let (maj, min, _) = m.version_triple();
    let mut o = header("constant_identifier_names");
    w!(o, "/// The contract this SDK was generated from.");
    w!(o, "abstract final class Contract {{");
    w!(o, "  static const id = '{}';", m.contract_id());
    w!(o, "  static const package = '{}:{}';", m.namespace, m.package);
    w!(o, "  static const major = {maj};");
    w!(o, "  static const minor = {min};");
    w!(o, "");
    w!(o, "  /// Library name and prefix of this package's ABI symbols ({0}_call_sync, ...).", m.symbol_prefix());
    w!(o, "  static const library = '{}';", m.symbol_prefix());
    w!(o, "  static const symbolPrefix = '{}_';", m.symbol_prefix());
    w!(o, "}}");
    w!(o, "");
    w!(o, "/// Stable method ids (wit/abi-ids.lock).");
    w!(o, "abstract final class MethodIds {{");
    for r in &m.resources {
        for f in r.ctor.iter().chain(&r.methods) {
            w!(o, "  static const {}{} = {:#06x};", camel(&r.name), pascal(&f.name), f.id);
        }
    }
    for h in &m.imports {
        for f in &h.funcs {
            w!(o, "  static const {}{} = {:#06x}; // import, answered by the app", camel(&h.name), pascal(&f.name), f.id);
        }
    }
    w!(o, "}}");
    w!(o, "");
    w!(o, "/// ABI {}.{} status codes (abi/wabi_abi.h).", abi_table::ABI_MAJOR, abi_table::ABI_MINOR);
    w!(o, "abstract final class WabiStatus {{");
    for (n, v) in abi_table::STATUSES {
        w!(o, "  static const {} = {v};", camel(&n.to_ascii_lowercase().replace('_', "-")));
    }
    w!(o, "}}");
    w!(o, "");
    w!(o, "/// ABI capability bits.");
    w!(o, "abstract final class WabiCapabilities {{");
    w!(o, "  static const abiMajor = {};", abi_table::ABI_MAJOR);
    w!(o, "  /// Minimum ABI minor this package needs (1 if it uses host calls).");
    w!(o, "  static const abiMinor = {};", m.required_abi_minor());
    w!(o, "  static const requiresHostCalls = {};", m.needs_host_calls());
    for (n, bit) in abi_table::CAPABILITIES {
        w!(o, "  static const {} = 1 << {bit};", camel(&n.to_ascii_lowercase().replace('_', "-")));
    }
    w!(o, "}}");
    o
}

fn ffi_native(t: CTy) -> &'static str {
    match t {
        CTy::Void => "Void",
        CTy::U32 => "Uint32",
        CTy::U64 | CTy::Handle => "Uint64",
        CTy::Status => "Int32",
        CTy::Bytes => "WabiBytes",
        CTy::Buffer => "WabiBuffer",
        CTy::BufferPtr => "Pointer<WabiBuffer>",
        CTy::HandlePtr => "Pointer<Uint64>",
        CTy::Callback => "Pointer<NativeFunction<WabiFutureCallback>>",
        CTy::VoidPtr => "Pointer<Void>",
        CTy::CStr => "Pointer<Utf8>",
        CTy::HostHandler => "Pointer<NativeFunction<WabiHostHandler>>",
    }
}

fn ffi_dart(t: CTy) -> &'static str {
    match t {
        CTy::Void => "void",
        CTy::U32 | CTy::U64 | CTy::Handle | CTy::Status => "int",
        other => ffi_native(other),
    }
}

fn native_abi(m: &Model) -> String {
    let mut o = header("non_constant_identifier_names, camel_case_types");
    w!(o, "import 'dart:ffi';");
    w!(o, "");
    w!(o, "import 'package:ffi/ffi.dart';");
    w!(o, "");
    w!(o, "/// struct wabi_bytes {{ const uint8_t* ptr; size_t len; }} — borrowed, host -> core.");
    w!(o, "final class WabiBytes extends Struct {{");
    w!(o, "  external Pointer<Uint8> ptr;");
    w!(o, "  @Size()");
    w!(o, "  external int len;");
    w!(o, "}}");
    w!(o, "");
    w!(o, "/// struct wabi_buffer {{ uint8_t* ptr; size_t len; }} — owned by the host, free with wabi_buffer_free.");
    w!(o, "final class WabiBuffer extends Struct {{");
    w!(o, "  external Pointer<Uint8> ptr;");
    w!(o, "  @Size()");
    w!(o, "  external int len;");
    w!(o, "}}");
    w!(o, "");
    w!(o, "/// void (*wabi_future_callback)(void* user_data, uint64_t future)");
    w!(o, "typedef WabiFutureCallback = Void Function(Pointer<Void>, Uint64);");
    w!(o, "");
    w!(o, "/// void (*wabi_host_handler)(void*, uint32_t method_id, const uint8_t* req, size_t len, uint64_t call) — ABI 1.1");
    w!(o, "typedef WabiHostHandler = Void Function(Pointer<Void>, Uint32, Pointer<Uint8>, Size, Uint64);");
    w!(o, "");
    w!(o, "/// dart:ffi bindings of the generic Wabi native ABI {}.{}. This list does not grow", abi_table::ABI_MAJOR, abi_table::ABI_MINOR);
    w!(o, "/// when WIT functions are added: those are addressed by method id.");
    w!(o, "final class NativeAbi {{");
    w!(o, "  NativeAbi(DynamicLibrary lib)");
    let inits: Vec<String> = abi_table::FUNCTIONS
        .iter()
        .map(|f| {
            let np: Vec<&str> = f.params.iter().map(|(t, _)| ffi_native(*t)).collect();
            let dp: Vec<&str> = f.params.iter().map(|(t, _)| ffi_dart(*t)).collect();
            let optional = if f.host_call {
                // ABI 1.1, optional: null unless the core has WABI_CAP_HOST_CALLS
                format!("lib.providesSymbol('{}') ? ", abi_table::symbol(&m.symbol_prefix(), f.name))
            } else {
                String::new()
            };
            format!(
                "        {} = {optional}lib.lookupFunction<{} Function({}), {} Function({})>('{}'){}",
                f.name,
                ffi_native(f.ret),
                np.join(", "),
                ffi_dart(f.ret),
                dp.join(", "),
                abi_table::symbol(&m.symbol_prefix(), f.name),
                if f.host_call { " : null" } else { "" }
            )
        })
        .collect();
    w!(o, "      : {};", inits.join(",\n").trim_start());
    w!(o, "");
    w!(o, "  /// Binds the core that `hook/build.dart` bundles as this package's native code");
    w!(o, "  /// asset (Dart native assets). The asset id is the URI of this library,");
    w!(o, "  /// `package:<dart package>/src/generated/native_abi.dart`, the default of `@Native`.");
    w!(o, "  /// Without such an asset the symbols are looked up in the process (e.g. a statically");
    w!(o, "  /// linked iOS xcframework). Throws [ArgumentError] if a required symbol is missing.");
    w!(o, "  factory NativeAbi.asset() {{");
    w!(o, "    // Resolve every required symbol now, so a wrong library fails here and not on first use.");
    for f in abi_table::FUNCTIONS.iter().filter(|f| !f.host_call) {
        w!(o, "    Native.addressOf<NativeFunction<{}>>(_{});", native_sig(f), f.name);
    }
    w!(o, "    return NativeAbi._asset();");
    w!(o, "  }}");
    w!(o, "");
    let inits: Vec<String> = abi_table::FUNCTIONS
        .iter()
        .map(|f| {
            if f.host_call {
                // ABI 1.1, optional: null unless the core exports it
                format!("        {n} = _provides(() => Native.addressOf<NativeFunction<{}>>(_{n})) ? _{n} : null", native_sig(f), n = f.name)
            } else {
                format!("        {n} = _{n}", n = f.name)
            }
        })
        .collect();
    w!(o, "  NativeAbi._asset()");
    w!(o, "      : {};", inits.join(",\n").trim_start());
    w!(o, "");
    w!(o, "  static bool _provides(Pointer<NativeFunction> Function() resolve) {{");
    w!(o, "    try {{");
    w!(o, "      resolve();");
    w!(o, "      return true;");
    w!(o, "    }} on ArgumentError {{");
    w!(o, "      return false;");
    w!(o, "    }}");
    w!(o, "  }}");
    w!(o, "");
    for f in abi_table::FUNCTIONS {
        let dp: Vec<String> = f.params.iter().map(|(t, n)| format!("{} {}", ffi_dart(*t), n)).collect();
        let opt = if f.host_call { "?" } else { "" };
        w!(o, "  final {} Function({}){opt} {};", ffi_dart(f.ret), dp.join(", "), f.name);
    }
    w!(o, "}}");
    w!(o, "");
    w!(o, "// The same functions as @Native externals of the code asset (NativeAbi.asset).");
    for f in abi_table::FUNCTIONS {
        let dp: Vec<String> = f.params.iter().map(|(t, n)| format!("{} {}", ffi_dart(*t), n)).collect();
        w!(o, "");
        w!(o, "@Native<{}>(symbol: '{}')", native_sig(f), abi_table::symbol(&m.symbol_prefix(), f.name));
        w!(o, "external {} _{}({});", ffi_dart(f.ret), f.name, dp.join(", "));
    }
    o
}

/// The dart:ffi native signature of an ABI function, e.g. `Int32 Function(Uint64)`.
fn native_sig(f: &abi_table::AbiFn) -> String {
    let np: Vec<&str> = f.params.iter().map(|(t, _)| ffi_native(*t)).collect();
    format!("{} Function({})", ffi_native(f.ret), np.join(", "))
}

fn resource(m: &Model, r: &Resource) -> String {
    let cls = crate::gen_csharp::class_name(m, r);
    let rid = camel(&r.name);
    let mut o = header("constant_identifier_names");
    w!(o, "import 'dart:async';");
    w!(o, "import 'dart:typed_data';");
    w!(o, "");
    w!(o, "import 'abi_constants.dart';");
    w!(o, "import 'types.dart';");
    w!(o, "import 'wire_codec.dart';");
    w!(o, "{RUNTIME}");
    w!(o, "");
    docs(&mut o, &r.docs, "");
    w!(o, "final class {cls} {{");
    if let Some(c) = &r.ctor {
        let ps: Vec<String> = c.params.iter().map(|(n, t)| format!("{} {}", dt(t), ident(n))).collect();
        docs(&mut o, &c.docs, "  ");
        w!(o, "  /// Uses [NativeBackend.shared] unless another [backend] (component model,");
        w!(o, "  /// test double) is given. Throws [WabiIncompatibleLibraryException] if the");
        w!(o, "  /// native core is missing or incompatible.");
        w!(o, "  {cls}({}{}{{ClientBackend? backend}}) : _backend = backend ?? NativeBackend.shared {{", ps.join(", "), if ps.is_empty() { "" } else { ", " });
        request(&mut o, &c.params, "    ");
        w!(o, "    final r = MsgPackReader(_backend.callSync(0, MethodIds.{rid}{}, w.takeBytes()));", pascal(&c.name));
        w!(o, "    _handle = ObjectHandle(this, _backend, r.readUint());");
        w!(o, "  }}");
        w!(o, "");
    }
    w!(o, "  final ClientBackend _backend;");
    w!(o, "  late final ObjectHandle _handle;");
    w!(o, "");
    for f in &r.methods {
        docs(&mut o, &f.docs, "  ");
        let ps: Vec<String> = f.params.iter().map(|(n, t)| format!("{} {}", dt(t), ident(n))).collect();
        let mid = format!("MethodIds.{rid}{}", pascal(&f.name));
        let name = ident(&f.name);
        if let Ret::Value(Ty::Stream(item)) = &f.ret {
            w!(o, "  ///");
            w!(o, "  /// Single-subscription, pull-based stream: the native subscription opens on");
            w!(o, "  /// `listen` and is released when the subscription is cancelled or done.");
            w!(o, "  Stream<{}> {name}({}) => _backend.openStream(() {{", dt(item), ps.join(", "));
            request(&mut o, &f.params, "        ");
            w!(o, "        return MsgPackReader(_backend.callSync(_handle.value, {mid}, w.takeBytes())).readUint();");
            w!(o, "      }}).map((bytes) => {});", dec(item, "MsgPackReader(bytes)", 1));
            w!(o, "");
            continue;
        }
        let ok = match &f.ret {
            Ret::Unit | Ret::Result { ok: None, .. } => None,
            Ret::Value(t) | Ret::Result { ok: Some(t), .. } => Some(dt(t)),
        };
        if f.is_async {
            let mut ps = ps.clone();
            ps.push("{CancellationToken? cancellationToken}".into());
            w!(o, "  Future<{}> {name}({}) async {{", ok.clone().unwrap_or("void".into()), ps.join(", "));
            request(&mut o, &f.params, "    ");
            w!(o, "    final r = MsgPackReader(await _backend.callAsync(_handle.value, {mid}, w.takeBytes(), cancellationToken: cancellationToken));");
        } else {
            w!(o, "  {} {name}({}) {{", ok.clone().unwrap_or("void".into()), ps.join(", "));
            request(&mut o, &f.params, "    ");
            w!(o, "    final r = MsgPackReader(_backend.callSync(_handle.value, {mid}, w.takeBytes()));");
        }
        match &f.ret {
            Ret::Unit => {}
            Ret::Value(t) => w!(o, "    return {};", dec(t, "r", 1)),
            Ret::Result { ok, err } => {
                w!(o, "    if (r.readResultTag() != 0) {{");
                match err {
                    Some(Ty::Named(n)) if m.types.iter().any(|t| &t.name == n && t.is_error) => {
                        w!(o, "      throw WireCodec.read{}(r);", pascal(n))
                    }
                    Some(t) => w!(o, "      throw WabiCallFailedException({});", dec(t, "r", 1)),
                    None => w!(o, "      throw WabiCallFailedException(null);"),
                }
                w!(o, "    }}");
                match ok {
                    Some(t) => w!(o, "    return {};", dec(t, "r", 1)),
                    None => w!(o, "    r.readNil();"),
                }
            }
        }
        w!(o, "  }}");
        w!(o, "");
    }
    w!(o, "  /// Releases the native object now (otherwise when garbage collected).");
    w!(o, "  /// In-flight calls fail, event streams end. Idempotent.");
    w!(o, "  void close() => _handle.close();");
    w!(o, "}}");
    o
}

fn request(o: &mut String, params: &[(String, Ty)], ind: &str) {
    w!(o, "{ind}final w = MsgPackWriter()..writeArrayHeader({});", params.len());
    for (n, t) in params {
        w!(o, "{ind}{}", enc(t, &ident(n), 1));
    }
}

fn host_ret(r: &Ret) -> String {
    match r {
        Ret::Unit | Ret::Result { ok: None, .. } => "Future<void>".into(),
        Ret::Value(t) | Ret::Result { ok: Some(t), .. } => format!("Future<{}>", dt(t)),
    }
}

/// App-side host calls (ABI 1.1): one interface per imported WIT interface,
/// plus `<Package>Host.register(...)` which decodes requests and encodes answers.
fn host(m: &Model) -> String {
    let cls = format!("{}Host", pascal(&m.package));
    let mut o = header("constant_identifier_names");
    w!(o, "import 'dart:async';");
    w!(o, "import 'dart:typed_data';");
    w!(o, "");
    w!(o, "import 'abi_constants.dart';");
    w!(o, "import 'types.dart';");
    w!(o, "import 'wire_codec.dart';");
    w!(o, "{RUNTIME}");
    for h in &m.imports {
        w!(o, "");
        docs(&mut o, &h.docs, "");
        w!(o, "///");
        w!(o, "/// WIT import `{}`: implemented by the APP, called by the core. Domain", h.name);
        w!(o, "/// errors are reported by throwing the generated error type.");
        w!(o, "abstract interface class {} {{", pascal(&h.name));
        for f in &h.funcs {
            docs(&mut o, &f.docs, "  ");
            let ps: Vec<String> = f.params.iter().map(|(n, t)| format!("{} {}", dt(t), ident(n))).collect();
            w!(o, "  {} {}({});", host_ret(&f.ret), ident(&f.name), ps.join(", "));
        }
        w!(o, "}}");
    }
    let params: Vec<String> = m.imports.iter().map(|h| format!("{} {}", pascal(&h.name), ident(&h.name))).collect();
    let args: Vec<String> = m.imports.iter().map(|h| ident(&h.name)).collect();
    w!(o, "");
    w!(o, "/// Connects the app's implementations of the WIT imports of {} to the core.", m.contract_id());
    w!(o, "abstract final class {cls} {{");
    w!(o, "  /// Call once at startup, before the core needs the app (process-wide).");
    w!(o, "  static void register({}, {{NativeBackend? backend}}) {{", params.join(", "));
    w!(o, "    (backend ?? NativeBackend.shared).registerHost((methodId, request) => _dispatch({}, methodId, request));", args.join(", "));
    w!(o, "  }}");
    w!(o, "");
    w!(o, "  /// Removes the registration.");
    w!(o, "  static void unregister({{NativeBackend? backend}}) => (backend ?? NativeBackend.shared).unregisterHost();");
    w!(o, "");
    w!(o, "  static Future<Uint8List> _dispatch({}, int methodId, Uint8List request) async {{", params.join(", "));
    w!(o, "    final r = MsgPackReader(request);");
    w!(o, "    final w = MsgPackWriter();");
    w!(o, "    switch (methodId) {{");
    for h in &m.imports {
        let target = ident(&h.name);
        for f in &h.funcs {
            w!(o, "      case MethodIds.{}{}:", camel(&h.name), pascal(&f.name));
            w!(o, "        r.readTupleHeader({});", f.params.len());
            let mut locals = vec![];
            for (n, t) in &f.params {
                let l = format!("{}{}", ident(&f.name), pascal(n)); // unique per case
                w!(o, "        final {l} = {};", dec(t, "r", 1));
                locals.push(l);
            }
            w!(o, "        if (r.remaining != 0) throw WabiProtocolException('trailing bytes in host call request');");
            let call = format!("await {target}.{}({})", ident(&f.name), locals.join(", "));
            match &f.ret {
                Ret::Unit => {
                    w!(o, "        {call};");
                    w!(o, "        w.writeNil();");
                }
                Ret::Value(t) => {
                    w!(o, "        final ret = {call};");
                    w!(o, "        {}", enc(t, "ret", 1));
                }
                Ret::Result { ok, err } => {
                    w!(o, "        try {{");
                    match ok {
                        Some(t) => {
                            w!(o, "          final ret = {call};");
                            w!(o, "          w..writeArrayHeader(2)..writeUint(0);");
                            w!(o, "          {}", enc(t, "ret", 1));
                        }
                        None => {
                            w!(o, "          {call};");
                            w!(o, "          w..writeArrayHeader(2)..writeUint(0)..writeNil();");
                        }
                    }
                    match err {
                        Some(Ty::Named(n)) => {
                            w!(o, "        }} on {} catch (e) {{", pascal(n));
                            w!(o, "          w..writeArrayHeader(2)..writeUint(1);");
                            w!(o, "          WireCodec.write{}(w, e);", pascal(n));
                        }
                        Some(t) => {
                            w!(o, "        }} on WabiCallFailedException catch (e) {{");
                            w!(o, "          if (e.error is! {}) rethrow;", dt(t));
                            w!(o, "          final err = e.error as {};", dt(t));
                            w!(o, "          w..writeArrayHeader(2)..writeUint(1);");
                            w!(o, "          {}", enc(t, "err", 1));
                        }
                        None => {
                            w!(o, "        }} on WabiCallFailedException {{");
                            w!(o, "          w..writeArrayHeader(2)..writeUint(1)..writeNil();");
                        }
                    }
                    w!(o, "        }}");
                }
            }
        }
    }
    w!(o, "      default:");
    w!(o, "        throw WabiNativeException(WabiStatus.errUnknownMethod, 'unknown host method 0x${{methodId.toRadixString(16)}}');");
    w!(o, "    }}");
    w!(o, "    return w.takeBytes();");
    w!(o, "  }}");
    w!(o, "}}");
    o
}

/// The package's Dart native-assets build hook; `hook/build.dart` only forwards to it.
fn build_hook(m: &Model, hook: &HookDefaults) -> String {
    let mut o = header("directives_ordering");
    w!(o, "import 'runtime/native_assets.dart';");
    w!(o, "import 'abi_constants.dart';");
    w!(o, "");
    w!(o, "/// Build hook of the {} SDK (Dart native assets): bundles the core library", m.contract_id());
    w!(o, "/// `{}` for the target platform. Called from the package's `hook/build.dart`;", m.symbol_prefix().trim_end_matches('_'));
    w!(o, "/// configuration (user-defines `library`, `prebuilt_dir`, `release_url`, `required`)");
    w!(o, "/// is described at [buildNativeCore].");
    w!(o, "Future<void> buildHook(List<String> args) => buildNativeCore(");
    w!(o, "      args,");
    w!(o, "      library: Contract.library,");
    // raw Dart string: no escapes or interpolation to worry about except the quote itself
    let lit = |v: &Option<String>| v.as_ref().map(|s| format!("r'{}'", s.replace('\'', ""))).unwrap_or_else(|| "null".into());
    w!(o, "      defaultPrebuiltDir: {},", lit(&hook.prebuilt_dir));
    w!(o, "      defaultReleaseUrl: {},", lit(&hook.release_url));
    w!(o, "    );");
    o
}
