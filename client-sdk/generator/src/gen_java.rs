pub use crate::gen_java_core::emit_core;

/// Package of the hand-written runtime (and its generated glue).
const RT_PKG: &str = "com.acme.client.runtime";
const RT_DIR: &str = "com/acme/client/runtime";

/// `acme:client` -> `com.acme.client`, `gematik:zero` -> `com.gematik.zero`
pub(crate) fn pkg(m: &Model) -> String {
    format!("com.{}.{}", snake(&m.namespace), snake(&m.package))
}

pub fn emit(m: &Model) -> Vec<(String, String)> {
    let dir = pkg(m).replace('.', "/");
    let mut files = vec![];
    for t in &m.types {
        files.push((format!("{dir}/{}.java", pascal(&t.name)), type_file(m, t)));
        if t.is_error {
            files.push((format!("{dir}/{}.java", exception_name(&t.name)), exception_file(m, t)));
        }
    }
    files.push((format!("{dir}/WireCodec.java"), codec(m)));
    files.push((format!("{dir}/MethodIds.java"), method_ids(m)));
    for r in &m.resources {
        files.push((format!("{dir}/{}.java", class_name(m, r)), resource(m, r)));
    }
    for h in &m.imports {
        files.push((format!("{dir}/{}.java", pascal(&h.name)), host_interface(m, h)));
    }
    if m.needs_host_calls() {
        files.push((format!("{dir}/{}.java", host_class(m)), host(m)));
    }
    files.push((format!("{RT_DIR}/NativeAbi.java"), native_abi(m)));
    files.push((format!("{RT_DIR}/AbiConstants.java"), abi_constants(m)));
    files.push((format!("{RT_DIR}/Contract.java"), contract(m)));
    files
}

pub(crate) fn header(pkg: &str) -> String {
    format!("// Generated by acme-wit-gen from wit/*.wit — DO NOT EDIT.\npackage {pkg};\n\n")
}

fn class_name(m: &Model, r: &Resource) -> String {
    crate::gen_csharp::class_name(m, r)
}

pub(crate) fn docs(o: &mut String, d: &Option<String>, ind: &str) {
    if let Some(d) = d {
        w!(o, "{ind}/**");
        for l in d.lines() {
            w!(o, "{ind} * {}", l.trim_end().replace("*/", "*&#47;"));
        }
        w!(o, "{ind} */");
    }
}

const KEYWORDS: &[&str] = &[
    "abstract", "assert", "boolean", "break", "byte", "case", "catch", "char", "class", "const", "continue",
    "default", "do", "double", "else", "enum", "extends", "final", "finally", "float", "for", "goto", "if",
    "implements", "import", "instanceof", "int", "interface", "long", "native", "new", "package", "private",
    "protected", "public", "return", "short", "static", "strictfp", "super", "switch", "synchronized", "this",
    "throw", "throws", "transient", "try", "void", "volatile", "while", "record", "var", "yield", "sealed",
];

pub(crate) fn ident(s: &str) -> String {
    let c = camel(s);
    if KEYWORDS.contains(&c.as_str()) { format!("{c}_") } else { c }
}

pub(crate) fn jt(t: &Ty) -> String {
    match t {
        Ty::Bool => "boolean".into(),
        Ty::U8 | Ty::S8 => "byte".into(),
        Ty::U16 | Ty::S16 => "short".into(),
        Ty::U32 | Ty::S32 | Ty::Char => "int".into(),
        Ty::U64 | Ty::S64 => "long".into(),
        Ty::F32 => "float".into(),
        Ty::F64 => "double".into(),
        Ty::String => "String".into(),
        Ty::Bytes => "byte[]".into(),
        Ty::List(t) => format!("java.util.List<{}>", boxed(t)),
        Ty::Option(t) => format!("java.util.Optional<{}>", boxed(t)),
        Ty::Tuple(_) => unimplemented!("tuples are not supported by the Java emitter yet"),
        Ty::Named(n) => pascal(n),
        Ty::Stream(t) => format!("java.util.concurrent.Flow.Publisher<{}>", boxed(t)),
    }
}

pub(crate) fn boxed(t: &Ty) -> String {
    match t {
        Ty::Bool => "Boolean".into(),
        Ty::U8 | Ty::S8 => "Byte".into(),
        Ty::U16 | Ty::S16 => "Short".into(),
        Ty::U32 | Ty::S32 | Ty::Char => "Integer".into(),
        Ty::U64 | Ty::S64 => "Long".into(),
        Ty::F32 => "Float".into(),
        Ty::F64 => "Double".into(),
        t => jt(t),
    }
}

fn is_primitive(t: &Ty) -> bool {
    !matches!(boxed(t).as_str(), s if s == jt(t))
}

pub(crate) fn enc(t: &Ty, e: &str, d: usize) -> String {
    match t {
        Ty::Bool => format!("w.writeBool({e});"),
        Ty::U8 => format!("w.writeUInt(Byte.toUnsignedLong({e}));"),
        Ty::U16 => format!("w.writeUInt(Short.toUnsignedLong({e}));"),
        Ty::U32 => format!("w.writeUInt(Integer.toUnsignedLong({e}));"),
        Ty::U64 => format!("w.writeUInt64({e});"),
        Ty::S8 | Ty::S16 | Ty::S32 | Ty::S64 => format!("w.writeInt({e});"),
        Ty::F32 => format!("w.writeFloat32({e});"),
        Ty::F64 => format!("w.writeFloat64({e});"),
        Ty::Char => format!("w.writeUInt({e});"),
        Ty::String => format!("w.writeString({e});"),
        Ty::Bytes => format!("w.writeBinary({e});"),
        Ty::List(t) => format!(
            "w.writeArrayHeader({e}.size()); for (var x{d} : {e}) {{ {} }}",
            enc(t, &format!("x{d}"), d + 1)
        ),
        Ty::Option(t) => format!(
            "if ({e}.isPresent()) {{ var x{d} = {e}.get(); {} }} else {{ w.writeNil(); }}",
            enc(t, &format!("x{d}"), d + 1)
        ),
        Ty::Named(n) => format!("WireCodec.write{}(w, {e});", pascal(n)),
        Ty::Tuple(_) | Ty::Stream(_) => unreachable!(),
    }
}

pub(crate) fn dec(t: &Ty, r: &str, d: usize) -> String {
    match t {
        Ty::Bool => format!("{r}.readBool()"),
        Ty::U8 => format!("(byte) {r}.readUIntMax(0xFFL)"),
        Ty::U16 => format!("(short) {r}.readUIntMax(0xFFFFL)"),
        Ty::U32 => format!("(int) {r}.readUIntMax(0xFFFFFFFFL)"),
        Ty::U64 => format!("{r}.readUInt64()"),
        Ty::S8 => format!("(byte) {r}.readIntRange(Byte.MIN_VALUE, Byte.MAX_VALUE)"),
        Ty::S16 => format!("(short) {r}.readIntRange(Short.MIN_VALUE, Short.MAX_VALUE)"),
        Ty::S32 => format!("(int) {r}.readIntRange(Integer.MIN_VALUE, Integer.MAX_VALUE)"),
        Ty::S64 => format!("{r}.readInt64()"),
        Ty::F32 => format!("{r}.readFloat32()"),
        Ty::F64 => format!("{r}.readFloat64()"),
        Ty::Char => format!("(int) {r}.readUIntMax(0x10FFFFL)"),
        Ty::String => format!("{r}.readString()"),
        Ty::Bytes => format!("{r}.readBinary()"),
        Ty::List(t) => format!("{r}.readList(r{d} -> {})", dec(t, &format!("r{d}"), d + 1)),
        Ty::Option(t) => format!("{r}.readOptional(r{d} -> {})", dec(t, &format!("r{d}"), d + 1)),
        Ty::Named(n) => format!("WireCodec.read{}({r})", pascal(n)),
        Ty::Tuple(_) | Ty::Stream(_) => unreachable!(),
    }
}

fn default_value(t: &Ty) -> &'static str {
    match t {
        Ty::Bool => "false",
        Ty::Option(_) => "java.util.Optional.empty()",
        t if is_primitive(t) => "0",
        _ => "null",
    }
}

fn type_file(m: &Model, t: &TypeDecl) -> String {
    let name = pascal(&t.name);
    let mut o = header(&pkg(m));
    docs(&mut o, &t.docs, "");
    match &t.kind {
        TypeKind::Record(fields) => {
            let comps: Vec<String> = fields.iter().map(|f| format!("{} {}", jt(&f.ty), ident(&f.name))).collect();
            w!(o, "public record {name}({}) {{", comps.join(", "));
            w!(o, "    public {name} {{");
            for f in fields.iter().filter(|f| !is_primitive(&f.ty)) {
                w!(o, "        java.util.Objects.requireNonNull({}, \"{}\");", ident(&f.name), f.name);
            }
            w!(o, "    }}");
            w!(o, "}}");
        }
        TypeKind::Enum(cases) => {
            w!(o, "public enum {name} {{");
            let cs: Vec<String> = cases.iter().map(|c| format!("    {}({})", screaming(&c.name), c.tag)).collect();
            w!(o, "{};", cs.join(",\n"));
            w!(o, "");
            w!(o, "    final int wireTag;");
            w!(o, "");
            w!(o, "    {name}(int wireTag) {{");
            w!(o, "        this.wireTag = wireTag;");
            w!(o, "    }}");
            w!(o, "}}");
        }
        TypeKind::Variant(cases) => {
            let permits: Vec<String> = cases.iter().map(|c| format!("{name}.{}", pascal(&c.name))).collect();
            w!(o, "public sealed interface {name} permits {} {{", permits.join(", "));
            for c in cases {
                docs(&mut o, &c.docs, "    ");
                match &c.ty {
                    Some(t) => {
                        w!(o, "    record {}({} value) implements {name} {{", pascal(&c.name), jt(t));
                        if !is_primitive(t) {
                            w!(o, "        public {} {{ java.util.Objects.requireNonNull(value, \"value\"); }}", pascal(&c.name));
                        }
                        w!(o, "    }}");
                    }
                    None => w!(o, "    record {}() implements {name} {{}}", pascal(&c.name)),
                }
            }
            w!(o, "}}");
        }
    }
    o
}

fn exception_file(m: &Model, t: &TypeDecl) -> String {
    let name = pascal(&t.name);
    let ex = exception_name(&t.name);
    let mut o = header(&pkg(m));
    w!(o, "/** Thrown (inside CompletionException/ExecutionException for futures) when an operation fails with a {{@link {name}}}. */");
    w!(o, "public final class {ex} extends com.acme.client.runtime.AcmeException {{");
    w!(o, "    private final {name} error;");
    w!(o, "");
    w!(o, "    public {ex}({name} error) {{");
    w!(o, "        super(String.valueOf(error));");
    w!(o, "        this.error = error;");
    w!(o, "    }}");
    w!(o, "");
    w!(o, "    public {name} error() {{");
    w!(o, "        return error;");
    w!(o, "    }}");
    w!(o, "}}");
    o
}

fn codec(m: &Model) -> String {
    let mut o = header(&pkg(m));
    w!(o, "import com.acme.client.runtime.AcmeProtocolException;");
    w!(o, "import com.acme.client.runtime.MsgPackReader;");
    w!(o, "import com.acme.client.runtime.MsgPackWriter;");
    w!(o, "");
    w!(o, "/** Payload encoding v1 for all contract types (see ABI.md §5). */");
    w!(o, "final class WireCodec {{");
    w!(o, "    private WireCodec() {{}}");
    for t in &m.types {
        let name = pascal(&t.name);
        w!(o, "");
        match &t.kind {
            TypeKind::Record(fields) => {
                w!(o, "    static void write{name}(MsgPackWriter w, {name} v) {{");
                w!(o, "        int n = 0;");
                for f in fields {
                    if matches!(f.ty, Ty::Option(_)) {
                        w!(o, "        if (v.{}().isPresent()) n++;", ident(&f.name));
                    } else {
                        w!(o, "        n++;");
                    }
                }
                w!(o, "        w.writeMapHeader(n);");
                for f in fields {
                    let acc = format!("v.{}()", ident(&f.name));
                    if let Ty::Option(inner) = &f.ty {
                        w!(o, "        if ({acc}.isPresent()) {{ w.writeUInt({}); var f{} = {acc}.get(); {} }}", f.tag, f.tag, enc(inner, &format!("f{}", f.tag), 1));
                    } else {
                        w!(o, "        w.writeUInt({}); {}", f.tag, enc(&f.ty, &acc, 1));
                    }
                }
                w!(o, "    }}");
                w!(o, "");
                w!(o, "    static {name} read{name}(MsgPackReader r) {{");
                w!(o, "        int n = r.readMapHeader();");
                for f in fields {
                    w!(o, "        {} f{} = {}; boolean has{} = false;", jt(&f.ty), f.tag, default_value(&f.ty), f.tag);
                }
                w!(o, "        for (int i = 0; i < n; i++) {{");
                w!(o, "            switch ((int) r.readUIntMax(0xFFFFFFFFL)) {{");
                for f in fields {
                    w!(o, "                case {} -> {{ f{} = {}; has{} = true; }}", f.tag, f.tag, dec(&f.ty, "r", 1), f.tag);
                }
                w!(o, "                default -> r.skip();");
                w!(o, "            }}");
                w!(o, "        }}");
                for f in fields.iter().filter(|f| !matches!(f.ty, Ty::Option(_))) {
                    w!(o, "        if (!has{}) throw new AcmeProtocolException(\"{}: missing field '{}'\");", f.tag, t.name, f.name);
                }
                let args: Vec<String> = fields.iter().map(|f| format!("f{}", f.tag)).collect();
                w!(o, "        return new {name}({});", args.join(", "));
                w!(o, "    }}");
            }
            TypeKind::Enum(cases) => {
                w!(o, "    static void write{name}(MsgPackWriter w, {name} v) {{");
                w!(o, "        w.writeUInt(v.wireTag);");
                w!(o, "    }}");
                w!(o, "");
                w!(o, "    static {name} read{name}(MsgPackReader r) {{");
                w!(o, "        long tag = r.readUInt64();");
                w!(o, "        return switch ((int) tag) {{");
                for c in cases {
                    w!(o, "            case {} -> {name}.{};", c.tag, screaming(&c.name));
                }
                w!(o, "            default -> throw new AcmeProtocolException(\"unknown case tag \" + tag + \" for '{}'\");", t.name);
                w!(o, "        }};");
                w!(o, "    }}");
            }
            TypeKind::Variant(cases) => {
                // instanceof chain (Java 16) instead of a pattern switch (Java 21),
                // so the generated code also compiles for Android (Java 17).
                w!(o, "    static void write{name}(MsgPackWriter w, {name} v) {{");
                for (i, c) in cases.iter().enumerate() {
                    let cn = pascal(&c.name);
                    let kw = if i == 0 { "if" } else { "} else if" };
                    w!(o, "        {kw} (v instanceof {name}.{cn} c) {{");
                    match &c.ty {
                        Some(t) => w!(o, "            w.writeArrayHeader(2); w.writeUInt({}); {}", c.tag, enc(t, "c.value()", 1)),
                        None => w!(o, "            w.writeArrayHeader(1); w.writeUInt({});", c.tag),
                    }
                }
                w!(o, "        }} else {{");
                w!(o, "            throw new IllegalArgumentException(\"unknown {name} case: \" + v);");
                w!(o, "        }}");
                w!(o, "    }}");
                w!(o, "");
                w!(o, "    static {name} read{name}(MsgPackReader r) {{");
                w!(o, "        int n = r.readArrayHeader();");
                w!(o, "        if (n == 0) throw new AcmeProtocolException(\"{}: empty variant\");", t.name);
                w!(o, "        long tag = r.readUInt64();");
                w!(o, "        {name} v;");
                w!(o, "        int used;");
                w!(o, "        if (false) {{ throw new AssertionError(); }}");
                for c in cases {
                    let cn = pascal(&c.name);
                    match &c.ty {
                        Some(t) => w!(o, "        else if (tag == {} && n >= 2) {{ v = new {name}.{cn}({}); used = 2; }}", c.tag, dec(t, "r", 1)),
                        None => w!(o, "        else if (tag == {}) {{ v = new {name}.{cn}(); used = 1; }}", c.tag),
                    }
                }
                w!(o, "        else throw new AcmeProtocolException(\"unknown case tag \" + tag + \" for '{}'\");", t.name);
                w!(o, "        for (int i = used; i < n; i++) r.skip();");
                w!(o, "        return v;");
                w!(o, "    }}");
            }
        }
    }
    w!(o, "}}");
    o
}

fn method_ids(m: &Model) -> String {
    let mut o = header(&pkg(m));
    w!(o, "/** Stable method ids (wit/abi-ids.lock). */");
    w!(o, "final class MethodIds {{");
    w!(o, "    private MethodIds() {{}}");
    for r in &m.resources {
        for f in r.ctor.iter().chain(&r.methods) {
            w!(o, "    static final int {}_{} = {:#06x};", screaming(&r.name), screaming(&f.name), f.id);
        }
    }
    for h in &m.imports {
        for f in &h.funcs {
            w!(o, "    static final int {}_{} = {:#06x}; // import, answered by the app", screaming(&h.name), screaming(&f.name), f.id);
        }
    }
    w!(o, "}}");
    o
}

fn contract(m: &Model) -> String {
    let (maj, min, _) = m.version_triple();
    let mut o = header(RT_PKG);
    w!(o, "/** The contract this SDK was generated from. */");
    w!(o, "public final class Contract {{");
    w!(o, "    private Contract() {{}}");
    w!(o, "    public static final String ID = \"{}\";", m.contract_id());
    w!(o, "    public static final String PACKAGE = \"{}:{}\";", m.namespace, m.package);
    w!(o, "    public static final int MAJOR = {maj};");
    w!(o, "    public static final int MINOR = {min};");
    w!(o, "}}");
    o
}

fn ok_type(f: &Func) -> Option<&Ty> {
    match &f.ret {
        Ret::Unit | Ret::Result { ok: None, .. } => None,
        Ret::Value(t) | Ret::Result { ok: Some(t), .. } => Some(t),
    }
}

fn resource(m: &Model, r: &Resource) -> String {
    let cls = class_name(m, r);
    let rs = screaming(&r.name);
    let mut o = header(&pkg(m));
    w!(o, "import com.acme.client.runtime.ClientBackend;");
    w!(o, "import com.acme.client.runtime.MsgPackReader;");
    w!(o, "import com.acme.client.runtime.MsgPackWriter;");
    w!(o, "import com.acme.client.runtime.NativeBackend;");
    w!(o, "import com.acme.client.runtime.ObjectHandle;");
    w!(o, "import java.util.concurrent.CompletableFuture;");
    w!(o, "");
    docs(&mut o, &r.docs, "");
    w!(o, "public final class {cls} implements AutoCloseable {{");
    w!(o, "    private final ClientBackend backend;");
    w!(o, "    private final ObjectHandle handle;");
    w!(o, "");
    if let Some(c) = &r.ctor {
        let ps: Vec<String> = c.params.iter().map(|(n, t)| format!("{} {}", jt(t), ident(n))).collect();
        let args: Vec<String> = c.params.iter().map(|(n, _)| ident(n)).collect();
        docs(&mut o, &c.docs, "    ");
        w!(o, "    public {cls}({}) {{", ps.join(", "));
        w!(o, "        this({}{}NativeBackend.shared());", args.join(", "), if args.is_empty() { "" } else { ", " });
        w!(o, "    }}");
        w!(o, "");
        w!(o, "    /** Creates the client on an explicit backend (native core, component model, test double). */");
        w!(o, "    public {cls}({}{}ClientBackend backend) {{", ps.join(", "), if ps.is_empty() { "" } else { ", " });
        w!(o, "        this.backend = java.util.Objects.requireNonNull(backend, \"backend\");");
        request(&mut o, &c.params);
        w!(o, "        var r = new MsgPackReader(backend.callSync(0, MethodIds.{rs}_{}, w.toByteArray()));", screaming(&c.name));
        w!(o, "        this.handle = new ObjectHandle(this, backend, r.readUInt64());");
        w!(o, "    }}");
        w!(o, "");
    }
    for f in &r.methods {
        docs(&mut o, &f.docs, "    ");
        let ps: Vec<String> = f.params.iter().map(|(n, t)| format!("{} {}", jt(t), ident(n))).collect();
        let mid = format!("MethodIds.{rs}_{}", screaming(&f.name));
        let name = ident(&f.name);
        if let Ret::Value(Ty::Stream(item)) = &f.ret {
            w!(o, "    public java.util.concurrent.Flow.Publisher<{}> {name}({}) {{", boxed(item), ps.join(", "));
            w!(o, "        return backend.publisher(() -> {{");
            request_ind(&mut o, &f.params, "            ");
            w!(o, "            return new MsgPackReader(backend.callSync(handle.get(), {mid}, w.toByteArray())).readUInt64();");
            w!(o, "        }}, bytes -> {});", dec(item, "new MsgPackReader(bytes)", 1));
            w!(o, "    }}");
            w!(o, "");
            continue;
        }
        let decode_body = |o: &mut String, ind: &str| {
            match &f.ret {
                Ret::Unit => w!(o, "{ind}return null;"),
                Ret::Value(t) => w!(o, "{ind}return {};", dec(t, "r", 1)),
                Ret::Result { ok, err } => {
                    w!(o, "{ind}if (r.readResultTag() != 0) {{");
                    match err {
                        Some(Ty::Named(n)) => w!(o, "{ind}    throw new {}(WireCodec.read{}(r));", exception_name(n), pascal(n)),
                        Some(t) => w!(o, "{ind}    throw new com.acme.client.runtime.AcmeCallFailedException({});", dec(t, "r", 1)),
                        None => w!(o, "{ind}    throw new com.acme.client.runtime.AcmeCallFailedException(null);"),
                    }
                    w!(o, "{ind}}}");
                    match ok {
                        Some(t) => w!(o, "{ind}return {};", dec(t, "r", 1)),
                        None => {
                            w!(o, "{ind}r.readNil();");
                            w!(o, "{ind}return null;");
                        }
                    }
                }
            }
        };
        if f.is_async {
            let t = ok_type(f).map(boxed).unwrap_or("Void".into());
            w!(o, "    public CompletableFuture<{t}> {name}({}) {{", ps.join(", "));
            request(&mut o, &f.params);
            w!(o, "        return backend.callAsync(handle.get(), {mid}, w.toByteArray(), bytes -> {{");
            w!(o, "            var r = new MsgPackReader(bytes);");
            decode_body(&mut o, "            ");
            w!(o, "        }});");
            w!(o, "    }}");
        } else {
            let t = ok_type(f).map(jt).unwrap_or("void".into());
            w!(o, "    public {t} {name}({}) {{", ps.join(", "));
            request(&mut o, &f.params);
            w!(o, "        var r = new MsgPackReader(backend.callSync(handle.get(), {mid}, w.toByteArray()));");
            let mut body = String::new();
            decode_body(&mut body, "        ");
            if t == "void" {
                body = body.replace("return null;", "return;");
            }
            o.push_str(&body);
            w!(o, "    }}");
        }
        w!(o, "");
    }
    w!(o, "    /** Releases the native object. In-flight calls fail, event publishers complete. Idempotent. */");
    w!(o, "    @Override");
    w!(o, "    public void close() {{");
    w!(o, "        handle.close();");
    w!(o, "    }}");
    w!(o, "}}");
    o
}

fn request(o: &mut String, params: &[(String, Ty)]) {
    request_ind(o, params, "        ");
}

fn request_ind(o: &mut String, params: &[(String, Ty)], ind: &str) {
    w!(o, "{ind}var w = new MsgPackWriter();");
    w!(o, "{ind}w.writeArrayHeader({});", params.len());
    for (n, t) in params {
        w!(o, "{ind}{}", enc(t, &ident(n), 1));
    }
}

/// Plain constants (no java.lang.foreign), shared by the Panama and JNI backends.
fn abi_constants(m: &Model) -> String {
    let mut o = header(RT_PKG);
    w!(o, "/** Status codes, capability bits and version of the Acme native ABI (abi/acme_abi.h). */");
    w!(o, "public final class AbiConstants {{");
    w!(o, "    private AbiConstants() {{}}");
    w!(o, "");
    w!(o, "    /** Library name and prefix of this package's ABI symbols ({0}_call_sync, ...). */", m.symbol_prefix());
    w!(o, "    public static final String LIBRARY = \"{}\";", m.symbol_prefix());
    w!(o, "    public static final String SYMBOL_PREFIX = \"{}_\";", m.symbol_prefix());
    w!(o, "    public static final int ABI_MAJOR = {};", abi_table::ABI_MAJOR);
    w!(o, "    /** Minimum ABI minor this package needs (1 if it uses host calls). */");
    w!(o, "    public static final int ABI_MINOR = {};", m.required_abi_minor());
    w!(o, "    public static final boolean REQUIRES_HOST_CALLS = {};", m.needs_host_calls());
    w!(o, "");
    for (n, v) in abi_table::STATUSES {
        w!(o, "    public static final int ACME_{n} = {v};");
    }
    w!(o, "");
    for (n, bit) in abi_table::CAPABILITIES {
        w!(o, "    public static final long ACME_CAP_{n} = 1L << {bit};");
    }
    w!(o, "}}");
    o
}

fn layout(t: CTy) -> &'static str {
    match t {
        CTy::Void => unreachable!(),
        CTy::U32 | CTy::Status => "JAVA_INT",
        CTy::U64 | CTy::Handle => "JAVA_LONG",
        CTy::Bytes => "ACME_BYTES",
        CTy::Buffer => "ACME_BUFFER",
        CTy::BufferPtr | CTy::HandlePtr | CTy::Callback | CTy::VoidPtr | CTy::CStr | CTy::HostHandler => "ADDRESS",
    }
}

fn jtype(t: CTy) -> &'static str {
    match t {
        CTy::Void => "void",
        CTy::U32 | CTy::Status => "int",
        CTy::U64 | CTy::Handle => "long",
        _ => "MemorySegment",
    }
}

fn native_abi(m: &Model) -> String {
    let mut o = header(RT_PKG);
    w!(o, "import java.lang.foreign.*;");
    w!(o, "import java.lang.invoke.MethodHandle;");
    w!(o, "import static java.lang.foreign.ValueLayout.*;");
    w!(o, "");
    w!(o, "/**");
    w!(o, " * Panama FFM bindings of the generic Acme native ABI {}.{} (abi/acme_abi.h).", abi_table::ABI_MAJOR, abi_table::ABI_MINOR);
    w!(o, " * Java 22+ only; Android and older JVMs use the JNI backend instead.");
    w!(o, " * This list does not grow when WIT functions are added: those are addressed by method id.");
    w!(o, " */");
    w!(o, "public final class NativeAbi {{");
    w!(o, "    /** struct acme_bytes / acme_buffer {{ uint8_t* ptr; size_t len; }} (64-bit targets). */");
    w!(o, "    public static final StructLayout ACME_BYTES = MemoryLayout.structLayout(ADDRESS.withName(\"ptr\"), JAVA_LONG.withName(\"len\"));");
    w!(o, "    public static final StructLayout ACME_BUFFER = MemoryLayout.structLayout(ADDRESS.withName(\"ptr\"), JAVA_LONG.withName(\"len\"));");
    w!(o, "    /** void (*acme_future_callback)(void* user_data, uint64_t future) */");
    w!(o, "    public static final FunctionDescriptor CALLBACK = FunctionDescriptor.ofVoid(ADDRESS, JAVA_LONG);");
    w!(o, "");
    for f in abi_table::FUNCTIONS {
        w!(o, "    private final MethodHandle {};", f.name);
    }
    w!(o, "");
    w!(o, "    public NativeAbi(SymbolLookup lookup) {{");
    w!(o, "        if (Linker.nativeLinker().canonicalLayouts().get(\"size_t\").byteSize() != 8) {{");
    w!(o, "            throw new UnsupportedOperationException(\"the Java SDK supports 64-bit targets only\");");
    w!(o, "        }}");
    w!(o, "        var linker = Linker.nativeLinker();");
    for f in abi_table::FUNCTIONS {
        let args: Vec<&str> = f.params.iter().map(|(t, _)| layout(*t)).collect();
        let desc = if f.ret == CTy::Void {
            format!("FunctionDescriptor.ofVoid({})", args.join(", "))
        } else {
            let mut a = vec![layout(f.ret)];
            a.extend(args);
            format!("FunctionDescriptor.of({})", a.join(", "))
        };
        if f.host_call {
            // ABI 1.1, optional: null unless the core has ACME_CAP_HOST_CALLS
            w!(o, "        {} = lookup.find(\"{}\").map(s -> linker.downcallHandle(s, {desc})).orElse(null);", f.name, abi_table::symbol(&m.symbol_prefix(), f.name));
        } else {
            w!(o, "        {} = linker.downcallHandle(find(lookup, \"{}\"), {desc});", f.name, abi_table::symbol(&m.symbol_prefix(), f.name));
        }
    }
    w!(o, "    }}");
    w!(o, "");
    w!(o, "    /** ABI 1.1: true if the core exports the (optional) host-call functions. */");
    w!(o, "    public boolean hasHostCalls() {{");
    w!(o, "        return acme_host_register != null && acme_host_reply != null;");
    w!(o, "    }}");
    w!(o, "");
    w!(o, "    private static MemorySegment find(SymbolLookup lookup, String name) {{");
    w!(o, "        return lookup.find(name).orElseThrow(() -> new AcmeIncompatibleLibraryException(\"native core lacks symbol \" + name));");
    w!(o, "    }}");
    w!(o, "");
    w!(o, "    private static RuntimeException rethrow(Throwable t) {{");
    w!(o, "        if (t instanceof RuntimeException e) return e;");
    w!(o, "        if (t instanceof Error e) throw e;");
    w!(o, "        return new IllegalStateException(t);");
    w!(o, "    }}");
    for f in abi_table::FUNCTIONS {
        let ps: Vec<String> = f.params.iter().map(|(t, n)| format!("{} {}", jtype(*t), ident(n))).collect();
        let args: Vec<String> = f.params.iter().map(|(_, n)| ident(n)).collect();
        let ret = jtype(f.ret);
        w!(o, "");
        w!(o, "    public {ret} {}({}) {{", f.name, ps.join(", "));
        if f.host_call {
            w!(o, "        if ({} == null) throw new AcmeIncompatibleLibraryException(\"native core does not support host calls\");", f.name);
        }
        w!(o, "        try {{");
        if f.ret == CTy::Void {
            w!(o, "            {}.invokeExact({});", f.name, args.join(", "));
        } else {
            w!(o, "            return ({ret}) {}.invokeExact({});", f.name, args.join(", "));
        }
        w!(o, "        }} catch (Throwable t) {{");
        w!(o, "            throw rethrow(t);");
        w!(o, "        }}");
        w!(o, "    }}");
    }
    w!(o, "}}");
    o
}

/// `gematik:zero` -> `ZeroHost`: registers the app's implementations of the imports.
fn host_class(m: &Model) -> String {
    format!("{}Host", pascal(&m.package))
}

fn host_ret(r: &Ret) -> String {
    match r {
        Ret::Unit | Ret::Result { ok: None, .. } => "java.util.concurrent.CompletionStage<Void>".into(),
        Ret::Value(t) | Ret::Result { ok: Some(t), .. } => format!("java.util.concurrent.CompletionStage<{}>", boxed(t)),
    }
}

/// One interface per imported WIT interface: implemented by the APP.
fn host_interface(m: &Model, h: &HostInterface) -> String {
    let mut o = header(&pkg(m));
    docs(&mut o, &h.docs, "");
    w!(o, "// WIT import `{}`: implemented by the APP, called by the core (answers may", h.name);
    w!(o, "// complete later, on any thread). Domain errors: throw or complete exceptionally");
    w!(o, "// with the generated exception.");
    w!(o, "public interface {} {{", pascal(&h.name));
    for f in &h.funcs {
        docs(&mut o, &f.docs, "    ");
        let ps: Vec<String> = f.params.iter().map(|(n, t)| format!("{} {}", jt(t), ident(n))).collect();
        w!(o, "    {} {}({});", host_ret(&f.ret), ident(&f.name), ps.join(", "));
    }
    w!(o, "}}");
    o
}

/// `<Package>Host.register(...)`: decodes host-call requests, calls the app,
/// encodes its answers (ABI 1.1 host calls).
fn host(m: &Model) -> String {
    let cls = host_class(m);
    let mut o = header(&pkg(m));
    w!(o, "import com.acme.client.runtime.AbiConstants;");
    w!(o, "import com.acme.client.runtime.AcmeNativeException;");
    w!(o, "import com.acme.client.runtime.AcmeProtocolException;");
    w!(o, "import com.acme.client.runtime.HostCalls;");
    w!(o, "import com.acme.client.runtime.MsgPackReader;");
    w!(o, "import com.acme.client.runtime.MsgPackWriter;");
    w!(o, "import com.acme.client.runtime.NativeBackend;");
    w!(o, "import java.util.Objects;");
    w!(o, "import java.util.concurrent.CompletableFuture;");
    w!(o, "import java.util.concurrent.CompletionException;");
    w!(o, "import java.util.concurrent.CompletionStage;");
    w!(o, "import java.util.function.Supplier;");
    w!(o, "");
    let params: Vec<String> = m.imports.iter().map(|h| format!("{} {}", pascal(&h.name), ident(&h.name))).collect();
    let args: Vec<String> = m.imports.iter().map(|h| ident(&h.name)).collect();
    w!(o, "/** Connects the app's implementations of the WIT imports of {} to the core. */", m.contract_id());
    w!(o, "public final class {cls} {{");
    w!(o, "    private {cls}() {{}}");
    w!(o, "");
    w!(o, "    /** Call once at startup, before the core needs the app (process-wide). */");
    w!(o, "    public static void register({}) {{", params.join(", "));
    w!(o, "        register(NativeBackend.shared(), {});", args.join(", "));
    w!(o, "    }}");
    w!(o, "");
    w!(o, "    public static void register(NativeBackend backend, {}) {{", params.join(", "));
    for a in &args {
        w!(o, "        Objects.requireNonNull({a}, \"{a}\");");
    }
    w!(o, "        HostCalls.install(backend, (methodId, request) -> dispatch({}, methodId, request));", args.join(", "));
    w!(o, "    }}");
    w!(o, "");
    w!(o, "    /** Removes the registration. */");
    w!(o, "    public static void unregister() {{");
    w!(o, "        HostCalls.uninstall(NativeBackend.shared());");
    w!(o, "    }}");
    w!(o, "");
    w!(o, "    /** The app may throw synchronously or return a failed stage: both count. */");
    w!(o, "    private static <T> CompletionStage<T> call(Supplier<CompletionStage<T>> body) {{");
    w!(o, "        try {{");
    w!(o, "            return Objects.requireNonNull(body.get(), \"host implementation returned null\");");
    w!(o, "        }} catch (RuntimeException e) {{");
    w!(o, "            return CompletableFuture.failedFuture(e);");
    w!(o, "        }}");
    w!(o, "    }}");
    w!(o, "");
    w!(o, "    private static Throwable unwrap(Throwable t) {{");
    w!(o, "        while (t instanceof CompletionException && t.getCause() != null) t = t.getCause();");
    w!(o, "        return t;");
    w!(o, "    }}");
    w!(o, "");
    w!(o, "    private static CompletionStage<byte[]> dispatch({}, int methodId, byte[] request) {{", params.join(", "));
    w!(o, "        var r = new MsgPackReader(request);");
    w!(o, "        switch (methodId) {{");
    for h in &m.imports {
        let target = ident(&h.name);
        for f in &h.funcs {
            w!(o, "            case MethodIds.{}_{}: {{", screaming(&h.name), screaming(&f.name));
            w!(o, "                if (r.readArrayHeader() != {}) throw new AcmeProtocolException(\"{}: wrong parameter count\");", f.params.len(), f.name);
            for (n, t) in &f.params {
                w!(o, "                {} {} = {};", jt(t), host_local(n), dec(t, "r", 1));
            }
            w!(o, "                if (r.remaining() != 0) throw new AcmeProtocolException(\"trailing bytes in host call request\");");
            let a: Vec<String> = f.params.iter().map(|(n, _)| host_local(n)).collect();
            w!(o, "                return call(() -> {target}.{}({})).handle((ret, failure) -> {{", ident(&f.name), a.join(", "));
            w!(o, "                    var w = new MsgPackWriter();");
            match &f.ret {
                Ret::Unit => {
                    w!(o, "                    if (failure != null) throw new CompletionException(unwrap(failure));");
                    w!(o, "                    w.writeNil();");
                }
                Ret::Value(t) => {
                    w!(o, "                    if (failure != null) throw new CompletionException(unwrap(failure));");
                    w!(o, "                    {}", enc(t, "ret", 1));
                }
                Ret::Result { ok, err } => {
                    w!(o, "                    if (failure == null) {{");
                    w!(o, "                        w.writeArrayHeader(2);");
                    w!(o, "                        w.writeUInt(0);");
                    match ok {
                        Some(t) => w!(o, "                        {}", enc(t, "ret", 1)),
                        None => w!(o, "                        w.writeNil();"),
                    }
                    w!(o, "                        return w.toByteArray();");
                    w!(o, "                    }}");
                    w!(o, "                    Throwable cause = unwrap(failure);");
                    match err {
                        Some(Ty::Named(n)) => {
                            w!(o, "                    if (!(cause instanceof {} e)) throw new CompletionException(cause);", exception_name(n));
                            w!(o, "                    w.writeArrayHeader(2);");
                            w!(o, "                    w.writeUInt(1);");
                            w!(o, "                    WireCodec.write{}(w, e.error());", pascal(n));
                        }
                        Some(t) => {
                            w!(o, "                    if (!(cause instanceof com.acme.client.runtime.AcmeCallFailedException e) || !(e.error() instanceof {} err)) throw new CompletionException(cause);", boxed(t));
                            w!(o, "                    w.writeArrayHeader(2);");
                            w!(o, "                    w.writeUInt(1);");
                            w!(o, "                    {}", enc(t, "err", 1));
                        }
                        None => {
                            w!(o, "                    if (!(cause instanceof com.acme.client.runtime.AcmeCallFailedException)) throw new CompletionException(cause);");
                            w!(o, "                    w.writeArrayHeader(2);");
                            w!(o, "                    w.writeUInt(1);");
                            w!(o, "                    w.writeNil();");
                        }
                    }
                }
            }
            w!(o, "                    return w.toByteArray();");
            w!(o, "                }});");
            w!(o, "            }}");
        }
    }
    w!(o, "            default:");
    w!(o, "                throw new AcmeNativeException(AbiConstants.ACME_ERR_UNKNOWN_METHOD, \"unknown host method\", Integer.toHexString(methodId));");
    w!(o, "        }}");
    w!(o, "    }}");
    w!(o, "}}");
    o
}
