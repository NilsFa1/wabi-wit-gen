//! Swift emitter: structs, enums (with associated values for variants), Error
//! conformance for error types, the payload codec, one client class per
//! resource (async throws + AsyncSequence) and ABI constants.

use crate::abi_table;
use crate::ir::*;
use crate::names::*;

pub fn emit(m: &Model) -> Vec<(String, String)> {
    let mut files = vec![
        ("Types.swift".to_string(), types(m)),
        ("WireCodec.swift".to_string(), codec(m)),
        ("AbiConstants.swift".to_string(), constants(m)),
        ("NativeAbi.swift".to_string(), native_abi(m)),
    ];
    for r in &m.resources {
        files.push((format!("{}.swift", crate::gen_csharp::class_name(m, r)), resource(m, r)));
    }
    if m.needs_host_calls() {
        files.push((format!("{}.swift", host_class(m)), host(m)));
    }
    files
}

fn header() -> String {
    "// Generated by wabi-wit-gen from wit/*.wit — DO NOT EDIT.\n\n".into()
}

fn docs(o: &mut String, d: &Option<String>, ind: &str) {
    if let Some(d) = d {
        for l in d.lines() {
            w!(o, "{ind}/// {}", l.trim_end());
        }
    }
}

const KEYWORDS: &[&str] = &[
    "associatedtype", "class", "deinit", "enum", "extension", "func", "import", "init", "inout", "internal", "let",
    "operator", "private", "protocol", "public", "static", "struct", "subscript", "typealias", "var", "break", "case",
    "continue", "default", "defer", "do", "else", "fallthrough", "for", "guard", "if", "in", "repeat", "return",
    "switch", "where", "while", "as", "catch", "false", "is", "nil", "rethrows", "super", "self", "Self", "throw",
    "throws", "true", "try", "Type", "Protocol", "any", "some",
];

fn ident(s: &str) -> String {
    let c = camel(s);
    if KEYWORDS.contains(&c.as_str()) { format!("`{c}`") } else { c }
}

fn st(t: &Ty) -> String {
    match t {
        Ty::Bool => "Bool".into(),
        Ty::U8 => "UInt8".into(),
        Ty::U16 => "UInt16".into(),
        Ty::U32 => "UInt32".into(),
        Ty::U64 => "UInt64".into(),
        Ty::S8 => "Int8".into(),
        Ty::S16 => "Int16".into(),
        Ty::S32 => "Int32".into(),
        Ty::S64 => "Int64".into(),
        Ty::F32 => "Float".into(),
        Ty::F64 => "Double".into(),
        Ty::Char => "Unicode.Scalar".into(),
        Ty::String => "String".into(),
        Ty::Bytes => "[UInt8]".into(),
        Ty::List(t) => format!("[{}]", st(t)),
        Ty::Option(t) => format!("{}?", st(t)),
        Ty::Tuple(ts) => format!("({})", ts.iter().map(st).collect::<Vec<_>>().join(", ")),
        Ty::Named(n) => pascal(n),
        Ty::Stream(t) => format!("WabiStream<{}>", st(t)),
        Ty::Handle { resource, .. } => sdk_class(resource),
    }
}

fn enc(t: &Ty, e: &str, d: usize) -> String {
    match t {
        Ty::Bool => format!("w.writeBool({e})"),
        Ty::U8 | Ty::U16 | Ty::U32 | Ty::U64 => format!("w.writeUInt(UInt64({e}))"),
        Ty::S8 | Ty::S16 | Ty::S32 | Ty::S64 => format!("w.writeInt(Int64({e}))"),
        Ty::F32 => format!("w.writeFloat32({e})"),
        Ty::F64 => format!("w.writeFloat64({e})"),
        Ty::Char => format!("w.writeUInt(UInt64({e}.value))"),
        Ty::String => format!("w.writeString({e})"),
        Ty::Bytes => format!("w.writeBinary({e})"),
        Ty::List(t) => format!(
            "w.writeArrayHeader({e}.count); for x{d} in {e} {{ {} }}",
            enc(t, &format!("x{d}"), d + 1)
        ),
        Ty::Option(t) => format!("if let x{d} = {e} {{ {} }} else {{ w.writeNil() }}", enc(t, &format!("x{d}"), d + 1)),
        Ty::Tuple(ts) => {
            let mut s = format!("w.writeArrayHeader({})", ts.len());
            for (i, t) in ts.iter().enumerate() {
                s += "; ";
                s += &enc(t, &format!("{e}.{i}"), d + 1);
            }
            s
        }
        Ty::Named(_) => format!("{e}.encode(to: w)"),
        Ty::Stream(_) => unreachable!(),
        // lent for the call, or moved into the core (the SDK object is closed without a drop)
        Ty::Handle { owned: false, .. } => format!("w.writeUInt(try {e}.nativeHandle())"),
        Ty::Handle { owned: true, .. } => format!("w.writeUInt(try {e}.detachNativeHandle())"),
    }
}

fn dec(t: &Ty, r: &str, d: usize) -> String {
    match t {
        Ty::Bool => format!("try {r}.readBool()"),
        Ty::U8 | Ty::U16 | Ty::U32 | Ty::U64 => format!("try {r}.readUInt({}.self)", st(t)),
        Ty::S8 | Ty::S16 | Ty::S32 | Ty::S64 => format!("try {r}.readInt({}.self)", st(t)),
        Ty::F32 => format!("Float(try {r}.readFloat64())"),
        Ty::F64 => format!("try {r}.readFloat64()"),
        Ty::Char => format!("try {r}.readScalar()"),
        Ty::String => format!("try {r}.readString()"),
        Ty::Bytes => format!("try {r}.readBinary()"),
        Ty::List(t) => format!("try {r}.readList {{ r{d} in {} }}", dec(t, &format!("r{d}"), d + 1)),
        Ty::Option(t) => format!("try {r}.readOptional {{ r{d} in {} }}", dec(t, &format!("r{d}"), d + 1)),
        Ty::Tuple(ts) => format!(
            "try {{ () throws -> ({}) in try {r}.readTupleHeader({}); return ({}) }}()",
            ts.iter().map(st).collect::<Vec<_>>().join(", "),
            ts.len(),
            ts.iter().map(|t| dec(t, r, d + 1)).collect::<Vec<_>>().join(", ")
        ),
        Ty::Named(n) => format!("try {}.decode(from: {r})", pascal(n)),
        Ty::Stream(_) => unreachable!(),
        // an object the core hands out (only inside a resource class, where `backend` is in scope)
        Ty::Handle { resource, .. } => format!("try {}(backend: backend, handle: {r}.readUInt(UInt64.self))", sdk_class(resource)),
    }
}

fn types(m: &Model) -> String {
    let mut o = header();
    for t in &m.types {
        let name = pascal(&t.name);
        docs(&mut o, &t.docs, "");
        let err = if t.is_error { "Error, " } else { "" };
        match &t.kind {
            TypeKind::Record(fields) => {
                w!(o, "public struct {name}: {err}Equatable, Sendable {{");
                for f in fields {
                    docs(&mut o, &f.docs, "    ");
                    w!(o, "    public var {}: {}", ident(&f.name), st(&f.ty));
                }
                w!(o, "");
                let ps: Vec<String> = fields
                    .iter()
                    .map(|f| {
                        let def = if matches!(f.ty, Ty::Option(_)) { " = nil" } else { "" };
                        format!("{}: {}{def}", ident(&f.name), st(&f.ty))
                    })
                    .collect();
                w!(o, "    public init({}) {{", ps.join(", "));
                for f in fields {
                    w!(o, "        self.{} = {}", ident(&f.name), ident(&f.name));
                }
                w!(o, "    }}");
                w!(o, "}}");
            }
            TypeKind::Enum(cases) => {
                w!(o, "public enum {name}: UInt32, {err}Equatable, Sendable {{");
                for c in cases {
                    docs(&mut o, &c.docs, "    ");
                    w!(o, "    case {} = {}", ident(&c.name), c.tag);
                }
                w!(o, "}}");
            }
            TypeKind::Variant(cases) => {
                w!(o, "public enum {name}: {err}Equatable, Sendable {{");
                for c in cases {
                    docs(&mut o, &c.docs, "    ");
                    match &c.ty {
                        Some(t) => w!(o, "    case {}({})", ident(&c.name), st(t)),
                        None => w!(o, "    case {}", ident(&c.name)),
                    }
                }
                w!(o, "}}");
            }
        }
        w!(o, "");
    }
    o
}

fn codec(m: &Model) -> String {
    let mut o = header();
    w!(o, "// Payload encoding v1 for all contract types (see ABI.md §5).");
    w!(o, "");
    for t in &m.types {
        let name = pascal(&t.name);
        w!(o, "extension {name} {{");
        match &t.kind {
            TypeKind::Record(fields) => {
                w!(o, "    func encode(to w: MsgPackWriter) {{");
                w!(o, "        var n = 0");
                for f in fields {
                    if matches!(f.ty, Ty::Option(_)) {
                        w!(o, "        if {} != nil {{ n += 1 }}", ident(&f.name));
                    } else {
                        w!(o, "        n += 1");
                    }
                }
                w!(o, "        w.writeMapHeader(n)");
                for f in fields {
                    let fname = ident(&f.name);
                    if let Ty::Option(inner) = &f.ty {
                        w!(o, "        if let f{} = {fname} {{ w.writeUInt({}); {} }}", f.tag, f.tag, enc(inner, &format!("f{}", f.tag), 1));
                    } else {
                        w!(o, "        w.writeUInt({}); {}", f.tag, enc(&f.ty, &format!("self.{fname}"), 1));
                    }
                }
                w!(o, "    }}");
                w!(o, "");
                w!(o, "    static func decode(from r: MsgPackReader) throws -> {name} {{");
                w!(o, "        let n = try r.readMapHeader()");
                for f in fields {
                    let ty = match &f.ty {
                        Ty::Option(inner) => st(inner),
                        t => st(t),
                    };
                    w!(o, "        var f{}: {ty}? = nil", f.tag);
                }
                w!(o, "        for _ in 0..<n {{");
                w!(o, "            switch try r.readUInt(UInt32.self) {{");
                for f in fields {
                    w!(o, "            case {}: f{} = {}", f.tag, f.tag, dec(&f.ty, "r", 1));
                }
                w!(o, "            default: try r.skip()");
                w!(o, "            }}");
                w!(o, "        }}");
                for f in fields.iter().filter(|f| !matches!(f.ty, Ty::Option(_))) {
                    w!(o, "        guard let v{} = f{} else {{ throw WabiRuntimeError.protocolError(\"{}: missing field '{}'\") }}", f.tag, f.tag, t.name, f.name);
                }
                let args: Vec<String> = fields
                    .iter()
                    .map(|f| {
                        let v = if matches!(f.ty, Ty::Option(_)) { format!("f{}", f.tag) } else { format!("v{}", f.tag) };
                        format!("{}: {v}", ident(&f.name))
                    })
                    .collect();
                w!(o, "        return {name}({})", args.join(", "));
                w!(o, "    }}");
            }
            TypeKind::Enum(_) => {
                w!(o, "    func encode(to w: MsgPackWriter) {{");
                w!(o, "        w.writeUInt(UInt64(rawValue))");
                w!(o, "    }}");
                w!(o, "");
                w!(o, "    static func decode(from r: MsgPackReader) throws -> {name} {{");
                w!(o, "        let tag = try r.readUInt(UInt32.self)");
                w!(o, "        guard let v = {name}(rawValue: tag) else {{");
                w!(o, "            throw WabiRuntimeError.protocolError(\"unknown case tag \\(tag) for '{}'\")", t.name);
                w!(o, "        }}");
                w!(o, "        return v");
                w!(o, "    }}");
            }
            TypeKind::Variant(cases) => {
                w!(o, "    func encode(to w: MsgPackWriter) {{");
                w!(o, "        switch self {{");
                for c in cases {
                    match &c.ty {
                        Some(t) => w!(o, "        case .{}(let x): w.writeArrayHeader(2); w.writeUInt({}); {}", ident(&c.name), c.tag, enc(t, "x", 1)),
                        None => w!(o, "        case .{}: w.writeArrayHeader(1); w.writeUInt({})", ident(&c.name), c.tag),
                    }
                }
                w!(o, "        }}");
                w!(o, "    }}");
                w!(o, "");
                w!(o, "    static func decode(from r: MsgPackReader) throws -> {name} {{");
                w!(o, "        let n = try r.readArrayHeader()");
                w!(o, "        guard n > 0 else {{ throw WabiRuntimeError.protocolError(\"{}: empty variant\") }}", t.name);
                w!(o, "        let tag = try r.readUInt(UInt32.self)");
                w!(o, "        let v: {name}");
                w!(o, "        let used: Int");
                w!(o, "        switch tag {{");
                for c in cases {
                    match &c.ty {
                        Some(ty) => w!(o, "        case {} where n >= 2: v = .{}({}); used = 2", c.tag, ident(&c.name), dec(ty, "r", 1)),
                        None => w!(o, "        case {}: v = .{}; used = 1", c.tag, ident(&c.name)),
                    }
                }
                w!(o, "        default: throw WabiRuntimeError.protocolError(\"unknown case tag \\(tag) for '{}'\")", t.name);
                w!(o, "        }}");
                w!(o, "        for _ in used..<max(used, n) {{ try r.skip() }}");
                w!(o, "        return v");
                w!(o, "    }}");
            }
        }
        w!(o, "}}");
        w!(o, "");
    }
    o
}

fn constants(m: &Model) -> String {
    let (maj, min, _) = m.version_triple();
    let mut o = header();
    w!(o, "/// The contract this SDK was generated from.");
    w!(o, "public enum Contract {{");
    w!(o, "    public static let id = \"{}\"", m.contract_id());
    w!(o, "    public static let package = \"{}:{}\"", m.namespace, m.package);
    w!(o, "    public static let major = {maj}");
    w!(o, "    public static let minor = {min}");
    w!(o, "    /// Library name and prefix of this package's ABI symbols ({0}_call_sync, ...).", m.symbol_prefix());
    w!(o, "    public static let library = \"{}\"", m.symbol_prefix());
    w!(o, "    public static let symbolPrefix = \"{}_\"", m.symbol_prefix());
    w!(o, "}}");
    w!(o, "");
    w!(o, "/// Stable method ids (wit/abi-ids.lock).");
    w!(o, "enum MethodIds {{");
    for r in &m.resources {
        for f in r.ctor.iter().chain(&r.methods) {
            w!(o, "    static let {}{}: UInt32 = {:#06x}", camel(&r.name), pascal(&f.name), f.id);
        }
    }
    for h in &m.imports {
        for f in &h.funcs {
            w!(o, "    static let {}{}: UInt32 = {:#06x} // import, answered by the app", camel(&h.name), pascal(&f.name), f.id);
        }
    }
    w!(o, "}}");
    w!(o, "");
    w!(o, "/// ABI {}.{} status codes and capability bits (mirrors abi/wabi_abi.h).", abi_table::ABI_MAJOR, abi_table::ABI_MINOR);
    w!(o, "public enum WabiAbi {{");
    w!(o, "    public static let major: UInt32 = {}", abi_table::ABI_MAJOR);
    w!(o, "    public static let minor: UInt32 = {} // minimum this package needs", m.required_abi_minor());
    w!(o, "    public static let requiresHostCalls = {}", m.needs_host_calls());
    for (n, v) in abi_table::STATUSES {
        w!(o, "    public static let {}: Int32 = {v}", camel(&n.to_ascii_lowercase().replace('_', "-")));
    }
    for (n, bit) in abi_table::CAPABILITIES {
        w!(o, "    public static let cap{}: UInt64 = 1 << {bit}", pascal(&n.to_ascii_lowercase().replace('_', "-")));
    }
    w!(o, "}}");
    o
}

fn swift_c(t: abi_table::CTy) -> &'static str {
    use abi_table::CTy::*;
    match t {
        Void => "Void",
        U32 => "UInt32",
        U64 | Handle => "UInt64",
        Status => "wabi_status",
        Bytes => "wabi_bytes",
        Buffer => "wabi_buffer",
        BufferPtr => "UnsafeMutablePointer<wabi_buffer>?",
        HandlePtr => "UnsafeMutablePointer<UInt64>?",
        Callback => "wabi_future_callback!",
        VoidPtr => "UnsafeMutableRawPointer?",
        CStr => "UnsafePointer<CChar>!",
        HostHandler => "wabi_host_handler!",
        HostHandler2 => "wabi_host_handler2!",
        HostCancel => "wabi_host_cancel!",
    }
}

/// Generic ABI names (`wabi_call_sync`) forwarding to this package's prefixed
/// C symbols, so the hand-written runtime is the same for every package.
fn native_abi(m: &Model) -> String {
    let mut o = header();
    w!(o, "import CWabiClient");
    w!(o, "");
    w!(o, "// Symbol prefix of package {}: `{}_`.", m.contract_id(), m.symbol_prefix());
    for f in abi_table::FUNCTIONS {
        let ps: Vec<String> = f.params.iter().map(|(t, n)| format!("_ {n}: {}", swift_c(*t))).collect();
        let args: Vec<&str> = f.params.iter().map(|(_, n)| *n).collect();
        let ret = if f.ret == abi_table::CTy::Void { String::new() } else { format!(" -> {}", swift_c(f.ret)) };
        if f.host_call && !m.needs_host_calls() {
            // ABI 1.1 host calls: this package has no WIT imports, so its core need not export them.
            w!(o, "@inline(__always) func {}({}){ret} {{ WabiAbi.errUnsupported }}", f.name, ps.join(", "));
        } else {
            w!(o, "@inline(__always) func {}({}){ret} {{ {}({}) }}", f.name, ps.join(", "), abi_table::symbol(&m.symbol_prefix(), f.name), args.join(", "));
        }
    }
    o
}

/// `wabi:client` -> `ClientHost`: registers the app's implementations of the imports.
fn host_class(m: &Model) -> String {
    format!("{}Host", pascal(&m.package))
}

/// App-side host calls (ABI 1.2): one protocol per imported WIT interface,
/// plus `<Package>Host.register(...)` which decodes requests and encodes answers.
fn host(m: &Model) -> String {
    let cls = host_class(m);
    let mut o = header();
    for h in &m.imports {
        docs(&mut o, &h.docs, "");
        w!(o, "///");
        w!(o, "/// WIT import `{}`: implemented by the APP, called by the core. Domain", h.name);
        w!(o, "/// errors are reported by throwing the generated error type. If the core no");
        w!(o, "/// longer waits for an answer, the task running the function is cancelled.");
        w!(o, "public protocol {}: Sendable {{", pascal(&h.name));
        for f in &h.funcs {
            docs(&mut o, &f.docs, "    ");
            let ps: Vec<String> = f.params.iter().map(|(n, t)| format!("{}: {}", ident(n), st(t))).collect();
            let ret = match &f.ret {
                Ret::Unit | Ret::Result { ok: None, .. } => String::new(),
                Ret::Value(t) | Ret::Result { ok: Some(t), .. } => format!(" -> {}", st(t)),
            };
            w!(o, "    func {}({}) async throws{ret}", ident(&f.name), ps.join(", "));
        }
        w!(o, "}}");
        w!(o, "");
    }
    let params: Vec<String> = m.imports.iter().map(|h| format!("{}: {}", ident(&h.name), pascal(&h.name))).collect();
    let args: Vec<String> = m.imports.iter().map(|h| ident(&h.name)).collect();
    w!(o, "/// Connects the app's implementations of the WIT imports of {} to the core.", m.contract_id());
    w!(o, "public enum {cls} {{");
    w!(o, "    /// Call once at startup, before the core needs the app (process-wide).");
    w!(o, "    public static func register({}) throws {{", params.join(", "));
    w!(o, "        try HostCalls.install {{ methodId, request in");
    w!(o, "            try await dispatch({}, methodId, request)", args.iter().map(|a| format!("{a}: {a}")).collect::<Vec<_>>().join(", "));
    w!(o, "        }}");
    w!(o, "    }}");
    w!(o, "");
    w!(o, "    /// Removes the process-wide registration.");
    w!(o, "    public static func unregister() {{");
    w!(o, "        HostCalls.uninstall()");
    w!(o, "    }}");
    for r in &m.resources {
        let rc = crate::gen_csharp::class_name(m, r);
        w!(o, "");
        w!(o, "    /// Registers the implementations for the calls the core makes on behalf of this");
        w!(o, "    /// one instance. They take precedence over the process-wide ones and are");
        w!(o, "    /// removed when the instance is closed.");
        w!(o, "    public static func register(for instance: {rc}, {}) throws {{", params.join(", "));
        w!(o, "        try HostCalls.install(object: instance.nativeHandle()) {{ methodId, request in");
        w!(o, "            try await dispatch({}, methodId, request)", args.iter().map(|a| format!("{a}: {a}")).collect::<Vec<_>>().join(", "));
        w!(o, "        }}");
        w!(o, "    }}");
        w!(o, "");
        w!(o, "    /// Removes the registration of this instance.");
        w!(o, "    public static func unregister(for instance: {rc}) {{");
        w!(o, "        if let handle = try? instance.nativeHandle() {{ HostCalls.uninstall(object: handle) }}");
        w!(o, "    }}");
    }
    w!(o, "");
    w!(o, "    private static func dispatch({}, _ methodId: UInt32, _ request: [UInt8]) async throws -> [UInt8] {{", params.join(", "));
    w!(o, "        let r = MsgPackReader(request)");
    w!(o, "        var w = MsgPackWriter()");
    w!(o, "        switch methodId {{");
    for h in &m.imports {
        let target = ident(&h.name);
        for f in &h.funcs {
            w!(o, "        case MethodIds.{}{}:", camel(&h.name), pascal(&f.name));
            w!(o, "            try r.readTupleHeader({})", f.params.len());
            for (n, t) in &f.params {
                w!(o, "            let {} = {}", host_local(n), dec(t, "r", 1));
            }
            w!(o, "            guard r.remaining == 0 else {{ throw WabiRuntimeError.protocolError(\"trailing bytes in host call request\") }}");
            let a: Vec<String> = f.params.iter().map(|(n, _)| format!("{}: {}", ident(n), host_local(n))).collect();
            let call = format!("try await {target}.{}({})", ident(&f.name), a.join(", "));
            match &f.ret {
                Ret::Unit => {
                    w!(o, "            {call}");
                    w!(o, "            w.writeNil()");
                }
                Ret::Value(t) => {
                    w!(o, "            let ret = {call}");
                    w!(o, "            {}", enc(t, "ret", 1));
                }
                Ret::Result { ok, err } => {
                    w!(o, "            do {{");
                    match ok {
                        Some(t) => {
                            w!(o, "                let ret = {call}");
                            w!(o, "                w.writeArrayHeader(2); w.writeUInt(0)");
                            w!(o, "                {}", enc(t, "ret", 1));
                        }
                        None => {
                            w!(o, "                {call}");
                            w!(o, "                w.writeArrayHeader(2); w.writeUInt(0); w.writeNil()");
                        }
                    }
                    match err {
                        Some(Ty::Named(n)) => {
                            w!(o, "            }} catch let e as {} {{", pascal(n));
                            w!(o, "                w = MsgPackWriter()");
                            w!(o, "                w.writeArrayHeader(2); w.writeUInt(1)");
                            w!(o, "                e.encode(to: w)");
                        }
                        _ => {
                            w!(o, "            }} catch WabiRuntimeError.callFailed {{");
                            w!(o, "                w = MsgPackWriter()");
                            w!(o, "                w.writeArrayHeader(2); w.writeUInt(1); w.writeNil()");
                        }
                    }
                    w!(o, "            }}");
                }
            }
        }
    }
    w!(o, "        default:");
    w!(o, "            throw WabiRuntimeError.native(status: WabiAbi.errUnknownMethod, message: \"unknown host method \\(methodId)\")");
    w!(o, "        }}");
    w!(o, "        return w.bytes");
    w!(o, "    }}");
    w!(o, "}}");
    o
}

fn resource(m: &Model, r: &Resource) -> String {
    let cls = crate::gen_csharp::class_name(m, r);
    let rid = camel(&r.name);
    let mut o = header();
    docs(&mut o, &r.docs, "");
    w!(o, "public final class {cls}: @unchecked Sendable {{");
    w!(o, "    private let backend: ClientBackend?");
    w!(o, "    private let handle: ObjectHandle?");
    w!(o, "    private let initError: Error?");
    w!(o, "");
    if let Some(c) = &r.ctor {
        let ps: Vec<String> = c.params.iter().map(|(n, t)| format!("{}: {}", ident(n), st(t))).collect();
        let args: Vec<String> = c.params.iter().map(|(n, _)| format!("{}: {}", ident(n), ident(n))).collect();
        docs(&mut o, &c.docs, "    ");
        w!(o, "    /// Uses the process-wide native core. If the core is missing or incompatible,");
        w!(o, "    /// every call throws `WabiRuntimeError.incompatibleLibrary`.");
        w!(o, "    public convenience init({}) {{", ps.join(", "));
        w!(o, "        switch NativeBackend.shared {{");
        w!(o, "        case .success(let backend): self.init({}{}backend: backend)", args.join(", "), if args.is_empty() { "" } else { ", " });
        w!(o, "        case .failure(let error): self.init(failed: error)");
        w!(o, "        }}");
        w!(o, "    }}");
        w!(o, "");
        w!(o, "    /// Creates the client on an explicit backend (native core, component model, test double).");
        w!(o, "    public init({}{}backend: ClientBackend) {{", ps.join(", "), if ps.is_empty() { "" } else { ", " });
        w!(o, "        self.backend = backend");
        w!(o, "        let w = MsgPackWriter()");
        w!(o, "        w.writeArrayHeader({})", c.params.len());
        for (n, t) in &c.params {
            w!(o, "        {}", enc(t, &ident(n), 1));
        }
        w!(o, "        do {{");
        w!(o, "            let r = MsgPackReader(try backend.callSync(0, MethodIds.{rid}{}, w.bytes))", pascal(&c.name));
        w!(o, "            self.handle = try ObjectHandle(backend: backend, value: r.readUInt(UInt64.self))");
        w!(o, "            self.initError = nil");
        w!(o, "        }} catch {{");
        w!(o, "            self.handle = nil");
        w!(o, "            self.initError = error");
        w!(o, "        }}");
        w!(o, "    }}");
        w!(o, "");
    }
    w!(o, "    private init(failed error: Error) {{");
    w!(o, "        self.backend = nil");
    w!(o, "        self.handle = nil");
    w!(o, "        self.initError = error");
    w!(o, "    }}");
    w!(o, "");
    /* the handle is also what host-call registrations and resource parameters use */
    w!(o, "    /// The object's handle in the core (throws once closed).");
    w!(o, "    func nativeHandle() throws -> UInt64 {{");
    w!(o, "        try object().1");
    w!(o, "    }}");
    w!(o, "");
    w!(o, "    /// Gives the handle away (the object moves into the core): this instance is closed without a drop.");
    w!(o, "    func detachNativeHandle() throws -> UInt64 {{");
    w!(o, "        if let initError {{ throw initError }}");
    w!(o, "        return try handle!.detach()");
    w!(o, "    }}");
    w!(o, "");
    w!(o, "    /// Wraps an object the core handed out.");
    w!(o, "    init(backend: ClientBackend, handle: UInt64) throws {{");
    w!(o, "        self.backend = backend");
    w!(o, "        self.handle = try ObjectHandle(backend: backend, value: handle)");
    w!(o, "        self.initError = nil");
    w!(o, "    }}");
    w!(o, "");
    w!(o, "    private func object() throws -> (ClientBackend, UInt64) {{");
    w!(o, "        if let initError {{ throw initError }}");
    w!(o, "        return (backend!, try handle!.value())");
    w!(o, "    }}");
    w!(o, "");
    for f in &r.methods {
        docs(&mut o, &f.docs, "    ");
        let ps: Vec<String> = f.params.iter().map(|(n, t)| format!("{}: {}", ident(n), st(t))).collect();
        let mid = format!("MethodIds.{rid}{}", pascal(&f.name));
        let name = ident(&f.name);
        if let Ret::Value(Ty::Stream(item)) = &f.ret {
            w!(o, "    public func {name}({}) -> WabiStream<{}> {{", ps.join(", "), st(item));
            w!(o, "        WabiStream(open: {{ [self] in");
            w!(o, "            let (backend, h) = try self.object()");
            w!(o, "            let w = MsgPackWriter()");
            w!(o, "            w.writeArrayHeader({})", f.params.len());
            for (n, t) in &f.params {
                w!(o, "            {}", enc(t, &ident(n), 1));
            }
            w!(o, "            let r = MsgPackReader(try backend.callSync(h, {mid}, w.bytes))");
            w!(o, "            return (backend, try r.readUInt(UInt64.self))");
            w!(o, "        }}, decode: {{ bytes in {} }})", dec(item, "MsgPackReader(bytes)", 1));
            w!(o, "    }}");
            w!(o, "");
            continue;
        }
        let ok = match &f.ret {
            Ret::Unit | Ret::Result { ok: None, .. } => None,
            Ret::Value(t) | Ret::Result { ok: Some(t), .. } => Some(st(t)),
        };
        let asy = if f.is_async { "async " } else { "" };
        let ret = ok.map(|t| format!(" -> {t}")).unwrap_or_default();
        w!(o, "    public func {name}({}) {asy}throws{ret} {{", ps.join(", "));
        w!(o, "        let (backend, h) = try object()");
        w!(o, "        let w = MsgPackWriter()");
        w!(o, "        w.writeArrayHeader({})", f.params.len());
        for (n, t) in &f.params {
            w!(o, "        {}", enc(t, &ident(n), 1));
        }
        let bind = if matches!(f.ret, Ret::Unit) { "_" } else { "let r" };
        if f.is_async {
            w!(o, "        {bind} = MsgPackReader(try await backend.callAsync(h, {mid}, w.bytes))");
        } else {
            w!(o, "        {bind} = MsgPackReader(try backend.callSync(h, {mid}, w.bytes))");
        }
        match &f.ret {
            Ret::Unit => {}
            Ret::Value(t) => w!(o, "        return {}", dec(t, "r", 1)),
            Ret::Result { ok, err } => {
                w!(o, "        if try r.readResultTag() != 0 {{");
                match err {
                    Some(Ty::Named(n)) if m.types.iter().any(|t| &t.name == n && t.is_error) => {
                        w!(o, "            throw try {}.decode(from: r)", pascal(n))
                    }
                    Some(t) => w!(o, "            throw WabiRuntimeError.callFailed(String(describing: {}))", dec(t, "r", 1)),
                    None => w!(o, "            throw WabiRuntimeError.callFailed(\"\")"),
                }
                w!(o, "        }}");
                match ok {
                    Some(t) => w!(o, "        return {}", dec(t, "r", 1)),
                    None => w!(o, "        try r.readNil()"),
                }
            }
        }
        w!(o, "    }}");
        w!(o, "");
    }
    w!(o, "    /// Releases the native object now (otherwise released on deinit).");
    w!(o, "    /// In-flight calls fail, event sequences finish. Idempotent.");
    w!(o, "    public func close() {{");
    w!(o, "        handle?.close()");
    w!(o, "    }}");
    w!(o, "}}");
    o
}
