//! TypeScript emitter (Bun): plain object types (records are interfaces,
//! enums are string unions of the WIT names, variants are discriminated
//! unions `{ tag, value }`), an exception class per error type, the payload
//! codec, one client class per resource (Promise / AbortSignal /
//! AsyncIterable), the host-call registration and the bun:ffi bindings of the
//! ABI. 64-bit integers (handles, ids) are `bigint`, everything smaller `number`.

use crate::abi_table::{self, CTy};
use crate::ir::*;
use crate::names::*;

pub fn emit(m: &Model) -> Vec<(String, String)> {
    let mut files = vec![
        ("types.ts".to_string(), types(m)),
        ("wire_codec.ts".to_string(), codec(m)),
        ("abi_constants.ts".to_string(), constants(m)),
        ("native_abi.ts".to_string(), native_abi(m)),
    ];
    for r in &m.resources {
        files.push((format!("{}.ts", snake(&format!("{}-{}", m.namespace, r.name))), resource(m, r)));
    }
    if m.needs_host_calls() {
        files.push((format!("{}_host.ts", snake(&m.package)), host(m)));
    }
    files
}

const HEADER: &str = "// Generated by wabi-wit-gen from wit/*.wit — DO NOT EDIT.\n/* eslint-disable */\n";

/// Relative, so the same generated code works in any package.
const RUNTIME: &str = "./runtime/index.ts";

fn docs(o: &mut String, d: &Option<String>, ind: &str) {
    if let Some(d) = d {
        w!(o, "{ind}/**");
        for l in d.lines() {
            let l = l.trim_end().replace("*/", "*\\/");
            if l.is_empty() { w!(o, "{ind} *") } else { w!(o, "{ind} * {l}") }
        }
        w!(o, "{ind} */");
    }
}

const KEYWORDS: &[&str] = &[
    "break", "case", "catch", "class", "const", "continue", "debugger", "default", "delete", "do", "else", "enum",
    "export", "extends", "false", "finally", "for", "function", "if", "import", "in", "instanceof", "new", "null",
    "return", "super", "switch", "this", "throw", "true", "try", "typeof", "var", "void", "while", "with", "as",
    "implements", "interface", "let", "package", "private", "protected", "public", "static", "yield", "await",
    "arguments", "eval", "signal",
];

/// Parameter / local identifier (`signal` is reserved for the AbortSignal).
fn ident(s: &str) -> String {
    let c = camel(s);
    if KEYWORDS.contains(&c.as_str()) { format!("{c}_") } else { c }
}

/// Property names may be keywords in TypeScript.
fn prop(s: &str) -> String {
    camel(s)
}

fn tt(t: &Ty) -> String {
    match t {
        Ty::Bool => "boolean".into(),
        Ty::U8 | Ty::U16 | Ty::U32 | Ty::S8 | Ty::S16 | Ty::S32 | Ty::Char | Ty::F32 | Ty::F64 => "number".into(),
        Ty::U64 | Ty::S64 => "bigint".into(),
        Ty::String => "string".into(),
        Ty::Bytes => "Uint8Array".into(),
        Ty::List(t) => format!("{}[]", tt_wrapped(t)),
        Ty::Option(t) => format!("{} | undefined", tt(t)),
        Ty::Tuple(ts) => format!("[{}]", ts.iter().map(tt).collect::<Vec<_>>().join(", ")),
        Ty::Named(n) => pascal(n),
        Ty::Stream(t) => format!("AsyncIterableIterator<{}>", tt(t)),
        Ty::Handle { resource, .. } => sdk_class(resource),
    }
}

/// Element types of arrays need parentheses around unions.
fn tt_wrapped(t: &Ty) -> String {
    match t {
        Ty::Option(_) => format!("({})", tt(t)),
        _ => tt(t),
    }
}

fn enc(t: &Ty, e: &str, d: usize) -> String {
    match t {
        Ty::Bool => format!("w.writeBool({e});"),
        Ty::U8 | Ty::U16 | Ty::U32 | Ty::U64 | Ty::Char => format!("w.writeUint({e});"),
        Ty::S8 | Ty::S16 | Ty::S32 | Ty::S64 => format!("w.writeInt({e});"),
        Ty::F32 => format!("w.writeFloat32({e});"),
        Ty::F64 => format!("w.writeFloat64({e});"),
        Ty::String => format!("w.writeString({e});"),
        Ty::Bytes => format!("w.writeBinary({e});"),
        Ty::List(t) => format!(
            "w.writeArrayHeader({e}.length); for (const x{d} of {e}) {{ {} }}",
            enc(t, &format!("x{d}"), d + 1)
        ),
        Ty::Option(t) => format!(
            "{{ const x{d} = {e}; if (x{d} !== undefined) {{ {} }} else {{ w.writeNil(); }} }}",
            enc(t, &format!("x{d}"), d + 1)
        ),
        Ty::Tuple(ts) => {
            let mut s = format!("w.writeArrayHeader({});", ts.len());
            for (i, t) in ts.iter().enumerate() {
                s += " ";
                s += &enc(t, &format!("{e}[{i}]"), d + 1);
            }
            s
        }
        Ty::Named(n) => format!("WireCodec.write{}(w, {e});", pascal(n)),
        Ty::Stream(_) => unreachable!(),
        // lent for the call, or moved into the core (the SDK object is closed without a drop)
        Ty::Handle { owned: false, .. } => format!("w.writeUint({e}.nativeHandle);"),
        Ty::Handle { owned: true, .. } => format!("w.writeUint({e}.detachNativeHandle());"),
    }
}

fn dec(t: &Ty, r: &str, d: usize) -> String {
    match t {
        Ty::Bool => format!("{r}.readBool()"),
        Ty::U8 => format!("{r}.readUintMax(0xff)"),
        Ty::U16 => format!("{r}.readUintMax(0xffff)"),
        Ty::U32 => format!("{r}.readUintMax(0xffffffff)"),
        Ty::U64 => format!("{r}.readUint64()"),
        Ty::S8 => format!("{r}.readIntRange(-0x80, 0x7f)"),
        Ty::S16 => format!("{r}.readIntRange(-0x8000, 0x7fff)"),
        Ty::S32 => format!("{r}.readIntRange(-0x80000000, 0x7fffffff)"),
        Ty::S64 => format!("{r}.readInt64()"),
        Ty::F32 | Ty::F64 => format!("{r}.readFloat()"),
        Ty::Char => format!("{r}.readUintMax(0x10ffff)"),
        Ty::String => format!("{r}.readString()"),
        Ty::Bytes => format!("{r}.readBinary()"),
        Ty::List(t) => format!("{r}.readList((r{d}) => {})", dec(t, &format!("r{d}"), d + 1)),
        Ty::Option(t) => format!("{r}.readOptional((r{d}) => {})", dec(t, &format!("r{d}"), d + 1)),
        Ty::Tuple(ts) => format!(
            "((): {} => {{ {r}.readTupleHeader({}); return [{}]; }})()",
            tt(&Ty::Tuple(ts.clone())),
            ts.len(),
            ts.iter().map(|t| dec(t, r, d + 1)).collect::<Vec<_>>().join(", ")
        ),
        Ty::Named(n) => format!("WireCodec.read{}({r})", pascal(n)),
        Ty::Stream(_) => unreachable!(),
        // an object the core hands out (only inside a resource class)
        Ty::Handle { resource, .. } => format!("{}.adopt(this.backend, {r}.readUint64())", sdk_class(resource)),
    }
}

fn types(m: &Model) -> String {
    let mut o = String::from(HEADER);
    w!(o, "import {{ WabiException, describeValue }} from \"{RUNTIME}\";");
    w!(o, "");
    for t in &m.types {
        let name = pascal(&t.name);
        docs(&mut o, &t.docs, "");
        match &t.kind {
            TypeKind::Record(fields) => {
                w!(o, "export interface {name} {{");
                for f in fields {
                    docs(&mut o, &f.docs, "  ");
                    match &f.ty {
                        Ty::Option(inner) => w!(o, "  readonly {}?: {};", prop(&f.name), tt(inner)),
                        ty => w!(o, "  readonly {}: {};", prop(&f.name), tt(ty)),
                    }
                }
                w!(o, "}}");
            }
            TypeKind::Enum(cases) => {
                let cs: Vec<String> = cases.iter().map(|c| format!("\"{}\"", c.name)).collect();
                w!(o, "export type {name} = {};", cs.join(" | "));
                w!(o, "");
                w!(o, "/** All cases of `{name}` (declaration order). */");
                w!(o, "export const {name}Values: readonly {name}[] = [{}];", cs.join(", "));
            }
            TypeKind::Variant(cases) => {
                w!(o, "export type {name} =");
                for (i, c) in cases.iter().enumerate() {
                    let end = if i + 1 == cases.len() { ";" } else { "" };
                    let doc = c.docs.as_deref().map(|d| format!("  // {}", d.lines().next().unwrap_or("").trim())).unwrap_or_default();
                    match &c.ty {
                        Some(ty) => w!(o, "  | {{ readonly tag: \"{}\"; readonly value: {} }}{end}{doc}", c.name, tt(ty)),
                        None => w!(o, "  | {{ readonly tag: \"{}\" }}{end}{doc}", c.name),
                    }
                }
            }
        }
        if t.is_error {
            let exc = exception_name(&t.name);
            w!(o, "");
            w!(o, "/** Thrown by SDK calls that fail with a `{}`; host implementations throw it, too. */", t.name);
            w!(o, "export class {exc} extends WabiException {{");
            w!(o, "  constructor(readonly error: {name}) {{");
            w!(o, "    super(describeValue(error));");
            w!(o, "  }}");
            w!(o, "}}");
        }
        w!(o, "");
    }
    o
}

fn codec(m: &Model) -> String {
    let mut o = String::from(HEADER);
    let names: Vec<String> = m.types.iter().map(|t| pascal(&t.name)).collect();
    if !names.is_empty() {
        w!(o, "import type {{ {} }} from \"./types.ts\";", names.join(", "));
    }
    w!(o, "import {{ WabiProtocolException, MsgPackReader, MsgPackWriter }} from \"{RUNTIME}\";");
    w!(o, "");
    w!(o, "/** Payload encoding v1 for all contract types (abi/ABI.md §5). Internal. */");
    w!(o, "export const WireCodec = {{");
    for t in &m.types {
        let name = pascal(&t.name);
        match &t.kind {
            TypeKind::Record(fields) => {
                w!(o, "  write{name}(w: MsgPackWriter, v: {name}): void {{");
                w!(o, "    let n = 0;");
                for f in fields {
                    if matches!(f.ty, Ty::Option(_)) {
                        w!(o, "    if (v.{} !== undefined) n++;", prop(&f.name));
                    } else {
                        w!(o, "    n++;");
                    }
                }
                w!(o, "    w.writeMapHeader(n);");
                for f in fields {
                    let acc = format!("v.{}", prop(&f.name));
                    if let Ty::Option(inner) = &f.ty {
                        w!(o, "    if ({acc} !== undefined) {{ w.writeUint({}); {} }}", f.tag, enc(inner, &acc, 1));
                    } else {
                        w!(o, "    w.writeUint({}); {}", f.tag, enc(&f.ty, &acc, 1));
                    }
                }
                w!(o, "  }},");
                w!(o, "");
                w!(o, "  read{name}(r: MsgPackReader): {name} {{");
                w!(o, "    const n = r.readMapHeader();");
                for f in fields {
                    let inner = match &f.ty { Ty::Option(i) => i.as_ref(), t => t };
                    w!(o, "    let f{}: {} | undefined;", f.tag, tt_wrapped(inner));
                }
                w!(o, "    for (let i = 0; i < n; i++) {{");
                w!(o, "      switch (r.readUint64()) {{");
                for f in fields {
                    let inner = match &f.ty { Ty::Option(i) => i.as_ref(), t => t };
                    if matches!(f.ty, Ty::Option(_)) {
                        w!(o, "        case {}n: f{} = r.tryReadNil() ? undefined : {}; break;", f.tag, f.tag, dec(inner, "r", 1));
                    } else {
                        w!(o, "        case {}n: f{} = {}; break;", f.tag, f.tag, dec(inner, "r", 1));
                    }
                }
                w!(o, "        default: r.skip();");
                w!(o, "      }}");
                w!(o, "    }}");
                for f in fields {
                    if !matches!(f.ty, Ty::Option(_)) {
                        w!(o, "    if (f{} === undefined) throw new WabiProtocolException(\"{}: missing field '{}'\");", f.tag, t.name, f.name);
                    }
                }
                let args: Vec<String> = fields
                    .iter()
                    .map(|f| {
                        if matches!(f.ty, Ty::Option(_)) {
                            format!("...(f{} !== undefined ? {{ {}: f{} }} : {{}})", f.tag, prop(&f.name), f.tag)
                        } else {
                            format!("{}: f{}", prop(&f.name), f.tag)
                        }
                    })
                    .collect();
                w!(o, "    return {{ {} }};", args.join(", "));
                w!(o, "  }},");
            }
            TypeKind::Enum(cases) => {
                w!(o, "  write{name}(w: MsgPackWriter, v: {name}): void {{");
                w!(o, "    switch (v) {{");
                for c in cases {
                    w!(o, "      case \"{}\": w.writeUint({}); return;", c.name, c.tag);
                }
                w!(o, "    }}");
                w!(o, "    throw new TypeError(`unknown {}: ${{String(v)}}`);", t.name);
                w!(o, "  }},");
                w!(o, "");
                w!(o, "  read{name}(r: MsgPackReader): {name} {{");
                w!(o, "    const tag = r.readUint64();");
                w!(o, "    switch (tag) {{");
                for c in cases {
                    w!(o, "      case {}n: return \"{}\";", c.tag, c.name);
                }
                w!(o, "    }}");
                w!(o, "    throw new WabiProtocolException(`unknown case tag ${{tag}} for '{}'`);", t.name);
                w!(o, "  }},");
            }
            TypeKind::Variant(cases) => {
                w!(o, "  write{name}(w: MsgPackWriter, v: {name}): void {{");
                w!(o, "    switch (v.tag) {{");
                for c in cases {
                    match &c.ty {
                        Some(ty) => {
                            w!(o, "      case \"{}\": w.writeArrayHeader(2); w.writeUint({}); {} return;", c.name, c.tag, enc(ty, "v.value", 1));
                        }
                        None => w!(o, "      case \"{}\": w.writeArrayHeader(1); w.writeUint({}); return;", c.name, c.tag),
                    }
                }
                w!(o, "    }}");
                w!(o, "    throw new TypeError(`unknown {} case: ${{String((v as {{ tag?: unknown }}).tag)}}`);", t.name);
                w!(o, "  }},");
                w!(o, "");
                w!(o, "  read{name}(r: MsgPackReader): {name} {{");
                w!(o, "    const n = r.readArrayHeader();");
                w!(o, "    if (n === 0) throw new WabiProtocolException(\"{}: empty variant\");", t.name);
                w!(o, "    const tag = r.readUint64();");
                w!(o, "    let v: {name};");
                w!(o, "    let used: number;");
                w!(o, "    switch (tag) {{");
                for c in cases {
                    match &c.ty {
                        Some(ty) => {
                            w!(o, "      case {}n:", c.tag);
                            w!(o, "        if (n < 2) throw new WabiProtocolException(\"{}.{}: missing payload\");", t.name, c.name);
                            w!(o, "        v = {{ tag: \"{}\", value: {} }}; used = 2; break;", c.name, dec(ty, "r", 1));
                        }
                        None => w!(o, "      case {}n: v = {{ tag: \"{}\" }}; used = 1; break;", c.tag, c.name),
                    }
                }
                w!(o, "      default: throw new WabiProtocolException(`unknown case tag ${{tag}} for '{}'`);", t.name);
                w!(o, "    }}");
                w!(o, "    for (let i = used; i < n; i++) r.skip();");
                w!(o, "    return v;");
                w!(o, "  }},");
            }
        }
        w!(o, "");
    }
    w!(o, "}};");
    o
}

fn constants(m: &Model) -> String {
    let (maj, min, _) = m.version_triple();
    let mut o = String::from(HEADER);
    w!(o, "/** The contract this SDK was generated from. */");
    w!(o, "export const Contract = {{");
    w!(o, "  id: \"{}\",", m.contract_id());
    w!(o, "  package: \"{}:{}\",", m.namespace, m.package);
    w!(o, "  major: {maj},");
    w!(o, "  minor: {min},");
    w!(o, "  /** Library name and prefix of this package's ABI symbols ({}_call_sync, ...). */", m.symbol_prefix());
    w!(o, "  library: \"{}\",", m.symbol_prefix());
    w!(o, "  symbolPrefix: \"{}_\",", m.symbol_prefix());
    w!(o, "}} as const;");
    w!(o, "");
    w!(o, "/** Stable method ids (wit/abi-ids.lock). */");
    w!(o, "export const MethodIds = {{");
    for r in &m.resources {
        for f in r.ctor.iter().chain(&r.methods) {
            w!(o, "  {}{}: {:#06x},", camel(&r.name), pascal(&f.name), f.id);
        }
    }
    for h in &m.imports {
        for f in &h.funcs {
            w!(o, "  {}{}: {:#06x}, // import, answered by the app", camel(&h.name), pascal(&f.name), f.id);
        }
    }
    w!(o, "}} as const;");
    w!(o, "");
    w!(o, "/** ABI {}.{} status codes (abi/wabi_abi.h). */", abi_table::ABI_MAJOR, abi_table::ABI_MINOR);
    w!(o, "export const WabiStatus = {{");
    for (n, v) in abi_table::STATUSES {
        w!(o, "  {}: {v},", camel(&n.to_ascii_lowercase().replace('_', "-")));
    }
    w!(o, "}} as const;");
    w!(o, "");
    w!(o, "/** ABI capability bits (u64, as bigint). */");
    w!(o, "export const WabiCapabilities = {{");
    w!(o, "  abiMajor: {},", abi_table::ABI_MAJOR);
    w!(o, "  /** Minimum ABI minor this package needs (1 if it uses host calls). */");
    w!(o, "  abiMinor: {},", m.required_abi_minor());
    w!(o, "  requiresHostCalls: {},", m.needs_host_calls());
    for (n, bit) in abi_table::CAPABILITIES {
        w!(o, "  {}: 1n << {bit}n,", camel(&n.to_ascii_lowercase().replace('_', "-")));
    }
    w!(o, "}} as const;");
    o
}

/// bun:ffi argument types of one C parameter (by-value aggregates expand).
fn ffi_args(t: CTy) -> &'static str {
    match t {
        CTy::U32 => "FFIType.u32",
        CTy::U64 | CTy::Handle => "FFIType.u64",
        CTy::Status => "FFIType.i32",
        CTy::Bytes | CTy::Buffer => "...AGGREGATE",
        CTy::BufferPtr | CTy::HandlePtr | CTy::VoidPtr | CTy::Callback | CTy::HostHandler | CTy::HostHandler2 | CTy::HostCancel => "FFIType.ptr",
        CTy::Void | CTy::CStr => unreachable!("not a parameter type"),
    }
}

fn ffi_ret(t: CTy) -> &'static str {
    match t {
        CTy::Void => "FFIType.void",
        CTy::U32 => "FFIType.u32",
        CTy::U64 | CTy::Handle => "FFIType.u64",
        CTy::Status => "FFIType.i32",
        CTy::CStr => "FFIType.cstring",
        _ => unreachable!("not a return type"),
    }
}

fn ts_param(t: CTy) -> &'static str {
    match t {
        CTy::U32 | CTy::Status => "number",
        CTy::U64 | CTy::Handle => "bigint",
        CTy::Bytes => "Uint8Array",
        CTy::Buffer | CTy::BufferPtr | CTy::HandlePtr => "BigUint64Array",
        CTy::Callback | CTy::HostHandler | CTy::HostHandler2 | CTy::HostCancel | CTy::VoidPtr => "Pointer | null",
        CTy::Void | CTy::CStr => unreachable!(),
    }
}

fn ts_ret(t: CTy) -> &'static str {
    match t {
        CTy::Void => "void",
        CTy::U32 | CTy::Status => "number",
        CTy::U64 | CTy::Handle => "bigint",
        CTy::CStr => "string",
        _ => unreachable!(),
    }
}

fn call_arg(t: CTy, n: &str) -> String {
    match t {
        CTy::Bytes => format!("...bytesArgs({n})"),
        CTy::Buffer => format!("...bufferArgs({n})"),
        CTy::BufferPtr | CTy::HandlePtr => format!("ptr({n})"),
        _ => n.to_string(),
    }
}

fn native_abi(m: &Model) -> String {
    let prefix = m.symbol_prefix();
    let mut o = String::from(HEADER);
    w!(o, "import {{ dlopen, FFIType, ptr, type Pointer }} from \"bun:ffi\";");
    w!(o, "");
    w!(o, "/**");
    w!(o, " * `wabi_bytes` / `wabi_buffer` ({{ptr, len}}, 16 bytes) are passed BY VALUE. The");
    w!(o, " * SysV x86-64 and AAPCS64 calling conventions pass such an aggregate in two");
    w!(o, " * integer registers, i.e. exactly like two u64 arguments; Win64 passes it by");
    w!(o, " * reference to a caller-owned copy. bun:ffi has no struct type, so both");
    w!(o, " * conventions are spelled out here.");
    w!(o, " */");
    w!(o, "const WIN64 = process.platform === \"win32\";");
    w!(o, "const AGGREGATE = WIN64 ? [FFIType.ptr] : [FFIType.ptr, FFIType.u64];");
    w!(o, "");
    w!(o, "/** `wabi_bytes` borrowed for the duration of one call. */");
    w!(o, "function bytesArgs(data: Uint8Array): unknown[] {{");
    w!(o, "  const p = data.length === 0 ? 0 : ptr(data);");
    w!(o, "  return WIN64 ? [ptr(new BigUint64Array([BigInt(p), BigInt(data.length)]))] : [p, BigInt(data.length)];");
    w!(o, "}}");
    w!(o, "");
    w!(o, "/** `wabi_buffer` from its out-parameter storage `[ptr, len]`. */");
    w!(o, "function bufferArgs(b: BigUint64Array): unknown[] {{");
    w!(o, "  return WIN64 ? [ptr(b)] : [Number(b[0]), b[1]];");
    w!(o, "}}");
    let decl = |o: &mut String, host: bool| {
        for f in abi_table::FUNCTIONS.iter().filter(|f| f.host_call == host) {
            let args: Vec<&str> = f.params.iter().map(|(t, _)| ffi_args(*t)).collect();
            w!(o, "  {}: {{ args: [{}], returns: {} }},", abi_table::symbol(&prefix, f.name), args.join(", "), ffi_ret(f.ret));
        }
    };
    w!(o, "");
    w!(o, "const CORE = {{");
    decl(&mut o, false);
    w!(o, "}} as const;");
    w!(o, "");
    w!(o, "/** ABI 1.1, optional: only cores with WABI_CAP_HOST_CALLS export them. */");
    w!(o, "const HOST = {{");
    decl(&mut o, true);
    w!(o, "}} as const;");
    w!(o, "");
    w!(o, "/**");
    w!(o, " * bun:ffi bindings of the generic Wabi native ABI {}.{} (symbol prefix `{prefix}_`).", abi_table::ABI_MAJOR, abi_table::ABI_MINOR);
    w!(o, " * This list does not grow when WIT functions are added: those are addressed by method id.");
    w!(o, " */");
    w!(o, "export class NativeAbi {{");
    w!(o, "  private readonly core: any;");
    w!(o, "  private readonly host: any;");
    w!(o, "");
    w!(o, "  constructor(path: string) {{");
    w!(o, "    this.core = dlopen(path, CORE as any).symbols;");
    w!(o, "    let host: any;");
    w!(o, "    try {{");
    w!(o, "      host = dlopen(path, HOST as any).symbols;");
    w!(o, "    }} catch {{");
    w!(o, "      host = undefined;");
    w!(o, "    }}");
    w!(o, "    this.host = host;");
    w!(o, "  }}");
    w!(o, "");
    w!(o, "  get hasHostCalls(): boolean {{");
    w!(o, "    return this.host !== undefined;");
    w!(o, "  }}");
    for f in abi_table::FUNCTIONS {
        let ps: Vec<String> = f.params.iter().map(|(t, n)| format!("{n}: {}", ts_param(*t))).collect();
        let args: Vec<String> = f.params.iter().map(|(t, n)| call_arg(*t, n)).collect();
        let target = if f.host_call { "this.host" } else { "this.core" };
        let sym = abi_table::symbol(&prefix, f.name);
        w!(o, "");
        w!(o, "  {}({}): {} {{", f.name, ps.join(", "), ts_ret(f.ret));
        let call = format!("{target}.{sym}({})", args.join(", "));
        match f.ret {
            CTy::Void => w!(o, "    {call};"),
            CTy::CStr => w!(o, "    return String({call});"),
            _ => w!(o, "    return {call};"),
        }
        w!(o, "  }}");
    }
    w!(o, "}}");
    o
}

/// Index of the first parameter from which on all parameters are options:
/// those become optional (`x?: T`), earlier options stay `x: T | undefined`.
fn optional_tail(params: &[(String, Ty)]) -> usize {
    let mut i = params.len();
    while i > 0 && matches!(params[i - 1].1, Ty::Option(_)) {
        i -= 1;
    }
    i
}

fn param_list(params: &[(String, Ty)], tail_optional: bool) -> Vec<String> {
    let tail = if tail_optional { optional_tail(params) } else { params.len() };
    params
        .iter()
        .enumerate()
        .map(|(i, (n, t))| match t {
            Ty::Option(inner) if i >= tail => format!("{}?: {}", ident(n), tt(inner)),
            t => format!("{}: {}", ident(n), tt(t)),
        })
        .collect()
}

fn request(o: &mut String, params: &[(String, Ty)], ind: &str) {
    w!(o, "{ind}const w = new MsgPackWriter();");
    w!(o, "{ind}w.writeArrayHeader({});", params.len());
    for (n, t) in params {
        w!(o, "{ind}{}", enc(t, &ident(n), 1));
    }
}

fn type_imports(m: &Model) -> String {
    let names: Vec<String> = m.types.iter().map(|t| pascal(&t.name)).collect();
    let errors: Vec<String> = m.types.iter().filter(|t| t.is_error).map(|t| exception_name(&t.name)).collect();
    let mut s = String::new();
    if !names.is_empty() {
        s += &format!("import type {{ {} }} from \"./types.ts\";\n", names.join(", "));
    }
    if !errors.is_empty() {
        s += &format!("import {{ {} }} from \"./types.ts\";\n", errors.join(", "));
    }
    s
}

fn resource(m: &Model, r: &Resource) -> String {
    let cls = crate::gen_csharp::class_name(m, r);
    let rid = camel(&r.name);
    let mut o = String::from(HEADER);
    o += &type_imports(m);
    w!(o, "import {{ MethodIds }} from \"./abi_constants.ts\";");
    w!(o, "import {{ WireCodec }} from \"./wire_codec.ts\";");
    for other in r.handle_resources().iter().filter(|n| **n != r.name) {
        w!(o, "import {{ {} }} from \"./{}.ts\";", sdk_class(other), snake(&format!("{}-{other}", m.namespace)));
    }
    w!(o, "import {{ WabiCallFailedException, mapStream, MsgPackReader, MsgPackWriter, NativeBackend, ObjectHandle, type ClientBackend, type NativeObject }} from \"{RUNTIME}\";");
    w!(o, "");
    docs(&mut o, &r.docs, "");
    w!(o, "export class {cls} implements Disposable, NativeObject {{");
    w!(o, "  private readonly backend: ClientBackend;");
    w!(o, "  private readonly handle: ObjectHandle;");
    w!(o, "");
    w!(o, "  /** The object's handle in the core (throws once closed). */");
    w!(o, "  get nativeHandle(): bigint {{");
    w!(o, "    return this.handle.value;");
    w!(o, "  }}");
    w!(o, "");
    w!(o, "  /** Wraps an object the core handed out (used by generated code). */");
    w!(o, "  static adopt(backend: ClientBackend, handle: bigint): {cls} {{");
    w!(o, "    const object = Object.create({cls}.prototype) as {{ backend: ClientBackend; handle: ObjectHandle }};");
    w!(o, "    object.backend = backend;");
    w!(o, "    object.handle = new ObjectHandle(object, backend, handle);");
    w!(o, "    return object as unknown as {cls};");
    w!(o, "  }}");
    w!(o, "");
    w!(o, "  /**");
    w!(o, "   * Gives the handle away (the object moves into the core): this instance is");
    w!(o, "   * closed without a drop (used by generated code).");
    w!(o, "   */");
    w!(o, "  detachNativeHandle(): bigint {{");
    w!(o, "    return this.handle.detach();");
    w!(o, "  }}");
    w!(o, "");
    if let Some(c) = &r.ctor {
        let mut ps = param_list(&c.params, false);
        ps.push("backend: ClientBackend = NativeBackend.shared".into());
        docs(&mut o, &c.docs, "  ");
        w!(o, "  /**");
        w!(o, "   * Uses `NativeBackend.shared` unless another `backend` (component model,");
        w!(o, "   * test double) is given. Throws `WabiIncompatibleLibraryException` if the");
        w!(o, "   * native core is missing or incompatible.");
        w!(o, "   */");
        w!(o, "  constructor({}) {{", ps.join(", "));
        w!(o, "    this.backend = backend;");
        request(&mut o, &c.params, "    ");
        w!(o, "    const r = new MsgPackReader(backend.callSync(0n, MethodIds.{rid}{}, w.bytes()));", pascal(&c.name));
        w!(o, "    this.handle = new ObjectHandle(this, backend, r.readUint64());");
        w!(o, "  }}");
        w!(o, "");
    }
    for f in &r.methods {
        docs(&mut o, &f.docs, "  ");
        let mid = format!("MethodIds.{rid}{}", pascal(&f.name));
        let name = prop(&f.name);
        if let Ret::Value(Ty::Stream(item)) = &f.ret {
            let mut ps = param_list(&f.params, true);
            ps.push("signal?: AbortSignal".into());
            w!(o, "  /**");
            w!(o, "   * The native subscription opens right away (nothing is missed before the first");
            w!(o, "   * `next()`); `break`, `return()` or aborting `signal` stop and release it.");
            w!(o, "   */");
            w!(o, "  {name}({}): AsyncIterableIterator<{}> {{", ps.join(", "), tt(item));
            w!(o, "    const items = this.backend.openStream(() => {{");
            request(&mut o, &f.params, "      ");
            w!(o, "      return new MsgPackReader(this.backend.callSync(this.handle.value, {mid}, w.bytes())).readUint64();");
            w!(o, "    }}, signal);");
            w!(o, "    return mapStream(items, (bytes) => {});", dec(item, "new MsgPackReader(bytes)", 1));
            w!(o, "  }}");
            w!(o, "");
            continue;
        }
        let ok = match &f.ret {
            Ret::Unit | Ret::Result { ok: None, .. } => "void".to_string(),
            Ret::Value(t) | Ret::Result { ok: Some(t), .. } => tt(t),
        };
        if f.is_async {
            let mut ps = param_list(&f.params, true);
            ps.push("signal?: AbortSignal".into());
            w!(o, "  async {name}({}): Promise<{ok}> {{", ps.join(", "));
            request(&mut o, &f.params, "    ");
            w!(o, "    const r = new MsgPackReader(await this.backend.callAsync(this.handle.value, {mid}, w.bytes(), signal));");
        } else {
            let ps = param_list(&f.params, true);
            w!(o, "  {name}({}): {ok} {{", ps.join(", "));
            request(&mut o, &f.params, "    ");
            w!(o, "    const r = new MsgPackReader(this.backend.callSync(this.handle.value, {mid}, w.bytes()));");
        }
        match &f.ret {
            Ret::Unit => w!(o, "    r.readNil();"),
            Ret::Value(t) => w!(o, "    return {};", dec(t, "r", 1)),
            Ret::Result { ok, err } => {
                w!(o, "    if (r.readResultTag() !== 0) {{");
                match err {
                    Some(Ty::Named(n)) if m.types.iter().any(|t| &t.name == n && t.is_error) => {
                        w!(o, "      throw new {}(WireCodec.read{}(r));", exception_name(n), pascal(n))
                    }
                    Some(t) => w!(o, "      throw new WabiCallFailedException({});", dec(t, "r", 1)),
                    None => w!(o, "      throw new WabiCallFailedException(undefined);"),
                }
                w!(o, "    }}");
                match ok {
                    Some(t) => w!(o, "    return {};", dec(t, "r", 1)),
                    None => w!(o, "    r.readNil();"),
                }
            }
        }
        w!(o, "  }}");
        w!(o, "");
    }
    w!(o, "  /** Releases the native object now (otherwise when garbage collected). In-flight calls fail, streams end. Idempotent. */");
    w!(o, "  close(): void {{");
    w!(o, "    this.handle.close();");
    w!(o, "  }}");
    w!(o, "");
    w!(o, "  [Symbol.dispose](): void {{");
    w!(o, "    this.close();");
    w!(o, "  }}");
    w!(o, "}}");
    o
}

fn host_ret(r: &Ret) -> String {
    let t = match r {
        Ret::Unit | Ret::Result { ok: None, .. } => "void".to_string(),
        Ret::Value(t) | Ret::Result { ok: Some(t), .. } => tt(t),
    };
    format!("{t} | Promise<{t}>")
}

/// App-side host calls (ABI 1.2): one interface per imported WIT interface,
/// plus `<Package>Host.register(...)` which decodes requests and encodes answers.
fn host(m: &Model) -> String {
    let cls = format!("{}Host", pascal(&m.package));
    let mut o = String::from(HEADER);
    o += &type_imports(m);
    w!(o, "import {{ WabiStatus, MethodIds }} from \"./abi_constants.ts\";");
    w!(o, "import {{ WireCodec }} from \"./wire_codec.ts\";");
    w!(o, "import {{ WabiCallFailedException, WabiNativeException, WabiProtocolException, MsgPackReader, MsgPackWriter, NativeBackend, type NativeObject }} from \"{RUNTIME}\";");
    for h in &m.imports {
        w!(o, "");
        let note = format!("WIT import `{}`: implemented by the APP, called by the core.\nDomain errors: throw the generated exception. `signal` is aborted when the\ncore no longer waits for the answer.", h.name);
        let d = match &h.docs { Some(d) => format!("{}\n\n{note}", d.trim_end()), None => note };
        docs(&mut o, &Some(d), "");
        w!(o, "export interface {} {{", pascal(&h.name));
        for f in &h.funcs {
            docs(&mut o, &f.docs, "  ");
            let mut ps = param_list(&f.params, false);
            ps.push("signal: AbortSignal".into());
            w!(o, "  {}({}): {};", prop(&f.name), ps.join(", "), host_ret(&f.ret));
        }
        w!(o, "}}");
    }
    let params: Vec<String> = m.imports.iter().map(|h| format!("{}: {}", ident(&h.name), pascal(&h.name))).collect();
    let args: Vec<String> = m.imports.iter().map(|h| ident(&h.name)).collect();
    w!(o, "");
    w!(o, "/** Connects the app's implementations of the WIT imports of {} to the core. */", m.contract_id());
    w!(o, "export const {cls} = {{");
    w!(o, "  /** Call once at startup, before the core needs the app (process-wide). */");
    w!(o, "  register({}, backend: NativeBackend = NativeBackend.shared): void {{", params.join(", "));
    w!(o, "    backend.registerHost((methodId, request, signal) => dispatch({}, methodId, request, signal));", args.join(", "));
    w!(o, "  }},");
    w!(o, "");
    w!(o, "  /** Removes the process-wide registration. */");
    w!(o, "  unregister(backend: NativeBackend = NativeBackend.shared): void {{");
    w!(o, "    backend.unregisterHost();");
    w!(o, "  }},");
    w!(o, "");
    w!(o, "  /**");
    w!(o, "   * Registers the implementations for the calls the core makes on behalf of this");
    w!(o, "   * one instance. They take precedence over the process-wide ones and are");
    w!(o, "   * removed when the instance is closed.");
    w!(o, "   */");
    w!(o, "  registerFor(instance: NativeObject, {}, backend: NativeBackend = NativeBackend.shared): void {{", params.join(", "));
    w!(o, "    backend.registerHost((methodId, request, signal) => dispatch({}, methodId, request, signal), instance.nativeHandle);", args.join(", "));
    w!(o, "  }},");
    w!(o, "");
    w!(o, "  /** Removes the registration of this instance. */");
    w!(o, "  unregisterFor(instance: NativeObject, backend: NativeBackend = NativeBackend.shared): void {{");
    w!(o, "    backend.unregisterHost(instance.nativeHandle);");
    w!(o, "  }},");
    w!(o, "}};");
    w!(o, "");
    w!(o, "async function dispatch({}, methodId: number, request: Uint8Array, signal: AbortSignal): Promise<Uint8Array> {{", params.join(", "));
    w!(o, "  const r = new MsgPackReader(request);");
    w!(o, "  const w = new MsgPackWriter();");
    w!(o, "  switch (methodId) {{");
    for h in &m.imports {
        let target = ident(&h.name);
        for f in &h.funcs {
            w!(o, "    case MethodIds.{}{}: {{", camel(&h.name), pascal(&f.name));
            w!(o, "      r.readTupleHeader({});", f.params.len());
            let mut locals = vec![];
            for (n, t) in &f.params {
                let l = host_local(n);
                w!(o, "      const {l} = {};", dec(t, "r", 1));
                locals.push(l);
            }
            w!(o, "      if (r.remaining !== 0) throw new WabiProtocolException(\"trailing bytes in host call request\");");
            locals.push("signal".into());
            let call = format!("await {target}.{}({})", prop(&f.name), locals.join(", "));
            match &f.ret {
                Ret::Unit => {
                    w!(o, "      {call};");
                    w!(o, "      w.writeNil();");
                }
                Ret::Value(t) => {
                    w!(o, "      const ret_ = {call};");
                    w!(o, "      {}", enc(t, "ret_", 1));
                }
                Ret::Result { ok, err } => {
                    w!(o, "      try {{");
                    match ok {
                        Some(t) => {
                            w!(o, "        const ret_ = {call};");
                            w!(o, "        w.writeArrayHeader(2); w.writeUint(0);");
                            w!(o, "        {}", enc(t, "ret_", 1));
                        }
                        None => {
                            w!(o, "        {call};");
                            w!(o, "        w.writeArrayHeader(2); w.writeUint(0); w.writeNil();");
                        }
                    }
                    w!(o, "      }} catch (e) {{");
                    match err {
                        Some(Ty::Named(n)) if m.types.iter().any(|t| &t.name == n && t.is_error) => {
                            w!(o, "        if (!(e instanceof {})) throw e;", exception_name(n));
                            w!(o, "        w.writeArrayHeader(2); w.writeUint(1);");
                            w!(o, "        WireCodec.write{}(w, e.error);", pascal(n));
                        }
                        Some(t) => {
                            w!(o, "        if (!(e instanceof WabiCallFailedException)) throw e;");
                            w!(o, "        w.writeArrayHeader(2); w.writeUint(1);");
                            w!(o, "        {}", enc(t, &format!("(e.error as {})", tt(t)), 1));
                        }
                        None => {
                            w!(o, "        if (!(e instanceof WabiCallFailedException)) throw e;");
                            w!(o, "        w.writeArrayHeader(2); w.writeUint(1); w.writeNil();");
                        }
                    }
                    w!(o, "      }}");
                }
            }
            w!(o, "      return w.bytes();");
            w!(o, "    }}");
        }
    }
    w!(o, "  }}");
    w!(o, "  throw new WabiNativeException(WabiStatus.errUnknownMethod, `unknown host method 0x${{methodId.toString(16)}}`);");
    w!(o, "}}");
    o
}
