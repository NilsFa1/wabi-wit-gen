                s.push_str(&format!("### {lang}\n\nUse the generated [build helper](core-{lang}/build-native.sh):\n\n```sh\nbash core-{lang}/build-native.sh <core-project-directory> host\n```\n\nWith scaffolding and the default core destination, use `core-{lang}` as\nthe project directory. Implement the starter methods before calling them.\nThe helper writes libraries to `native/`; it can also build platform targets\nincluding `ios` (producing `native/apple/{module}.xcframework`).\n\n"));
