//! Ready-to-use packages around the generated code.
//!
//! * Java: `build.sh` producing the jars (desktop, Android) and the JNI shim.
//! * Swift: a SwiftPM package (manifest, C module with the headers).
//! * TypeScript: `package.json` and `index.ts` for Bun.
//! * Dart: a complete package (`pubspec.yaml`, `hook/build.dart`, library file) whose
//!   build hook bundles the core from `<out>/native` (Flutter: `flutter pub add
//!   <name> --path <out>/dart`, nothing else to configure).
//! * C#: an SDK-style project that `dotnet pack`s into a NuGet package with the
//!   core libraries from `<out>/native` under `runtimes/<rid>/native/`.
//! * Cores: `build-native.sh` for Rust and Go cores, writing exactly that
//!   `<out>/native` layout for every platform.

use crate::{ir::Model, runtime};

const RUST_SCRIPT: &str = include_str!("../templates/build-native-rust.sh");
const GO_SCRIPT: &str = include_str!("../templates/build-native-go.sh");

/// Dart package name and library file: the symbol prefix (`demo_greeter`).
pub fn dart_package_name(m: &Model) -> String {
    m.symbol_prefix()
}

/// Package files around `lib/src/generated` (`generated` = the emitted SDK file names).
pub fn dart_package(m: &Model, generated: &[String]) -> Vec<(String, String)> {
    let name = dart_package_name(m);
    let pubspec = format!(
        "# Generated by wabi-wit-gen — DO NOT EDIT (regenerated on every run).\n\
         name: {name}\n\
         description: >-\n  SDK for {contract}, generated by wabi-wit-gen. The native core comes from\n  ../native (see ../README.md) or the app's hooks.user_defines.{name} (library, prebuilt_dir, release_url).\n\
         version: {version}\n\
         publish_to: none\n\
         \n\
         environment:\n  sdk: \">=3.10.0 <4.0.0\" # native assets (hook/build.dart)\n\
         \n\
         dependencies:\n  code_assets: ^2.1.0\n  crypto: ^3.0.6\n  ffi: ^2.1.0\n  hooks: ^2.2.0\n",
        contract = m.contract_id(),
        version = m.version,
    );
    let hook = format!(
        "// Generated by wabi-wit-gen — DO NOT EDIT.\n\
         // Dart native assets: bundles the core library for the target platform\n\
         // (default: ../native, see lib/src/generated/build_hook.dart).\n\
         import 'package:{name}/src/generated/build_hook.dart';\n\nvoid main(List<String> args) => buildHook(args);\n"
    );
    let mut lib = format!("// Generated by wabi-wit-gen — DO NOT EDIT.\n/// SDK for {} (generated by wabi-wit-gen).\nlibrary;\n\n", m.contract_id());
    lib.push_str("export 'src/generated/abi_constants.dart' show Contract;\n");
    let internal = ["abi_constants.dart", "wire_codec.dart", "native_abi.dart", "build_hook.dart"];
    for f in generated.iter().filter(|f| f.ends_with(".dart") && !f.contains('/') && !internal.contains(&f.as_str())) {
        lib.push_str(&format!("export 'src/generated/{f}';\n"));
    }
    lib.push_str("export 'src/generated/runtime/backend.dart' show NativeObject;\n");
    lib.push_str("export 'src/generated/runtime/cancellation.dart';\n");
    lib.push_str("export 'src/generated/runtime/errors.dart';\n");
    lib.push_str("export 'src/generated/runtime/native_backend.dart' show CoreInfo, NativeBackend;\n");
    vec![
        ("pubspec.yaml".into(), pubspec),
        ("hook/build.dart".into(), hook),
        (format!("lib/{name}.dart"), lib),
    ]
}

/// `<out>/native` subdirectory, file and NuGet runtime identifiers of every shipped library.
fn natives(m: &Model) -> Vec<(String, Vec<&'static str>)> {
    let p = m.symbol_prefix();
    let mut v = vec![
        (format!("linux-x64/lib{p}.so"), vec!["linux-x64"]),
        (format!("linux-arm64/lib{p}.so"), vec!["linux-arm64"]),
        (format!("windows-x64/{p}.dll"), vec!["win-x64"]),
        (format!("macos/lib{p}.dylib"), vec!["osx-arm64", "osx-x64"]), // universal
    ];
    for (abi, rid) in [("arm64-v8a", "android-arm64"), ("armeabi-v7a", "android-arm"), ("x86_64", "android-x64"), ("x86", "android-x86")] {
        v.push((format!("android/jniLibs/{abi}/lib{p}.so"), vec![rid]));
    }
    v
}

/// SDK-style C# project: `dotnet pack` -> NuGet package incl. the native core.
pub fn csharp_project(m: &Model) -> (String, String) {
    let ns = crate::gen_csharp::cs_ns(m);
    let mut packed = String::new();
    for (file, rids) in natives(m) {
        for rid in rids {
            packed.push_str(&format!(
                "    <None Include=\"../native/{file}\" Pack=\"true\" PackagePath=\"runtimes/{rid}/native/\" Visible=\"false\" Condition=\"Exists('../native/{file}')\" />\n"
            ));
        }
    }
    let p = m.symbol_prefix();
    let text = format!(
        r#"<Project Sdk="Microsoft.NET.Sdk">
  <!--
    Generated by wabi-wit-gen — DO NOT EDIT (regenerated on every run).
    C# SDK for {contract}: the generated code and its runtime (namespace {ns}.Runtime).

      dotnet pack -c Release        NuGet package {ns}.{version}.nupkg incl. the native core from
                                    ../native (see ../README.md) under runtimes/<rid>/native/
      <ProjectReference Include="…/{ns}.csproj" />   during development: the library of this
                                    machine from ../native is copied next to the app
  -->
  <PropertyGroup>
    <TargetFramework>net8.0</TargetFramework>
    <Nullable>enable</Nullable>
    <AllowUnsafeBlocks>true</AllowUnsafeBlocks>
    <LangVersion>12</LangVersion>
    <RootNamespace>{ns}</RootNamespace>
    <AssemblyName>{ns}</AssemblyName>
    <PackageId>{ns}</PackageId>
    <Version>{version}</Version>
    <Description>SDK for {contract} (generated by wabi-wit-gen); native core {p} included per platform.</Description>
    <IsPackable>true</IsPackable>
    <EnableDefaultItems>false</EnableDefaultItems>
  </PropertyGroup>
  <ItemGroup>
    <Compile Include="**/*.cs" Exclude="bin/**;obj/**" />
  </ItemGroup>
  <ItemGroup Label="native core in the NuGet package">
{packed}  </ItemGroup>
  <ItemGroup Label="native core for project references (this machine)">
    <None Include="../native/linux-x64/lib{p}.so" Link="lib{p}.so" CopyToOutputDirectory="PreserveNewest" Pack="false" Visible="false" Condition="$([MSBuild]::IsOSPlatform('Linux')) And '$([System.Runtime.InteropServices.RuntimeInformation]::OSArchitecture)' == 'X64' And Exists('../native/linux-x64/lib{p}.so')" />
    <None Include="../native/linux-arm64/lib{p}.so" Link="lib{p}.so" CopyToOutputDirectory="PreserveNewest" Pack="false" Visible="false" Condition="$([MSBuild]::IsOSPlatform('Linux')) And '$([System.Runtime.InteropServices.RuntimeInformation]::OSArchitecture)' == 'Arm64' And Exists('../native/linux-arm64/lib{p}.so')" />
    <None Include="../native/macos/lib{p}.dylib" Link="lib{p}.dylib" CopyToOutputDirectory="PreserveNewest" Pack="false" Visible="false" Condition="$([MSBuild]::IsOSPlatform('OSX')) And Exists('../native/macos/lib{p}.dylib')" />
    <None Include="../native/windows-x64/{p}.dll" Link="{p}.dll" CopyToOutputDirectory="PreserveNewest" Pack="false" Visible="false" Condition="$([MSBuild]::IsOSPlatform('Windows')) And Exists('../native/windows-x64/{p}.dll')" />
  </ItemGroup>
</Project>
"#,
        contract = m.contract_id(),
        version = m.version,
    );
    (format!("{ns}.csproj"), text)
}

/// `build-native.sh` for a Rust or Go core of `m`.
pub fn build_script(core: &str, m: &Model) -> Option<String> {
    let template = match core {
        "rust" => RUST_SCRIPT,
        "go" => GO_SCRIPT,
        _ => return None,
    };
    // xcframework name = Swift module; its C module is C<xcf> (as in the generated Swift code)
    let xcf = swift_module(m);
    Some(template.replace("@LIB@", &m.symbol_prefix()).replace("@XCF@", &xcf).replace("@CONTRACT@", &m.contract_id()))
}

// ------------------------------------------------------------------- Java

/// `build.sh` next to the Java sources: jars for desktop and Android, JNI shim for the host.
pub fn java_build_script(m: &Model) -> String {
    include_str!("../templates/build-java.sh")
        .replace("@CONTRACT@", &m.contract_id())
        .replace("@JAR@", &m.symbol_prefix().replace('_', "-"))
        .replace("@JNI@", &crate::runtime::jni_library(m))
}

// ------------------------------------------------------------------ Swift

/// Swift module (and SwiftPM package) of the SDK: `demo:greeter` -> `DemoGreeter`.
pub fn swift_module(m: &Model) -> String {
    format!("{}{}", crate::names::pascal(&m.namespace), crate::names::pascal(&m.package))
}

/// Package files around `Sources/<Module>` (the generated code) and
/// `Sources/C<Module>` (the headers): manifest, module map, umbrella header.
pub fn swift_package(m: &Model) -> Vec<(String, String)> {
    let module = swift_module(m);
    let c = crate::runtime::swift_c_module(m);
    let p = m.symbol_prefix();
    let manifest = format!(
        "// swift-tools-version:5.9\n\
         // Generated by wabi-wit-gen — DO NOT EDIT (regenerated on every run).\n\
         // Swift SDK for {contract}: the generated code and its runtime (Sources/{module}),\n\
         // linked against any core that implements the Wabi native ABI as lib{p}.\n\
         //\n\
         // macOS/Linux: `swift build -Xlinker -L<dir with lib{p}>` in the package that uses this one.\n\
         // iOS: replace the system library by a compatible xcframework (see ../../README.md):\n\
         //      .binaryTarget(name: \"{c}\", path: \"../../native/apple/{module}.xcframework\")\n\
         import PackageDescription\n\n\
         let package = Package(\n    name: \"{module}\",\n    platforms: [.macOS(.v12), .iOS(.v15)],\n    products: [\n        .library(name: \"{module}\", targets: [\"{module}\"]),\n    ],\n    targets: [\n        .systemLibrary(name: \"{c}\", path: \"Sources/{c}\"),\n        .target(name: \"{module}\", dependencies: [\"{c}\"], path: \"Sources/{module}\"),\n    ]\n)\n",
        contract = m.contract_id(),
    );
    let modulemap = format!("module {c} [system] {{\n    header \"shim.h\"\n    link \"{p}\"\n    export *\n}}\n");
    let shim = format!(
        "// C view of the native ABI for the Swift SDK (generated by wabi-wit-gen — DO NOT EDIT).\n#include \"wabi_abi.h\"\n#include \"{p}.h\"\n"
    );
    vec![
        ("Package.swift".into(), manifest),
        (format!("Sources/{c}/module.modulemap"), modulemap),
        (format!("Sources/{c}/shim.h"), shim),
    ]
}

// ------------------------------------------------------------- TypeScript

/// npm-style name of the TypeScript package: `demo:greeter` -> `demo-greeter`.
pub fn ts_package_name(m: &Model) -> String {
    m.symbol_prefix().replace('_', "-")
}

/// Package files around the generated TypeScript (`generated` = the emitted file names).
pub fn ts_package(m: &Model, generated: &[String]) -> Vec<(String, String)> {
    let name = ts_package_name(m);
    let package = format!(
        "{{\n  \"name\": \"{name}\",\n  \"version\": \"{version}\",\n  \"description\": \"SDK for {contract} (generated by wabi-wit-gen) for Bun; loads the native core through bun:ffi.\",\n  \"type\": \"module\",\n  \"module\": \"index.ts\",\n  \"exports\": {{\n    \".\": \"./index.ts\"\n  }},\n  \"engines\": {{\n    \"bun\": \">=1.4.0\"\n  }}\n}}\n",
        version = m.version,
        contract = m.contract_id(),
    );
    let mut index = format!(
        "// Generated by wabi-wit-gen — DO NOT EDIT.\n/**\n * SDK for {} (generated by wabi-wit-gen) for Bun.\n * Library lookup: `WABI_NATIVE_LIB`, else the OS loader's search path.\n */\n",
        m.contract_id()
    );
    let internal = ["abi_constants.ts", "wire_codec.ts", "native_abi.ts"];
    for f in generated.iter().filter(|f| f.ends_with(".ts") && !f.contains('/') && !internal.contains(&f.as_str())) {
        index.push_str(&format!("export * from \"./{f}\";\n"));
    }
    index.push_str("export { Contract } from \"./abi_constants.ts\";\n");
    index.push_str(
        "export {\n  CoreInfo,\n  NativeBackend,\n  WabiCallFailedException,\n  WabiCancelledException,\n  WabiClosedException,\n  WabiException,\n  WabiIncompatibleLibraryException,\n  WabiNativeException,\n  WabiProtocolException,\n  type ClientBackend,\n  type NativeObject,\n} from \"./runtime/index.ts\";\n",
    );
    vec![("package.json".into(), package), ("index.ts".into(), index)]
}

